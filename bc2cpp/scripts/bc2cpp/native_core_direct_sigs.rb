# frozen_string_literal: true

# Writes sig/native/core_direct.rbs from the NativeCoreDirect tables (ENTRIES and KERNEL_ENTRIES), which stay the source
# of truth for each row's arity and argument shape. Run with --check to fail when the committed file is stale.
#
#   ruby scripts/bc2cpp/native_core_direct_sigs.rb          # rewrite the file
#   ruby scripts/bc2cpp/native_core_direct_sigs.rb --check  # exit 1 if it differs
require_relative '../../tools/bc2cpp/native_core_direct'

module NativeCoreDirectSigs
  PATH = File.expand_path('../../sig/native/core_direct.rbs', __dir__)

  # The RBS type of the argument at position 0 for each non-trivial argument shape; every other position is untyped.
  ARG_TYPES = { nil_or_string: 'String?' }.freeze

  module_function

  def rows
    NativeCoreDirect::ENTRIES + NativeCoreDirect::KERNEL_ENTRIES
  end

  def overload(row)
    params = Array.new(row.arity) do |index|
      index.zero? ? ARG_TYPES.fetch(row.arg, 'untyped') : 'untyped'
    end
    params = Array.new(row.arity, 'untyped') if row.arg == :none
    "(#{params.join(', ')}) -> untyped"
  end

  def render
    lines = ['# Generated by scripts/bc2cpp/native_core_direct_sigs.rb from NativeCoreDirect (tools/bc2cpp/native_core_direct.rb).',
             '# Do not edit; change the table and rerun the generator. Returns are untyped here: the result kinds live in core_results.rbs.']
    rows.group_by(&:owner).sort.each do |owner, owner_rows|
      keyword = owner == 'Kernel' ? 'module' : 'class'
      lines << ''
      lines << "#{keyword} #{owner}"
      owner_rows.group_by(&:name).sort.each do |name, overloads|
        sigs = overloads.sort_by(&:arity).map { |row| overload(row) }
        lines << "  def #{name}: #{sigs.join(' | ')}"
      end
      lines << 'end'
    end
    "#{lines.join("\n")}\n"
  end
end

if $PROGRAM_NAME == __FILE__
  text = NativeCoreDirectSigs.render
  if ARGV.include?('--check')
    current = File.exist?(NativeCoreDirectSigs::PATH) ? File.read(NativeCoreDirectSigs::PATH) : nil
    abort "bc2cpp: #{NativeCoreDirectSigs::PATH} is stale; run scripts/bc2cpp/native_core_direct_sigs.rb" unless current == text
    puts 'ok: core_direct.rbs matches NativeCoreDirect'
  else
    File.write(NativeCoreDirectSigs::PATH, text)
    puts "wrote #{NativeCoreDirectSigs::PATH}"
  end
end
