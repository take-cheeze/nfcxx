# frozen_string_literal: true

# Writes generated/bc2cpp/rgss_direct.rbs from NativeDirect::GENERATED, the RGSS direct entry points. The table
# stays the source of truth for each binding's argument kinds; this file is derived from it. Run with --check to fail
# when the committed file is stale.
#
#   ruby scripts/bc2cpp/native_rgss_direct_sigs.rb          # rewrite the file
#   ruby scripts/bc2cpp/native_rgss_direct_sigs.rb --check  # exit 1 if it differs
require_relative '../../tools/bc2cpp/native_direct_table'

module NativeRgssDirectSigs
  PATH = File.expand_path('../../generated/bc2cpp/rgss_direct.rbs', __dir__)

  # RBS type for each argument kind in NativeDirect::GENERATED. :value is an mrb_value whose class the table does not
  # record, so it stays untyped.
  # :str and :cstr are both passed as a string (cstr is a NUL-terminated C string).
  KIND_TYPES = { int: 'Integer', float: 'Float', bool: 'bool', str: 'String', cstr: 'String', value: 'untyped' }.freeze

  module_function

  def render
    lines = ['# Generated by scripts/bc2cpp/native_rgss_direct_sigs.rb from NativeDirect::GENERATED (tools/bc2cpp/native_direct_table.rb).',
             '# Do not edit; change the table (scripts/native/binding_split.rb) and rerun the generator. Returns are untyped',
             '# here: the result kinds live in declarations.rbs#rgss_results.']
    by_class = Hash.new { |h, k| h[k] = [] }
    NativeDirect::GENERATED.each do |name, owners|
      owners.each do |owner, (_function, kinds)|
        singleton = owner.end_with?('.singleton')
        klass = singleton ? owner.delete_suffix('.singleton') : owner
        params = kinds.map { |kind| KIND_TYPES.fetch(kind) }
        by_class[klass] << "  def #{singleton ? 'self.' : ''}#{name}: (#{params.join(', ')}) -> untyped"
      end
    end
    by_class.sort.each do |klass, defs|
      lines << ''
      lines << "class #{klass}"
      lines.concat(defs.sort)
      lines << 'end'
    end
    "#{lines.join("\n")}\n"
  end
end

if $PROGRAM_NAME == __FILE__
  text = NativeRgssDirectSigs.render
  if ARGV.include?('--check')
    current = File.exist?(NativeRgssDirectSigs::PATH) ? File.read(NativeRgssDirectSigs::PATH) : nil
    abort "bc2cpp: #{NativeRgssDirectSigs::PATH} is stale; run scripts/bc2cpp/native_rgss_direct_sigs.rb" unless current == text
    puts 'ok: rgss_direct.rbs matches NativeDirect::GENERATED'
  else
    File.write(NativeRgssDirectSigs::PATH, text)
    puts "wrote #{NativeRgssDirectSigs::PATH}"
  end
end
