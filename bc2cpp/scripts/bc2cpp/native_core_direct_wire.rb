# frozen_string_literal: true

# Writes tools/bc2cpp/native_core_direct_generated.rb: the core direct-call entries for the frame-free candidates the
# clang producer reports (tools/bc2cpp/native_core_candidates.rb), so a call site can call the mruby function directly.
#
#   clang -fsyntax-only -Xclang -ast-dump=json <flags> 3rd/mruby/src/array.c |
#     ruby tools/bc2cpp/native_core_candidates.rb 3rd/mruby/src/array.c > cand-array.json
#   ruby scripts/bc2cpp/native_core_direct_wire.rb 3rd/mruby/src/array.c=cand-array.json ... [--check]
#
# A row is taken when it is frame-free and defined in its unit, its owner is one the guards cover (Array, String,
# Integer), its aspec is MRB_ARGS_NONE, and no hand-written entry already names that owner and method. Each row's body
# text is pinned in the entry (NativeCoreDirect.audit compares it with the source on every compile), so an edit to the
# function drops the entry rather than leaving a stale call. A function with no MRB_API declaration gets an extern "C"
# prototype in a helper; its signature is the one the pinned body text has.
#
# --check fails when the committed file differs from what this generator writes.
require 'json'
require_relative '../../tools/bc2cpp/native_core_direct'

module NativeCoreDirectWire
  OWNERS = %w[Array String Integer].freeze
  OUT = File.expand_path('../../tools/bc2cpp/native_core_direct_generated.rb', __dir__)
  INCLUDE = File.expand_path('../../3rd/mruby/include', __dir__)

  module_function

  # The MRB_API header declaring `function`, or nil when no public header declares it.
  def public_header(function)
    Dir[File.join(INCLUDE, '**', '*.h')].find do |header|
      File.read(header, encoding: 'UTF-8').match?(/MRB_API[^;]*\b#{Regexp.escape(function)}\s*\(/)
    end
  end

  # [owner, name, function, source, body] for every row that qualifies, in a stable order.
  def rows(pairs)
    hand = NativeCoreDirect::HAND_ENTRIES.map { |e| [e.owner, e.name] }.to_set
    pairs.flat_map do |source, candidates|
      candidates.filter_map do |c|
        # A static function links nowhere from a generated call site, so only external linkage is wired.
        next unless c['frame_free'] && c['external'] && OWNERS.include?(c['owner']) && c['aspec'] == 'MRB_ARGS_NONE()' && c['name']
        next if hand.include?([c['owner'], c['name']])
        # The audit matches registrations by identifier name; an operator token maps through OPSYM_TO_RUBY.
        next unless c['name'].match?(/\A\w+[?!]?\z/)

        body = NativeCoreDirect.function_body(source, c['function'])
        # frame_free is judged on this build's preprocessing, so a body with conditional compilation is not wired.
        next if body.nil? || body.match?(/^\s*#\s*(if|ifdef|ifndef|elif|else|endif)\b/)

        [c['owner'], c['name'], c['function'], source, body]
      end
    end.sort_by { |owner, name, function, *| [owner, name, function] }
  end

  def helper_name(function)
    "bc2cpp_#{function}"
  end

  def entry_lines(owner, name, function, body, header)
    call = header ? "#{function}(M, recv)" : "#{helper_name(function)}(M, recv)"
    apis = header ? "[%w[#{header.delete_prefix("#{INCLUDE}/")} #{function}]]" : '[]'
    text = <<~RUBY
      Entry.new(name: #{name.inspect}, owner: #{owner.inspect}, arity: 0, arg: :none, aspec: 'MRB_ARGS_NONE()',
                expression: #{call.inspect}#{header ? '' : ", helper: #{helper_name(function).inspect}"},
                apis: #{apis},
                checks: [[#{function.inspect}, <<~'C', :exact]]),
    RUBY
    text + body.lines.map { |l| "                  #{l}" }.join.sub(/\n?\z/, "\n") + "              C\n"
  end

  def helper_text(function)
    <<~CPP
      extern "C" mrb_value #{function}(mrb_state*, mrb_value);
      static inline mrb_value #{helper_name(function)}(mrb_state* M, mrb_value self) {
        return #{function}(M, self);
      }
    CPP
  end

  def render(pairs)
    selected = rows(pairs)
    headers = {}
    entries = selected.map do |owner, name, function, _source, body|
      headers[function] = public_header(function)
      entry_lines(owner, name, function, body, headers[function])
    end
    helpers = selected.map { |*, function, _s, _b| function }.uniq.reject { |f| headers[f] }
    helper_defs = helpers.map { |f| "    #{helper_name(f).inspect} => <<~'CPP',\n#{helper_text(f).lines.map { |l| "      #{l}" }.join}    CPP\n" }

    out = +"# frozen_string_literal: true\n\n"
    out << "# Generated by scripts/bc2cpp/native_core_direct_wire.rb from the clang candidates (ADR 0257). Do not edit;\n"
    out << "# change the generator or the audited hand entries and rerun it.\n"
    out << "module NativeCoreDirect\n"
    out << "  GENERATED_ENTRIES = [\n" << entries.map { |e| "    " + e.lines.join("    ") }.join << "  ].freeze\n\n"
    out << "  GENERATED_HELPERS = {\n" << helper_defs.join << "  }.freeze\n"
    out << "end\n"
    out
  end

  def run(argv)
    check = argv.delete('--check')
    pairs = argv.map do |arg|
      source, json = arg.split('=', 2)
      abort "expected SOURCE=candidates.json: #{arg}" unless json
      [File.expand_path(source, Dir.pwd), JSON.parse(File.read(json))]
    end
    text = render(pairs)
    if check
      current = File.exist?(OUT) ? File.read(OUT, encoding: 'UTF-8') : nil
      if current == text
        puts 'native_core_direct_wire: generated file is fresh'
        exit 0
      end
      warn 'native_core_direct_wire: stale: run scripts/bc2cpp/native_core_direct_wire.rb SOURCE=candidates.json ...'
      exit 1
    end
    File.write(OUT, text)
    puts "wrote #{OUT} (#{text.scan('Entry.new(').size} entries)"
  end
end

NativeCoreDirectWire.run(ARGV) if $PROGRAM_NAME == __FILE__
