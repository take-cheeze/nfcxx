# frozen_string_literal: true

# BC2CPP_ENTRY: the host-callable entry header, `<OUT_SYMBOL>_entry.h` (docs/bc2cpp-entry-points.md).
#
# A host (scripts/bc2cpp/trace_host.cxx, app/psp/main.cxx, app/wio/src/maix_game_main.cxx) drives the game through a
# few methods every frame (`RPG2k#main_loop`, `#current_scene_name`). Called with mrb_funcall they go through method
# lookup, a pushed call frame and the registered wrapper. For each declared entry point (ENTRY_POINTS, or
# BC2CPP_ENTRY_POINTS) this header defines `bc2cpp_entry_<Owner>_<name>(M, self, args...)` with mrb_funcall's
# contract, which calls the compiled `_impl` directly when the generator proved that is what the dispatch would run:
#   - the compiled entry is the plain forwarder `return <impl>(M, self, args...)`: no Fiber hand-off, no core block
#     guard, no resumable step function, no optional/rest/keyword/block parameters (compiles_clean? as well);
#   - public, with the declared argument count;
#   - in the closed world, nothing can put another body in front of it on the owner: the name is not installed,
#     aliased or undefined at run time, the owner has no prepended or unknown mixin, and the owner has exactly one
#     definition of the name;
# and, at run time, the receiver's class (its singleton class, when it has one) is exactly the owner. Any other
# receiver, and every entry the generator could not prove, takes mrb_funcall.
#
# The direct call keeps mrb_funcall's error contract (vm.c funcall_with_block_m): outside any protected region (no
# M->jmp) a raise is caught, M->exc holds the exception and the exception object is returned; inside one, it
# propagates. It does not push a call frame, so the entry method has no frame of its own in an exception's backtrace.
module EntryHeader
  # Owner#name/argc of the methods hosts call. Override with BC2CPP_ENTRY_POINTS ("Owner#name/argc ...").
  ENTRY_POINTS = %w[RPG2k#main_loop/0 RPG2k#start/0 RPG2k#current_scene_name/0].freeze

  Entry = Struct.new(:owner, :name, :argc)

  def self.entry_points(spec = ENV.fetch('BC2CPP_ENTRY_POINTS', nil))
    (spec ? spec.split : ENTRY_POINTS).map do |item|
      m = item.match(%r{\A([A-Z]\w*(?:::[A-Z]\w*)*)#([^/\s]+)/(\d+)\z}) or raise ArgumentError, "BC2CPP_ENTRY_POINTS: bad entry #{item.inspect}"
      Entry.new(m[1], m[2], m[3].to_i)
    end
  end

  SUPPORT = <<~CPP
    #ifndef BC2CPP_ENTRY_SUPPORT
    #define BC2CPP_ENTRY_SUPPORT 1
    #include <mruby/class.h>
    #include <mruby/error.h>
    #include <mruby/variable.h>
    // The class at `path` ("A::B"), or NULL when a segment is not a defined class or module. No raise.
    static inline struct RClass* bc2cpp_entry_class(mrb_state* M, const char* path) {
      struct RClass* c = M->object_class;
      const char* p = path;
      while (*p) {
        const char* end = p;
        while (*end && *end != ':') ++end;
        mrb_sym sym = mrb_intern(M, p, (size_t)(end - p));
        if (!mrb_const_defined_at(M, mrb_obj_value(c), sym)) return NULL;
        mrb_value v = mrb_const_get(M, mrb_obj_value(c), sym);
        if (!mrb_class_p(v) && !mrb_module_p(v)) return NULL;
        c = mrb_class_ptr(v);
        p = *end ? end + 2 : end;
      }
      return c;
    }
    // mrb_funcall's contract for a direct call (vm.c funcall_with_block_m): the arena is restored and the result
    // kept; with no protected region active a raise is caught, left in M->exc, and the exception object returned.
    template <class F>
    static inline mrb_value bc2cpp_entry_call(mrb_state* M, mrb_value self, F&& body) {
      if (M->jmp) {
        int ai = mrb_gc_arena_save(M);
        mrb_gc_protect(M, self);
        mrb_value v = body();
        mrb_gc_arena_restore(M, ai);
        mrb_gc_protect(M, v);
        return v;
      }
      struct Ctx { F* body; } ctx = { &body };
      mrb_bool error = FALSE;
      M->exc = NULL;
      mrb_gc_protect(M, self);
      mrb_value v = mrb_protect_error(M, [](mrb_state*, void* ud) -> mrb_value {
        return (*static_cast<Ctx*>(ud)->body)();
      }, &ctx, &error);
      // mrb_protect_error clears M->exc; mrb_funcall leaves the exception there.
      if (error) M->exc = mrb_obj_ptr(v);
      return v;
    }
    #endif
  CPP
end

class CodeGen
  # The text of `<symbol>_entry.h` for the entry points this unit compiles.
  def emit_entry_header(compiled, symbol)
    entries = EntryHeader.entry_points.select { |e| compiled.any? { |m| m[:owner] == e.owner } }
    out = String.new
    out << "// #{symbol}_entry.h -- generated by tools/bc2cpp (codegen_entry_header.rb); see docs/bc2cpp-entry-points.md.\n"
    out << "// bc2cpp_entry_<Owner>_<name>(M, self, args...) calls the method as mrb_funcall would: the compiled _impl\n"
    out << "// directly where BC2CPP_ENTRY_<Owner>_<name> is 1, by name where it is 0.\n"
    out << "#pragma once\n#include <mruby.h>\n"
    out << EntryHeader::SUPPORT
    entries.each do |e|
      m = compiled.find { |c| c[:owner] == e.owner && c[:name] == e.name && !c[:unsupported] }
      why = m ? entry_direct_refusal(m, e) : 'not compiled'
      out << "\n" << entry_header_function(e, m, why)
    end
    out
  end

  private

  # nil when calling `m`'s _impl is what dispatching `e` on an exact `e.owner` receiver runs, else why not.
  def entry_direct_refusal(m, e)
    return 'no closed world' unless @closed_world
    return 'not public' unless m[:visibility] == :public
    return "argc #{m[:arity]}, declared #{e.argc}" unless m[:arity] == e.argc
    return 'not compiled clean' unless m[:label] && compiles_clean?(m[:label])
    return 'impl takes typed or extra parameters' unless decl_line(m) == entry_plain_decl(m[:impl], e.argc)
    return 'entry is not a plain forwarder (guard, hand-off or argument decoding)' unless entry_plain_forwarder?(m, e.argc)
    return 'name installed, aliased or undefined at run time' if devirt_blocked_name?(e.name) ||
                                                                 symbol_installed_names.nil? ||
                                                                 symbol_installed_names.include?(e.name)
    return 'owner has a prepended or unknown mixin' if !Array(@prepended_modules[e.owner]).empty? ||
                                                       @unknown_mixins.include?(e.owner)
    return 'owner has more than one definition' unless @registry.fetch(e.name, []).count { |d| d.owner == e.owner } == 1

    nil
  end

  def entry_plain_decl(impl, argc)
    "mrb_value #{impl}(#{(['mrb_state*', 'mrb_value'] + Array.new(argc, 'mrb_value')).join(', ')})"
  end

  # The registered entry hands its receiver and arguments to `_impl` unchanged.
  def entry_plain_forwarder?(m, argc)
    entry = Regexp.escape(m[:entry])
    impl = Regexp.escape(m[:impl])
    body = if argc.zero?
             "  return #{impl}\\(M, self\\);\\n"
           else
             "(?:  mrb_value \\w+;\\n){#{argc}}  mrb_get_args\\(M, \"o{#{argc}}\"(?:, &\\w+){#{argc}}\\);\\n" \
               "  return #{impl}\\(M, self(?:, \\w+){#{argc}}\\);\\n"
           end
    m[:code].match?(/^static mrb_value #{entry}\(mrb_state\* M, mrb_value self\) \{\n#{body}\}/)
  end

  def entry_header_function(e, m, why)
    fn = "bc2cpp_entry_#{cpp_name(e.owner, e.name)}"
    params = (['mrb_state* M', 'mrb_value self'] + Array.new(e.argc) { |i| "mrb_value a#{i}" }).join(', ')
    args = Array.new(e.argc) { |i| "a#{i}" }
    funcall = "mrb_funcall(M, self, \"#{e.name}\", #{e.argc}#{args.map { |a| ", #{a}" }.join})"
    if why
      return "// #{e.owner}##{e.name}: by name (#{why}).\n" \
             "#define BC2CPP_ENTRY_#{cpp_name(e.owner, e.name)} 0\n" \
             "static inline mrb_value #{fn}(#{params}) { return #{funcall}; }\n"
    end

    "// #{e.owner}##{e.name}: direct call of #{m[:impl]} for an exact #{e.owner} receiver, else by name.\n" \
      "#define BC2CPP_ENTRY_#{cpp_name(e.owner, e.name)} 1\n" \
      "#{entry_plain_decl(m[:impl], e.argc)};\n" \
      "static inline mrb_value #{fn}(#{params}) {\n" \
      "  struct RClass* owner = bc2cpp_entry_class(M, \"#{e.owner}\");\n" \
      "  if (!owner || mrb_immediate_p(self) || mrb_class(M, self) != owner) return #{funcall};\n" \
      "  return bc2cpp_entry_call(M, self, [&] { return #{m[:impl]}(#{(['M', 'self'] + args).join(', ')}); });\n" \
      "}\n"
  end
end
