# frozen_string_literal: true

require 'set'

# CONSTANT_REVIEWED (docs/adr/0491): a ratchet over the type check's untyped engine constants. A constant the analysis
# gives no type (no class pool, literal, integer, array-sum or constructed class) is TC1017 unless its name is listed in
# constant_reviewed_list.rb. A listed constant that is now typed, or no longer exists, is TC1017 too, so the list can
# only shrink. It mirrors PROVEN_MISS_REVIEWED (ADR 0275) and NOMETHOD_REVIEWED (ADR 0226).
#
# Only engine constants are judged: a fixture or project run (`--files`) has no list unless one is passed with
# `--constants FILE`. The list is regenerated by scripts/bc2cpp/constant_reviewed_update.rb; a fixture passes its own.
module ConstantReviewed
  CODE = 'TC1017'
  DEFAULT_LIST = File.expand_path('constant_reviewed_list.rb', __dir__)

  module_function

  # The set of names a list file declares as CONSTANT_REVIEWED. The file is evaluated in an anonymous module, so
  # loading a list defines nothing at top level. A missing or malformed list is an error, not an empty list.
  def load(path = DEFAULT_LIST)
    holder = Module.new
    holder.module_eval(File.read(path), path)
    holder.const_get(:CONSTANT_REVIEWED).to_set
  end

  # Names of the engine constants the analysis leaves untyped, sorted.
  def untyped_names(constants)
    engine(constants).reject { |c| c['type'] }.map { |c| c['name'] }.sort
  end

  # Gate: [{file:, line:, col:, message:}] for each unlisted untyped constant and each stale listed name.
  def violations(constants, reviewed:)
    rows = engine(constants)
    by_name = rows.to_h { |c| [c['name'], c] }
    unlisted = rows.select { |c| !c['type'] && !reviewed.include?(c['name']) }.sort_by { |c| c['name'] }
    out = unlisted.map do |c|
      { file: c['file'], line: c['line'], col: c['col'],
        message: "constant #{c['name']} has no type and is not in CONSTANT_REVIEWED: give it a type, or review it and list it" }
    end
    reviewed.sort.each do |name|
      c = by_name[name]
      if c.nil?
        out << { file: '-', line: 0, col: 1,
                 message: "listed constant #{name} is not an engine constant of this program: remove it from CONSTANT_REVIEWED" }
      elsif c['type']
        out << { file: c['file'], line: c['line'], col: c['col'],
                 message: "listed constant #{name} is typed (#{c['type']}, #{c['source']}): remove it from CONSTANT_REVIEWED" }
      end
    end
    out
  end

  def engine(constants)
    constants.select { |c| c['scope'] == 'engine' }
  end

  # The list file's text for +names+ (what constant_reviewed_update.rb --write writes).
  def list_source(names)
    body = names.empty? ? 'Set[].freeze' : "Set[\n#{names.sort.map { |n| "  #{n.inspect}," }.join("\n")}\n].freeze"
    <<~RUBY
      # frozen_string_literal: true

      # CONSTANT_REVIEWED (docs/adr/0491): the engine constants the bc2cpp type check leaves untyped, read and reviewed.
      # The gate (tools/bc2cpp/constant_reviewed.rb, TC1017) fails on an unlisted untyped constant and on a listed one
      # that is typed or gone, so this list only shrinks. Regenerate with
      # `MRBC=... ruby scripts/bc2cpp/constant_reviewed_update.rb --write`, after reading each added name's source.
      require 'set'

      CONSTANT_REVIEWED = #{body}
    RUBY
  end
end
