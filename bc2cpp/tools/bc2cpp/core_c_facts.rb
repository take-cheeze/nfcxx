# frozen_string_literal: true

# CORE_C_FACTS: the closed-world owner set of each method name mruby's own C looks up (hash.c's `default`, key `eql?` and
# `hash`, `==`, `respond_to_missing?`, `initialize_copy`), from the answer owner calls already use (CodeGen#name_owner_set:
# every class whose definition a lookup can find, nil when it cannot be named). BC2CPP_CORE_C_FACTS=path writes them as a
# header that the core C compiles against (runtime/core_c_facts_inject.h); without it the sets only print.
module CoreCFacts
  # name => [receiver class, owner whose C function the core expects]: BC2CPP_CW_ONLY_<n> holds when no class or module
  # on the lookup path of an instance of the receiver class (or of a subclass) defines the name but that owner
  NAMES = {
    'default' => %w[Hash Hash], 'eql?' => nil, 'hash' => nil, '==' => nil, 'respond_to_missing?' => nil,
    'initialize_copy' => nil
  }.freeze

  def self.sets(gen) = NAMES.keys.to_h { |name| [name, gen.name_owner_set(name)] }

  # The names on the lookup paths of +base+'s instances and its subclasses' (nil when a chain is partly unknown).
  def self.lookup_path(gen, base)
    answers = gen.call_facts_answers
    path = Set.new
    answers.classes.each do |klass|
      names, unknown = answers.ancestors(klass)
      next unless names.include?(base)
      return nil if unknown

      path.merge(names)
    end
    path
  end

  def self.only?(gen, name, owners)
    receiver, expected = NAMES[name]
    return false unless owners && expected && (path = lookup_path(gen, receiver))

    (owners & path.to_a) == [expected]
  end

  def self.header(sets, only)
    out = +"/* generated by bc2cpp (core_c_facts.rb): closed-world owner sets of names the mruby core C looks up */\n"
    sets.each do |name, owners|
      id = name.gsub(/\W/) { |c| format('_%02x', c.ord) }
      out << (owners ? "#define BC2CPP_CW_OWNERS_#{id} \"#{owners.join(' ')}\"\n" : "/* #{name}: not nameable */\n")
      out << "#define BC2CPP_CW_ONLY_#{id} 1\n" if only[name]
    end
    out
  end

  def self.report(gen)
    sets = sets(gen)
    only = sets.to_h { |name, owners| [name, only?(gen, name, owners)] }
    warn "== core C facts (CORE_C_FACTS): #{sets.count { |_, o| o }} of #{sets.size} names have a closed owner set =="
    sets.each do |name, owners|
      warn "  CORE_C_FACT #{name}: #{owners ? owners.join(' ') : 'not nameable'}#{' (core only)' if only[name]}"
    end
    warn ''
    return unless (path = ENV['BC2CPP_CORE_C_FACTS']) && !path.empty?

    File.write(path, header(sets, only))
  end
end
