#!/usr/bin/env bash
# Build the QBE back end (3rd/qbe) into build/qbe. QBE is the code generator of Path B (scripts/pathb-ssa-build).
# The build happens in a copy of the source so the submodule stays clean. The cproc C front end is gone (it was the qbe
# backend's front end); docs/notes/cproc-removal.md has the history.
#
# 3rd/qbe is take-cheeze/qbe, a daily mirror of https://c9x.me/git/qbe.git (see that repo's sync workflow). Its pin and the
# nfcxx fixes (the commits of the fork, no patch files) are described in docs/notes/realworld.md and docs/notes/linux-kernel.md.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
jobs=$(nproc 2>/dev/null || sysctl -n hw.ncpu)   # macOS has no nproc
# ccache when it is installed: the QBE objects are rebuilt from the same sources in every fresh checkout.
cc_wrap=cc; command -v ccache >/dev/null && cc_wrap="ccache cc"
git -C "$root" submodule update --init 3rd/qbe

p=qbe
rm -rf "$root/build/$p"; mkdir -p "$root/build"
cp -r "$root/3rd/$p" "$root/build/$p"
rm -rf "$root/build/$p/.git"
# the submodule's own build products (left by a build in 3rd/) are stale for these sources: make rebuilds them
find "$root/build/$p" \( -name '*.o' -o -name "$p" \) -type f -delete
# config.h is generated by the submodule's Makefile from uname (Deftgt): a copy made on another host carries that host's target
rm -f "$root/build/$p/config.h"
make -C "$root/build/qbe" -j"$jobs" CC="$cc_wrap" >/dev/null
echo "built: $root/build/qbe/qbe"
