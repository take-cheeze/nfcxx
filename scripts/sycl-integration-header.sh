#!/usr/bin/env bash
# sycl-integration-header.sh DUMP: the integration header of a SYCL translation unit (docs/notes/sycl-kernel-builtins.md).
# DUMP is the pre-pass record file (NFCXX_SYCL_DUMP, written by the front end): one tab-separated line per kernel with its
# stable name, closure size, line, column, file, parameter count, and per parameter kind, info and offset. The output
# holds one KernelInfoData specialization per kernel (the oneAPI headers' kernel_desc.hpp, with __SYCL_UNNAMED_LAMBDA__).
# The header must follow <sycl/sycl.hpp>, since it names the sycl::detail templates.
set -euo pipefail
dump=$1
q=$(printf "\047")   # a single quote, for the char arguments of KernelInfoData
echo "// Generated by nfcxx from the kernel-info pre-pass: KernelInfoData for each kernel of this translation unit."
echo "namespace sycl { inline namespace _V1 { namespace detail {"
sort -u "$dump" | awk -F'\t' -v q="$q" '
{
  name = $1; size = $2; line = $3; col = $4; file = $5; n = $6 + 0
  chars = ""
  for (i = 1; i <= length(name); i++) {
    chars = chars (i > 1 ? ", " : "") q substr(name, i, 1) q
  }
  printf "template <> struct KernelInfoData<%s> {\n", chars
  printf "  static constexpr unsigned getNumParams() { return %d; }\n", n
  print  "  static constexpr const kernel_param_desc_t &getParamDesc(int Idx) { return Params[Idx]; }"
  printf "  static constexpr const char *getName() { return \"%s\"; }\n", name
  print  "  static constexpr bool isESIMD() { return false; }"
  printf "  static constexpr const char *getFileName() { return \"%s\"; }\n", file
  print  "  static constexpr const char *getFunctionName() { return \"\"; }"
  printf "  static constexpr unsigned getLineNumber() { return %d; }\n", line
  printf "  static constexpr unsigned getColumnNumber() { return %d; }\n", col
  printf "  static constexpr int64_t getKernelSize() { return %d; }\n", size
  print  "private:"
  printf "  static constexpr kernel_param_desc_t Params[] = {"
  for (k = 0; k < n; k++) {
    kind = $(7 + 3 * k); info = $(8 + 3 * k); off = $(9 + 3 * k)
    printf "{static_cast<kernel_param_kind_t>(%d), %d, %d}, ", kind, info, off
  }
  print  "{static_cast<kernel_param_kind_t>(1), 0, 0}};"
  print  "};"
}'
echo "}}}"
