#!/usr/bin/env ruby
# Regenerate be/nfcxx_names.h from the EDG sources: name tables for the IL enumerations the Path B back end
# prints (operator, expression-node, statement and dynamic-init kinds). EDG has no shared name tables for
# these in this configuration, so each enumerator becomes one case in a switch. A switch fails to compile
# if an enumerator is missing, and enumerators compiled out in the configured build are removed by hand
# (see the note in the generated header). Aliases ("NAME = OTHER") are skipped so case labels stay unique.
# Ported from scripts/pathb-gen-names.sh; the generated file is the same apart from the script's name in its header.

ROOT = File.expand_path(File.join(File.dirname($0), ".."))
IL = File.join(ROOT, "3rd/edg/src/il_def.h")
OUT = File.join(ROOT, "be/nfcxx_names.h")

# Enumerators that EDG compiles out with the cpfe configuration in scripts/setup-pathb.sh
# (DO_IL_LOWERING and friends); a case label for them would not compile.
SKIP = %w[enk_lowered_eh_construct ck_stack_offset]

# tag, prefix, generated function, parameter type, parameter name
TABLES = [
  %w[an_expr_operator_kind eok_ nfcxx_eok_name an_expr_operator_kind op],
  %w[an_expr_node_kind enk_ nfcxx_enk_name an_expr_node_kind kind],
  %w[a_statement_kind stmk_ nfcxx_stmk_name a_statement_kind kind],
  %w[a_dynamic_init_kind dik_ nfcxx_dik_name a_dynamic_init_kind kind],
  %w[a_constant_repr_kind ck_ nfcxx_ck_name a_constant_repr_kind kind],
].freeze

# Enumerators of "enum TAG" that have the given prefix, in source order: the lines after the enum's
# first line, up to the first line starting with "};". No enum, or no file, gives none (the shell's grep
# then fails, and so does the script).
def names_of(lines, tag, prefix)
  return [] if lines.nil?
  start = lines.index { |l| l.start_with?("enum #{tag} ") }
  return [] if start.nil?
  member = /\A[ \t]*#{Regexp.escape(prefix)}[a-z_0-9]+[ \t]*,/
  names = []
  lines.each_with_index do |line, i|
    next if i <= start
    break if line.start_with?("};")
    next unless member.match?(line)
    names << line.sub(/\A[ \t]*/, "").sub(/[ \t]*,.*/, "")
  end
  names
end

lines = nil
if File.file?(IL)
  lines = File.binread(IL).each_line.map { |l| l.delete_suffix("\n") }
else
  $stderr.puts "grep: #{IL}: No such file or directory"
end

out = [
  "/* Generated by scripts/pathb-gen-names.rb from 3rd/edg/src/il_def.h. Do not edit by hand. */",
  "/* Enumerators compiled out in the configured build (see skip list below) are dropped. */",
]
TABLES.each do |tag, prefix, fn, type, var|
  out << ""
  out << "static const char *#{fn}(#{type} #{var})"
  out << "{"
  out << "  switch (#{var}) {"
  names = names_of(lines, tag, prefix).reject { |n| SKIP.include?(n) }
  if names.empty?
    # The script stops here (pipefail with set -e): the file holds the tables so far and this table's head.
    File.binwrite(OUT, out.map { |l| "#{l}\n" }.join)
    exit 1
  end
  names.each do |n|
    out << "    case #{n}: return \"#{n.delete_prefix(prefix)}\";"
  end
  out << "    default: return NULL;"
  out << "  }"
  out << "}"
end

File.binwrite(OUT, out.map { |l| "#{l}\n" }.join)
puts "wrote #{OUT}"
