#!/usr/bin/env ruby
# sycl-integration-header.rb DUMP: the integration header of a SYCL translation unit (docs/notes/sycl-kernel-builtins.md).
# DUMP is the pre-pass record file (NFCXX_SYCL_DUMP, written by the front end): one tab-separated line per kernel with its
# stable name, closure size, line, column, file, parameter count, and per parameter kind, info and offset. The output
# holds one KernelInfoData specialization per kernel (the oneAPI headers' kernel_desc.hpp, with __SYCL_UNNAMED_LAMBDA__).
# The header must follow <sycl/sycl.hpp>, since it names the sycl::detail templates.
# This is scripts/sycl-integration-header.sh (sort -u and awk) ported to Ruby: the same lines in the same order.

dump = ARGV[0]
if dump.nil?
  warn "sycl-integration-header.rb: DUMP is required"
  exit 1
end

q = "'"
out = +""
out << "// Generated by nfcxx from the kernel-info pre-pass: KernelInfoData for each kernel of this translation unit.\n"
out << "namespace sycl { inline namespace _V1 { namespace detail {\n"
# sort -u: the distinct lines, in byte order
File.readlines(dump, chomp: true).uniq.sort.each do |line|
  f = line.split("\t", -1)
  field = ->(i) { f[i - 1] || "" }   # awk's $i (1-based): missing fields are empty
  name = field.(1)
  size = field.(2).to_i
  ln = field.(3).to_i
  col = field.(4).to_i
  file = field.(5)
  n = field.(6).to_i
  chars = name.each_char.map { |c| "#{q}#{c}#{q}" }.join(", ")
  out << "template <> struct KernelInfoData<#{chars}> {\n"
  out << "  static constexpr unsigned getNumParams() { return #{n}; }\n"
  out << "  static constexpr const kernel_param_desc_t &getParamDesc(int Idx) { return Params[Idx]; }\n"
  out << "  static constexpr const char *getName() { return \"#{name}\"; }\n"
  out << "  static constexpr bool isESIMD() { return false; }\n"
  out << "  static constexpr const char *getFileName() { return \"#{file}\"; }\n"
  out << "  static constexpr const char *getFunctionName() { return \"\"; }\n"
  out << "  static constexpr unsigned getLineNumber() { return #{ln}; }\n"
  out << "  static constexpr unsigned getColumnNumber() { return #{col}; }\n"
  out << "  static constexpr int64_t getKernelSize() { return #{size}; }\n"
  out << "private:\n"
  out << "  static constexpr kernel_param_desc_t Params[] = {"
  n.times do |k|
    kind = field.(7 + 3 * k).to_i
    info = field.(8 + 3 * k).to_i
    off = field.(9 + 3 * k).to_i
    out << "{static_cast<kernel_param_kind_t>(#{kind}), #{info}, #{off}}, "
  end
  out << "{static_cast<kernel_param_kind_t>(1), 0, 0}};\n"
  out << "};\n"
end
out << "}}}\n"
print out
