# Usage: scripts/mrb scripts/cpp-feature-report.rb checklist.tsv results.tsv
# An invalid result: main reports the message and returns status 1 (raised, not exited, as in cpp-feature-checklist.rb).
class ReportError < StandardError; end
def fail_report(message)
  raise ReportError, message
end

def read_rows(path)
  File.open(path, 'rb') { |f| f.read.split("\n")[1..-1].map { |line| line.split("\t", -1) } }
end

def main(argv)
  begin
    report(argv)
  rescue ReportError => e
    $stderr.puts e.message
    1
  rescue SystemCallError => e
    $stderr.puts "cpp-feature-report.rb: #{e.message}"
    1
  end
end

def report(argv)
  fail_report('usage: cpp-feature-report.rb checklist.tsv results.tsv') unless argv.size == 2
  checklist = read_rows(argv[0])
  results = {}
  read_rows(argv[1]).each do |row|
    fail_report('invalid result row') unless row.size == 6
    key, standard, route, status = row
    fail_report('unknown checklist key: ' + key) unless checklist.any? { |r| r[0] == key && r[1] == standard }
    fail_report('unknown route: ' + route) unless ['qbe', 'gcc', 'pathb', 'host'].include?(route)
    results[key] ||= {}
    fail_report('duplicate result: ' + key + ' ' + route) if results[key][route]
    results[key][route] = status
  end
  puts '# C++ language feature matrix: C++11 and C++14 pilot'
  puts ''
  puts 'Generated by `scripts/cpp-feature-report.rb` from the pinned checklist and `tests/cpp-features/run.sh`.'
  puts 'Each cell describes one focused probe in its own standard mode; a pass is not full paper conformance.'
  puts 'Unmeasured routes say `not-run`. C++17 and later have no probes yet.'
  puts 'See the [runner documentation](../../tests/cpp-features/README.md) for reproduction, measurement environment and probe limits.'
  puts ''
  puts 'Compiler-version cells are adapted from [cpprefjp/site implementation-status.md](https://github.com/cpprefjp/site/blob/213f89d/implementation-status.md),'
  puts 'by the cpprefjp contributors, [CC BY 4.0](https://github.com/cpprefjp/site/blob/213f89d/LICENSE).'
  puts 'Labels are replaced with page identifiers; notes and empty version cells are preserved.'
  puts 'These are upstream observations, not independently verified first-support versions. Intel mixes ICC/ICX.'
  puts ''
  puts '| Standard | Paper / feature probe | GCC | Clang | Intel | MSVC | nfcxx qbe | nfcxx gcc | nfcxx Path B |'
  puts '| --- | --- | --- | --- | --- | --- | --- | --- | --- |'
  checklist.each do |row|
    key, standard, paper, page = row
    next unless results[key]
    page = 'https://github.com/cpprefjp/site/blob/213f89d/' + (page.start_with?('/') ? page.byteslice(1, page.bytesize - 1) : page) unless page.start_with?('http')
    label = key.split('-', 3)[2]
    versions = row[6, 4].map { |cell| cell.gsub('|', '&#124;') }
    statuses = ['qbe', 'gcc', 'pathb'].map { |route| results[key][route] || 'not-run' }
    puts '| ' + ([standard, '[' + paper + ': ' + label + '](' + page + ')'] + versions + statuses).join(' | ') + ' |'
  end
  0
end

rc = main(ARGV)
exit(rc) if rc != 0
