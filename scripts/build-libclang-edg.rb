#!/usr/bin/env ruby
# libclang-edg: build lib/libclang-edg/clang_edg.c and the generated stubs into build/libclang-edg/libclang-edg.so, a
# shared library with libclang's C API: the functions clang.cindex uses (lib/libclang-edg/include/clang-c/). Needs the
# front end built first (scripts/setup-libclang-edg.sh).
#
# When the front-end archive is there (build/libclang-edg/cmake/src/nfcxx-so/libedgfe-pic.a), the front end is linked
# into the library and runs in-process, with the options scripts/libclang-cursors.rb gives cpfe fixed now
# (build/libclang-edg/edg_args.h: this host's system include directories and GNU version, the base directory). The
# library then runs a process only when LIBCLANG_EDG_RUNNER names a runner at run time. Without the archive (or with
# LIBCLANG_EDG_IN_PROCESS=0) the library runs scripts/libclang-cursors.rb from this checkout, or LIBCLANG_EDG_RUNNER.
#
# The compile and link commands are the bash original's (tests/launch/oracle/build-libclang-edg.sh); the runner's
# default is the Ruby file's path. CC, CXX and LIBCLANG_EDG_LDFLAGS are as before.
require "fileutils"
require "open3"
require_relative "launch"

NAME = "build-libclang-edg"
ROOT = Launch.root_of(__FILE__)

# the C string lines of edg_args.h: a backslash and a double quote are escaped
def cstr(s)
  esc = s.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }
  %(  "#{esc}",\n)
end

# the text of build/libclang-edg/edg_args.h: the options of scripts/libclang-cursors.rb for this host
def edg_args_h(base, gnu, sys)
  text = +"/* Generated by scripts/build-libclang-edg.rb: the options of scripts/libclang-cursors.rb, for this host. */\n"
  text << %(#define NFC_EDG_STD "--c++23"\n)
  text << "static const char *const nfc_edg_before[] = {\n"
  text << cstr("-D_POSIX_SOURCE") << cstr("-D__CHAR_BIT__=8")
  text << "};\n"
  text << "static const char *const nfc_edg_after[] = {\n"
  after = ["--g++", "--wdir", "/"]
  after << "--gnu_version=#{gnu}" if gnu
  after.push("-tused", "--edg_base_dir=#{base}")
  after += sys.reject(&:empty?).map { |d| "--sys_include=#{d}" }
  after << "--sys_include=#{base}/include"
  after.each { |a| text << cstr(a) }
  text << "};\n"
end

# the names of the files newer than so, as find -newer lists them (empty when none)
def newer_than(paths, so)
  out, _st = Open3.capture2("find", *paths, "-newer", so)
  out
end

# the front end in-process: edg_args.h, then the compile and link of the library, unless it is up to date
def in_process(root, out, base, archive, srcs, flags, cc, cxx)
  gnu = HostSys.gnu_version
  text = edg_args_h(base, gnu, HostSys.sys_includes)
  tmp = File.join(out, "edg_args.h.tmp")
  File.write(tmp, text)
  h = File.join(out, "edg_args.h")
  so = File.join(out, "libclang-edg.so")

  # the link takes a minute (LTO): skip it when the library is newer than its inputs and the options are the same
  same = File.file?(h) && File.binread(tmp) == File.binread(h)
  up_to_date = same && File.file?(so) &&
               newer_than([archive, *srcs, File.join(root, "lib/libclang-edg/include"), $0], so).empty?
  if up_to_date
    FileUtils.rm_f(tmp)
    puts "#{so} is up to date (the front end in-process)"
    return
  end
  File.rename(tmp, h)

  objs = srcs.map do |s|
    o = File.join(out, "#{File.basename(s, ".c")}.o")
    run_or_exit([cc, *flags, "-DLIBCLANG_EDG_IN_PROCESS", "-I", out, "-c", "-o", o, s])
    o
  end
  # the front end is C++ (libstdc++); its symbols are hidden, so the library exports libclang's API only. EDG's
  # release configuration compiles with -flto, so the link is the optimization: -flto=auto runs it in parallel.
  ldflags = Launch.env_or("LIBCLANG_EDG_LDFLAGS", "-flto=auto").split
  run_or_exit([cxx, "-shared", *ldflags, "-o", so, *objs, archive, "-lpthread", "-lm"])
  FileUtils.rm_f(objs)
  puts "built #{so} (the front end in-process)"
end

# run a build command; a failure ends the script with its status (set -e)
def run_or_exit(argv)
  code = Launch.run(argv)
  exit code unless code.zero?
end

def main
  out = Launch.env_or("LIBCLANG_EDG_OUT", File.join(ROOT, "build/libclang-edg"))
  base = Launch.env_or("LIBCLANG_EDG_BASE", File.join(out, "edg-base"))
  archive = File.join(out, "cmake/src/nfcxx-so/libedgfe-pic.a")
  cc = Launch.env_or("CC", "cc")
  cxx = Launch.env_or("CXX", "c++")
  FileUtils.mkdir_p(out)

  srcs = [File.join(ROOT, "lib/libclang-edg/clang_edg.c"), File.join(ROOT, "lib/libclang-edg/generated/stubs.c")]
  runner = File.join(ROOT, "scripts/libclang-cursors.rb")
  flags = ["-std=c99", "-Wall", "-Wextra", "-Werror", "-fPIC", "-O2", "-DLIBCLANG_EDG_RUNNER_DEFAULT=\"#{runner}\"",
           "-I", File.join(ROOT, "lib/libclang-edg/include")]
  so = File.join(out, "libclang-edg.so")

  if Launch.env_or("LIBCLANG_EDG_IN_PROCESS", "1") != "0" && File.file?(archive)
    in_process(ROOT, out, base, archive, srcs, flags, cc, cxx)
  else
    FileUtils.rm_f(File.join(out, "edg_args.h")) # tests/libclang-edg/run.sh checks the in-process library when it is there
    run_or_exit([cc, *flags, "-shared", "-o", so, *srcs])
    puts "built #{so} (the front end through #{runner})"
  end
end

main
