#!/usr/bin/env ruby
# libclang-edg: build lib/libclang-edg/clang_edg.c and the generated stubs into build/libclang-edg/libclang-edg.so, a
# shared library with libclang's C API: the functions clang.cindex uses (lib/libclang-edg/include/clang-c/). Needs the
# front end built first (scripts/setup-libclang-edg.sh).
#
# When the front-end archive is there (build/libclang-edg/cmake/src/nfcxx-so/libedgfe-pic.a), the front end is linked
# into the library and runs in-process, with the options scripts/libclang-cursors gives cpfe fixed now
# (build/libclang-edg/edg_args.h: this host's system include directories and GNU version, the base directory). The
# library then runs a process only when LIBCLANG_EDG_RUNNER names a runner at run time. Without the archive (or with
# LIBCLANG_EDG_IN_PROCESS=0) the library runs scripts/libclang-cursors from this checkout, or LIBCLANG_EDG_RUNNER.
#
# The host probes (host_gnu_version, host_sys_includes) are scripts/host-sys.sh's, ported here: the same commands with the
# same output reading (NFCXX_CXX, NFCXX_SYS_INCLUDES).
require "fileutils"
require "open3"

$stdout.sync = true

# ${VAR:-default} for a variable: the default when it is unset or empty
def or_default(value, default)
  value.nil? || value.empty? ? default : value
end

# Runs a command as the script's `set -e` does: when it fails, the script ends with its status.
def run!(*cmd)
  system(*cmd)
  status = $?
  exit(status.exitstatus || 1) unless status.success?
end

# The output of a command (its trailing newlines removed) when it succeeds, else "": the `$(cmd) || var=` of host-sys.sh.
def capture_or_empty(*cmd)
  out, status = Open3.capture2(*cmd, err: File::NULL)
  status.success? ? out.sub(/\n+\z/, "") : ""
rescue SystemCallError
  ""
end

def host_cxx
  or_default(ENV["NFCXX_CXX"], "g++")
end

# host_dialect: clang when the host C++ compiler's first --version line says clang, else g++
def host_dialect
  first = capture_or_empty(host_cxx, "--version").lines.first.to_s
  first =~ /clang/i ? "clang" : "g++"
end

# host_gnu_version: major*10000 + minor*100 + patch of the host g++, as EDG's --gnu_version; "" when there is none
def host_gnu_version
  ver = capture_or_empty(host_cxx, "-dumpfullversion")
  if ver.empty? && host_dialect == "clang"
    # Apple clang has no -dumpfullversion: the g++-mode harness needs GNU 15's builtins (see host-sys.sh)
    return "150000"
  end
  return "" if ver.empty?

  maj, min, pat = ver.split(".")
  (maj.to_i * 10000 + min.to_i * 100 + pat.to_i).to_s
end

# host_sys_includes: the include directories of the host C++ library (NFCXX_SYS_INCLUDES overrides the discovery), in the
# order the compiler searches them; "framework directory" entries are left out
def host_sys_includes
  listed = ENV["NFCXX_SYS_INCLUDES"]
  return listed.split(":") unless listed.nil? || listed.empty?

  _out, err = begin
    Open3.capture3(host_cxx, "-E", "-x", "c++", "-v", "-", stdin_data: "")
  rescue SystemCallError
    return []
  end
  dirs = []
  on = false
  err.each_line do |raw|
    line = raw.chomp
    if line.include?("search starts here:")
      on = true
      next
    end
    on = false if line.include?("End of search list")
    next unless on

    line = line.sub(/\A +/, "") if line.start_with?(" ")
    next if line.include?("framework directory")

    dirs << line if line.match?(/\A[^ ]/)
  end
  dirs
end

# one C string of edg_args.h, escaped as the script's cstr does
def cstr(text)
  %(  "#{text.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }}",\n)
end

# true when any of the paths (a directory's entries included, as find lists them) is newer than the reference file
def newer_than?(paths, ref)
  reference = File.mtime(ref)
  paths.any? do |p|
    entries = [p]
    if File.directory?(p)
      entries += Dir.glob("#{p}/**/*", File::FNM_DOTMATCH).reject { |e| %w[. ..].include?(File.basename(e)) }
    end
    entries.any? { |e| File.mtime(e) > reference }
  end
end

root = File.expand_path("..", File.dirname(__FILE__))
out = or_default(ENV["LIBCLANG_EDG_OUT"], "#{root}/build/libclang-edg")
base = or_default(ENV["LIBCLANG_EDG_BASE"], "#{out}/edg-base")
archive = "#{out}/cmake/src/nfcxx-so/libedgfe-pic.a"
cc = or_default(ENV["CC"], "cc")
cxx = or_default(ENV["CXX"], "c++")
FileUtils.mkdir_p(out)
srcs = ["#{root}/lib/libclang-edg/clang_edg.c", "#{root}/lib/libclang-edg/generated/stubs.c"]
flags = ["-std=c99", "-Wall", "-Wextra", "-Werror", "-fPIC", "-O2", "-DLIBCLANG_EDG_RUNNER_DEFAULT=\"#{root}/scripts/libclang-cursors\"",
         "-I", "#{root}/lib/libclang-edg/include"]
so = "#{out}/libclang-edg.so"

if ENV.fetch("LIBCLANG_EDG_IN_PROCESS", "1") != "0" && File.file?(archive)
  # the options of scripts/libclang-cursors, as C strings: before the -std option, and after the caller's -I/-D/-U
  gnu = host_gnu_version
  header = +"/* Generated by scripts/build-libclang-edg.rb: the options of scripts/libclang-cursors, for this host. */\n"
  header << %(#define NFC_EDG_STD "--c++23"\n)
  header << "static const char *const nfc_edg_before[] = {\n"
  header << cstr("-D_POSIX_SOURCE") << cstr("-D__CHAR_BIT__=8")
  header << "};\n"
  header << "static const char *const nfc_edg_after[] = {\n"
  header << cstr("--g++") << cstr("--wdir") << cstr("/")
  header << cstr("--gnu_version=#{gnu}") unless gnu.empty?
  header << cstr("-tused")
  header << cstr("--edg_base_dir=#{base}")
  host_sys_includes.each { |d| header << cstr("--sys_include=#{d}") unless d.empty? }
  header << cstr("--sys_include=#{base}/include")
  header << "};\n"
  tmp = "#{out}/edg_args.h.tmp"
  File.write(tmp, header)

  # the link takes a minute (LTO): skip it when the library is newer than its inputs and the options are the same
  if File.file?("#{out}/edg_args.h") && FileUtils.compare_file(tmp, "#{out}/edg_args.h") && File.file?(so) &&
     !newer_than?([archive, *srcs, "#{root}/lib/libclang-edg/include", __FILE__], so)
    FileUtils.rm_f(tmp)
    puts "#{so} is up to date (the front end in-process)"
    exit 0
  end
  FileUtils.mv(tmp, "#{out}/edg_args.h")
  objs = []
  srcs.each do |s|
    o = "#{out}/#{File.basename(s, ".c")}.o"
    run!(cc, *flags, "-DLIBCLANG_EDG_IN_PROCESS", "-I", out, "-c", "-o", o, s)
    objs << o
  end
  # the front end is C++ (libstdc++); its symbols are hidden, so the library exports libclang's API only. EDG's
  # release configuration compiles with -flto, so the link is the optimization: -flto=auto runs it in parallel.
  ldflags = ENV["LIBCLANG_EDG_LDFLAGS"]
  ldflags = ldflags.nil? || ldflags.empty? ? ["-flto=auto"] : ldflags.split
  run!(cxx, "-shared", *ldflags, "-o", so, *objs, archive, "-lpthread", "-lm")
  FileUtils.rm_f(objs)
  puts "built #{so} (the front end in-process)"
else
  FileUtils.rm_f("#{out}/edg_args.h")   # tests/libclang-edg/run.sh checks the in-process library when it is there
  run!(cc, *flags, "-shared", "-o", so, *srcs)
  puts "built #{so} (the front end through #{root}/scripts/libclang-cursors)"
end
