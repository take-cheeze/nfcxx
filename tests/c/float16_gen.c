/* Generates tests/c/float16_golden.inc, the expected results of the _Float16 tests (tests/c/float16_ops.c), from gcc's
   own _Float16 arithmetic and conversions:

     gcc -O0 -o /tmp/f16gen tests/c/float16_gen.c && /tmp/f16gen > tests/c/float16_golden.inc

   This file has no EXPECT line, so tests/c/run.sh does not run it. The random inputs come from a fixed LCG. */
#include <stdio.h>
#include <string.h>

typedef union { unsigned short u; _Float16 h; } f16u;
static _Float16 hf(unsigned short b) { f16u x; x.u = b; return x.h; }
static unsigned short hb(_Float16 h) { f16u x; x.h = h; return x.u; }
static unsigned fbits(float f) { unsigned u; memcpy(&u, &f, 4); return u; }
static unsigned long long dbits(double d) { unsigned long long u; memcpy(&u, &d, 8); return u; }

static unsigned long long rng = 0x9e3779b97f4a7c15ull;
static unsigned long long next(void)
{
	rng = rng * 6364136223846793005ull + 1442695040888963407ull;
	return rng >> 11;
}

/* a 16-bit pattern: half of them uniform, the others with a random exponent (subnormals, infinities, NaNs) */
static unsigned short randh(void)
{
	if (next() & 1)
		return (unsigned short)next();
	return (unsigned short)((next() & 1) << 15 | (next() % 32) << 10 | next() % 1024);
}

static const unsigned short special[] = {
	0x0000, 0x8000, 0x0001, 0x8001, 0x03ff, 0x0400, 0x0401, 0x3c00, 0xbc00, 0x4000, 0x3800, 0x3555,
	0x7bff, 0xfbff, 0x7c00, 0xfc00, 0x7e00, 0x7c01, 0x6800, 0x7800, 0x0200, 0x1400, 0x4900, 0x4d00,
	0x2e66, 0x3c01, 0x3bff, 0x5bff, 0x6bff, 0x7000, 0x0100, 0x7bfe,
};
#define NSPECIAL (sizeof special / sizeof special[0])

static void bin(unsigned short a, unsigned short b)
{
	_Float16 x = hf(a), y = hf(b);
	printf("{0x%04x,0x%04x,0x%04x,0x%04x,0x%04x,0x%04x,%d,%d,%d,%d,%d,%d},\n", a, b,
		hb(x + y), hb(x - y), hb(x * y), hb(x / y),
		x == y, x != y, x < y, x <= y, x > y, x >= y);
}

static void un(unsigned short a)
{
	_Float16 x = hf(a), inc = hf(a), dec = hf(a);
	double d = x;
	float f = x;
	inc++;
	dec--;
	printf("{0x%04x,0x%04x,0x%04x,%d,0x%016llx,0x%08x},\n", a, hb(inc), hb(dec), x ? 1 : 0,
		dbits(d), fbits(f));
}

static void from_double(unsigned long long bits)
{
	double d;
	memcpy(&d, &bits, 8);
	printf("{0x%016llx,0x%04x},\n", bits, hb((_Float16)d));
}

static void from_s64(long long v)
{
	printf("{(long long)0x%016llxULL,0x%04x},\n", (unsigned long long)v, hb((_Float16)v));
}

static void from_u64(unsigned long long v)
{
	printf("{%lluULL,0x%04x},\n", v, hb((_Float16)v));
}

static void mixed(unsigned short a, float f)
{
	float r = hf(a) + f;
	printf("{0x%04x,0x%08x,0x%08x},\n", a, fbits(f), fbits(r));
}

static void to_int(unsigned short a)
{
	_Float16 x = hf(a);
	printf("{0x%04x,(long long)0x%016llxULL},\n", a, (unsigned long long)(long long)x);
}

int main(void)
{
	unsigned i, j;
	unsigned long long bits;
	float f;

	printf("/* generated by tests/c/float16_gen.c from gcc's _Float16; do not edit */\n");

	printf("static const struct f16_bin f16_bins[] = {\n");
	for (i = 0; i < NSPECIAL; ++i)
		for (j = 0; j < NSPECIAL; ++j)
			bin(special[i], special[j]);
	for (i = 0; i < 1500; ++i)
		bin(randh(), randh());
	printf("};\n");

	printf("static const struct f16_un f16_uns[] = {\n");
	for (i = 0; i < NSPECIAL; ++i)
		un(special[i]);
	for (i = 0; i < 400; ++i)
		un(randh());
	printf("};\n");

	printf("static const struct f16_dbl f16_dbls[] = {\n");
	for (i = 0; i < 600; ++i) {
		/* doubles that round into the binary16 range, and the others */
		bits = next() << 20 ^ next() << 40 ^ next();
		if (i % 3 == 0)
			bits = (bits & ~(0x7ffull << 52)) | ((unsigned long long)(1000 + next() % 40) << 52);
		from_double(bits);
	}
	from_double(dbits(65504.0));
	from_double(dbits(65519.0));
	from_double(dbits(65520.0));
	from_double(dbits(0x1p-25));
	from_double(dbits(0x1.8p-25));
	from_double(dbits(0x1p-24));
	from_double(dbits(0.1));
	from_double(dbits(-0.0));
	printf("};\n");

	/* compile-time conversions: the literals are folded by the compiler (cproc eval.c); the expected bits are gcc's
	   conversions of the same values */
	{
		static const char *lits[] = {"0.1", "65520.0", "65519.0", "2049.0", "2051.0", "-65504.0",
			"5.9604644775390625e-8", "2.9802322387695312e-8", "2.9802322387695313e-8", "0.5", "1e-30", "-0.0"};
		static double vals[300 + 12];
		unsigned nv = 0;
		for (i = 0; i < 300; ++i) {
			bits = next() << 20 ^ next() << 40 ^ next();
			memcpy(&vals[nv], &bits, 8);
			if (vals[nv] == vals[nv] && vals[nv] < 1e300 && vals[nv] > -1e300)
				++nv;
		}
		printf("static const _Float16 f16_folds[] = {\n");
		for (i = 0; i < nv; ++i)
			printf("%.17e,\n", vals[i]);
		for (i = 0; i < sizeof lits / sizeof lits[0]; ++i)
			printf("%s,\n", lits[i]);
		printf("};\n");
		printf("static const unsigned short f16_foldbits[] = {\n");
		for (i = 0; i < nv; ++i)
			printf("0x%04x,\n", hb((_Float16)vals[i]));
		printf("0x%04x,\n", hb((_Float16)0.1));
		printf("0x%04x,\n", hb((_Float16)65520.0));
		printf("0x%04x,\n", hb((_Float16)65519.0));
		printf("0x%04x,\n", hb((_Float16)2049.0));
		printf("0x%04x,\n", hb((_Float16)2051.0));
		printf("0x%04x,\n", hb((_Float16)-65504.0));
		printf("0x%04x,\n", hb((_Float16)5.9604644775390625e-8));
		printf("0x%04x,\n", hb((_Float16)2.9802322387695312e-8));
		printf("0x%04x,\n", hb((_Float16)2.9802322387695313e-8));
		printf("0x%04x,\n", hb((_Float16)0.5));
		printf("0x%04x,\n", hb((_Float16)1e-30));
		printf("0x%04x,\n", hb((_Float16)-0.0));
		printf("};\n");
	}

	printf("static const struct f16_s64 f16_s64s[] = {\n");
	for (i = 0; i < 300; ++i) {
		from_s64((long long)(next() << (next() % 40)) * ((next() & 1) ? 1 : -1));
	}
	from_s64(0);
	from_s64(2049);
	from_s64(-2049);
	from_s64(2051);
	from_s64(0x7fffffffffffffffLL);
	from_s64(-0x7fffffffffffffffLL - 1);
	printf("};\n");

	printf("static const struct f16_u64 f16_u64s[] = {\n");
	for (i = 0; i < 300; ++i)
		from_u64(next() << (next() % 40));
	from_u64(2051);
	from_u64(0xffffffffffffffffULL);
	printf("};\n");

	printf("static const struct f16_mix f16_mixes[] = {\n");
	for (i = 0; i < NSPECIAL; ++i) {
		f = 0.5f;
		mixed(special[i], f);
		mixed(special[i], 1.0f / 3.0f);
	}
	for (i = 0; i < 300; ++i) {
		f = (float)(int)(next() % 100000) / 7.0f;
		mixed(randh(), f);
	}
	printf("};\n");

	printf("static const struct f16_int f16_ints[] = {\n");
	for (i = 0; i < 400; ++i) {
		unsigned short a = randh();
		_Float16 x = hf(a);
		if (x == x && x > -65000 && x < 65000)
			to_int(a);
	}
	to_int(0x3c00);
	to_int(0xbc00);
	to_int(0x7bff);
	to_int(0xfbff);
	to_int(0x0000);
	printf("};\n");
	return 0;
}
