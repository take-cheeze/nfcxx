-- __name: the name of a table's type in error messages (luaL_typeerror, luaG_typeerror) and in tostring.
local named = setmetatable({}, {__name = "Point"})
print(tostring(named):match("^Point: ") ~= nil)
print(tostring(setmetatable({}, {__name = 7})):match("^table: ") ~= nil)
print(pcall(function() return string.rep(named, 2) end))
print(pcall(function() return math.floor(named) end))
print(pcall(function() return named() end))
print(pcall(function() return named + 1 end))
print(pcall(function() return named < named end))
print(pcall(function() return named .. "" end))
print(pcall(function() return setmetatable({}, {__name = "X"}) .. "" end))
print(pcall(function() return setmetatable({}, {__name = 1})() end))
print(pcall(function() return table.concat({}, named) end))
print(pcall(function() return ipairs() end))
print(pcall(function() return setmetatable(named, 1) end))
