#!/bin/bash
# Differential test: scripts/build-libclang-edg.rb against scripts/build-libclang-edg.sh (see ../fetch-build/common.sh). The
# compilers (cc, c++, gcc, g++) are stubs: each -o output is created empty, the probes of the host C++ library answer from
# the hooks (g++ -dumpfullversion, g++ --version, g++ -E -v). Nothing is compiled.
here=$(cd "$(dirname "$0")" && pwd -P)
RBM_NAME=build-libclang-edg
. "$here/../fetch-build/common.sh"

# the compilers: the -o outputs are created; FAKE_CC_FAIL makes a compile fail; the probes print the host's answers
# (GNU 13.3.0 unless NO_GNU_VERSION, or CLANG_HOST makes the host clang)
write_compiler() {
  mkdir -p "$SB/fix"
  cat > "$SB/fix/compiler" <<'H'
#!/bin/bash
case "$*" in
  -dumpfullversion) [ -z "$NO_GNU_VERSION" ] || exit 1; echo 13.3.0; exit 0 ;;
  --version) if [ -n "$CLANG_HOST" ]; then echo "clang version 21.0.0"; else echo "g++ (GCC) 13.3.0"; fi; exit 0 ;;
  *" -E "*)
    cat >&2 <<'X'
#include <...> search starts here:
 /usr/include/c++/13
 /usr/include/x86_64-linux-gnu/c++/13
 /usr/include
 /opt/frameworks/Frameworks (framework directory)
End of search list.
X
    exit 0 ;;
esac
[ -z "$FAKE_CC_FAIL" ] || { echo "error: compile failed" >&2; exit 1; }
prev=
for a; do [ "$prev" = -o ] && : > "$a"; prev=$a; done
exit 0
H
}

setup() {
  # the original names itself in the generated header; the port names itself (the one text the oracle is given)
  sed -i 's#Generated by scripts/build-libclang-edg.sh#Generated by scripts/build-libclang-edg.rb#' "$SB/repo/scripts/build-libclang-edg.sh"
  mkdir -p "$SB/hooks"
  write_compiler
  for c in cc c++ gcc g++; do cp "$SB/fix/compiler" "$SB/hooks/$c"; done
  chmod +x "$SB/hooks"/*
  # the sources and headers (the newer-than check reads them), and the front end's archive
  mkdir -p "$SB/repo/lib/libclang-edg/generated" "$SB/repo/lib/libclang-edg/include/clang-c"
  echo '/* clang_edg.c */' > "$SB/repo/lib/libclang-edg/clang_edg.c"
  echo '/* stubs.c */' > "$SB/repo/lib/libclang-edg/generated/stubs.c"
  echo '/* Index.h */' > "$SB/repo/lib/libclang-edg/include/clang-c/Index.h"
  mkdir -p "$SB/repo/build/libclang-edg/cmake/src/nfcxx-so"
  : > "$SB/repo/build/libclang-edg/cmake/src/nfcxx-so/libedgfe-pic.a"
}
setup_no_archive() { setup; rm -f "$SB/repo/build/libclang-edg/cmake/src/nfcxx-so/libedgfe-pic.a"; }
setup_stale() {                 # a library older than the sources: built again
  setup
  echo old > "$SB/repo/build/libclang-edg/libclang-edg.so"
  touch -d '2001-01-01' "$SB/repo/build/libclang-edg/libclang-edg.so"
}
setup_other_out() {             # the front end under LIBCLANG_EDG_OUT
  setup_no_archive
  mkdir -p "$SB/work/edg/cmake/src/nfcxx-so"
  : > "$SB/work/edg/cmake/src/nfcxx-so/libedgfe-pic.a"
}

rbm_case in-process setup ""
RBM_WARM=1 rbm_case up-to-date setup ""
rbm_case no-archive setup_no_archive ""
rbm_case in-process-off setup "LIBCLANG_EDG_IN_PROCESS=0"
rbm_case ldflags setup "LIBCLANG_EDG_LDFLAGS=-Wl,--as-needed"
rbm_case ldflags-empty setup "LIBCLANG_EDG_LDFLAGS="
rbm_case out-and-base setup_other_out "LIBCLANG_EDG_OUT=$SB/work/edg LIBCLANG_EDG_BASE=/opt/edg-base"
rbm_case clang-host setup "CLANG_HOST=1 NO_GNU_VERSION=1"
rbm_case no-gnu-version setup "NO_GNU_VERSION=1"
rbm_case sys-includes-env setup "NFCXX_SYS_INCLUDES=/opt/a:/opt/b::/opt/c"
rbm_case cc-cxx-env setup "CC=gcc CXX=g++ NFCXX_CXX=g++"
rbm_case compile-fails setup "FAKE_CC_FAIL=1"
rbm_case stale-library setup_stale ""
rbm_summary
