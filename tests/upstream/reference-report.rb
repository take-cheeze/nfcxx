# Usage: scripts/mrb tests/upstream/reference-report.rb SNAPSHOT_ROOT
def die(message)
  $stderr.puts message
  exit 1
end
root = ARGV[0]
die('usage: reference-report.rb SNAPSHOT_ROOT') unless root
puts '# Reference examples: measured compile survey'
puts ''
puts 'Generated by `tests/upstream/reference-report.rb`. These are compile-only observations, not conformance assertions or runtime passes.'
puts 'All extracted C++ examples were surveyed with system GCC 15.2.0; language examples were also compiled to objects on the three nfcxx routes.'
puts 'cppreference uses C++23 throughout. cpprefjp language examples use their page standard; library examples use C++23.'
puts 'Newer-draft examples, fragments, intentional errors and library limitations can cause rejection. `mode-unavailable` means the compiler does not recognize the requested dialect flag.'
puts 'The per-invocation budget was 20 seconds, except the corrected sizeof/sizeof... cases rerun with 60 seconds. Timeouts under this budget are not proof of missing support.'
puts ''
puts '| Reference / scope | Examples | Route | Accepted | Rejected | Mode unavailable | Crashed | Timed out |'
puts '| --- | --- | --- | --- | --- | --- | --- | --- |'
['cppreference', 'cpprefjp'].each do |suite|
  ['all', 'language'].each do |scope|
    suffix = scope == 'all' ? '-all' : ''
    inventory = File.open(root + '/' + suite + suffix + '-inventory.tsv', 'rb') { |f| f.read.split("\n")[1..-1] }
    expected = {}
    inventory.each do |line|
      row = line.split("\t", -1)
      die('duplicate inventory ID: ' + row[0]) if expected[row[0]]
      expected[row[0]] = row[1]
    end
    routes = scope == 'all' ? ['host'] : ['host', 'qbe', 'gcc', 'pathb']
    counts = {}; seen = {}
    File.open(root + '/' + suite + '-' + scope + '-survey/results.tsv', 'rb') do |f|
      f.read.split("\n")[1..-1].each do |line|
        row = line.split("\t", -1)
        key = row[1] + ':' + row[4]
        die('invalid/duplicate result: ' + key) if seen[key] || expected[row[1]] != row[2] || !routes.include?(row[4])
        seen[key] = true
        counts[row[4]] ||= {}
        counts[row[4]][row[5]] = (counts[row[4]][row[5]] || 0) + 1
      end
    end
    die('incomplete survey: ' + suite + '/' + scope) unless seen.size == expected.size * routes.size
    routes.each do |route|
      c = counts[route]
      values = ['accepted', 'rejected', 'mode-unavailable', 'crash', 'timeout'].map { |status| c[status] || 0 }
      die('unknown/infrastructure status in survey') unless values.inject(0) { |a, n| a + n } == expected.size
      puts '| ' + ([suite + ' / ' + scope, expected.size.to_s, route] + values.map { |n| n.to_s }).join(' | ') + ' |'
    end
  end
end
puts ''
puts 'The language rows are subsets of the all-example inventories, not additional examples. Host syntax acceptance and nfcxx object compilation test different stages; neither executes unreviewed source.'
puts ''
puts 'cppreference is usable as a large corpus of positive examples after classification. Acceptance is an upper bound on candidates for reviewed runtime checks, not a count of trustworthy regression assertions.'
puts 'Its examples do not provide systematic negative/diagnostic coverage, complete per-paper coverage, or portable exact output for every example.'
puts 'The HTML inventory takes the first code block in each t-example container; multi-block or multi-file examples need manual assembly.'
puts 'cpprefjp provides explicitly tagged examples and standard-specific language pages, making extraction and mode selection easier; a tag still does not establish deterministic behavior or a portable oracle.'
puts ''
puts 'Runtime checks remain explicit: ten cppreference and four cpprefjp examples, four GCC programs, and three LLVM programs. Clang uses five native lit tests; EDG uses its native regression harness.'
puts 'See [setup, scope and known gaps](../../tests/upstream/README.md) and the [PR/nightly plan](cpp-test-ci-plan.md).'
puts 'Raw manifests, per-case logs and TSV results remain under `build/testsuite-snapshots/`.'
