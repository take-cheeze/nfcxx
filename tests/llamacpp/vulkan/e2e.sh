#!/usr/bin/env bash
# End-to-end throughput on the Vulkan backend: llama.cpp's llama-bench on a GGUF model, with ggml and ggml-vulkan as
# tests/llamacpp/vulkan/build.sh compiled them through nfcxx (its objects in OUT/obj). libllama (src/*.cpp, src/models/*.cpp),
# common/*.cpp and llama-bench.cpp are host-only C++ outside what is under test here, so the host g++ compiles them (into
# OUT/e2e); the link is nfcxx's, which the nfcxx objects need (their template instances, .ti beside each object).
# Usage: tests/llamacpp/vulkan/e2e.sh MODEL.gguf [OUT_DIR] [-- llama-bench options]   (default OUT_DIR build/llvk; run build.sh first)
# Env: LLAMA (clone, default build/targets/llama.cpp), JOBS (default 4), NGL (layers on the GPU, default 99),
# BENCH_ARGS (default "-p 512 -n 128 -r 5"), E2E_BUILD_ONLY=1 (build and link only). Set VK_ICD_FILENAMES to pick the GPU.
set -u
root=$(cd "$(dirname "$0")/../../.." && pwd)
model=${1:?usage: e2e.sh MODEL.gguf [OUT_DIR]}
out=${2:-$root/build/llvk}
llama=${LLAMA:-$root/build/targets/llama.cpp}
[ -f "$out/sources" ] || { echo "e2e: no $out/sources (run tests/llamacpp/vulkan/build.sh first)" >&2; exit 2; }
e2e=$out/e2e; mkdir -p "$e2e/gen"
sed 's/@LLAMA_VERSION@/0.0.0/; s/@LLAMA_BUILD_COMMIT@/test/' "$llama/src/llama-version.h.in" > "$e2e/gen/llama-version.h"
# -include algorithm: src/models/clef.cpp calls std::find without <algorithm>, which libstdc++ 15 no longer brings in
cxxflags="-std=c++17 -O2 -include algorithm -I$e2e/gen -I$llama/include -I$llama/src -I$llama/common -I$llama/ggml/include -I$llama/vendor"
# common/build-info.cpp is generated by CMake from its template (the build number and commit are placeholders here)
sed 's/@LLAMA_BUILD_NUMBER@/0/; s/@LLAMA_BUILD_COMMIT@/test/; s/@BUILD_COMPILER@/g++/; s/@BUILD_TARGET@/x86_64-linux/' \
  "$llama/common/build-info.cpp.in" > "$e2e/gen/build-info.cpp"
mapfile -t commons < <(find "$llama/common" -name '*.cpp' ! -name 'build-info.cpp.in' | sort)
srcs=("$llama"/src/*.cpp "$llama"/src/models/*.cpp "${commons[@]}" "$e2e/gen/build-info.cpp" "$llama/vendor/cpp-httplib/httplib.cpp"
      "$llama/tools/llama-bench/llama-bench.cpp" "$llama/tools/llama-bench/main.cpp")
# common/ first on the include path there: its unicode.h is not src/unicode.h (the same name, another API)
cxxcommon="-std=c++17 -O2 -include algorithm -I$e2e/gen -I$llama/common -I$llama/include -I$llama/src -I$llama/ggml/include -I$llama/vendor"
compile() {  # compile SRC: OUT/e2e/<path with / as _>.o, unless it is there
  local o fl=$cxxflags; o=$e2e/$(echo "${1#"$llama"/}" | tr / _).o
  case $1 in "$llama"/common/*|"$e2e"/gen/build-info.cpp) fl=$cxxcommon ;; esac
  [ -f "$o" ] || ${CXX:-g++} $fl -c "$1" -o "$o" || { echo "FAIL compile $1"; return 1; }
}
export -f compile; export llama e2e cxxflags cxxcommon
printf '%s\n' "${srcs[@]}" | xargs -d '\n' -n 1 -P "${JOBS:-4}" bash -c 'compile "$0"' || exit 1
# ggml's objects from build.sh: every source but the test program
objs=(); while IFS=$'\t' read -r f _; do
  case $f in */tests/test-backend-ops.cpp) continue ;; esac
  f=${f#"$llama"/}; f=${f#"$out"/}  # the same object names as build.sh (llama.cpp paths, and OUT paths without OUT)
  objs+=("$out/obj/$(echo "$f" | tr / _).o")
done < "$out/sources"
for s in "${srcs[@]}"; do objs+=("$e2e/$(echo "${s#"$llama"/}" | tr / _).o"); done
# NFCXX_PATH=b: the Path B runtime archive (scripts/pathb-ldrt), as build.sh links it
[ "${NFCXX_PATH:-}" != b ] || objs+=("$("$root/scripts/pathb-ldrt")")
"$root/nfcxx" "${objs[@]}" -fopenmp -lvulkan -lm -lpthread -lstdc++ -lgomp -o "$e2e/llama-bench" \
  > "$e2e/link.log" 2>&1 || { echo "FAIL link: $(grep -m3 'undefined\|error' "$e2e/link.log" | cut -c1-200)"; exit 1; }
echo "linked $e2e/llama-bench"
[ "${E2E_BUILD_ONLY:-0}" = 1 ] && exit 0
# shellcheck disable=SC2086
"$e2e/llama-bench" -m "$model" -ngl "${NGL:-99}" ${BENCH_ARGS:--p 512 -n 128 -r 5}
