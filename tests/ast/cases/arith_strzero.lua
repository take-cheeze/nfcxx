-- integer // and % by zero when an operand is a string: the string metamethod raises the error, so it has no position
local z, s, zs = 0, "7", "0"
local function e(f, ...) print(select(2, pcall(f, ...))) end
e(function() return 5 // z end)
e(function() return 5 % z end)
e(function() return s // z end)
e(function() return s % z end)
e(function() return 5 // zs end)
e(function() return 5 % zs end)
e(function() return "5" // "0" end)
e(function() return s // 0 end)
e(function() return 7 % "0" end)
e(function() return "7" % 0 end)
e(function() return "7.5" % 0 end)
e(function() return 7.5 // zs end)
e(function() return 7 // "0.0" end)
e(function() return "0x10" // zs end)
e(function() return {} // zs end)
e(function() return s // {} end)
e(function() return s // "x" end)
e(function() return s // nil end)
e(function() local a = 3; a = s % z; return a end)
e(function() return s + z end)
e(function() error(select(2, pcall(function() return s % zs end)), 2) end)
print(pcall(function() return s // z end))
