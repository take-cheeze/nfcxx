-- integer and float arithmetic, comparisons, conversions
local function show(...)
  local t = table.pack(...)
  local out = {}
  for i = 1, t.n do out[#out + 1] = tostring(t[i]) .. (math.type(t[i]) and ("(" .. math.type(t[i]) .. ")") or "") end
  print(table.concat(out, " "))
end
