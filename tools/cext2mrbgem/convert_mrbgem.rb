# Python's \w (str patterns: Unicode letters, numbers and underscore), for use inside [...]
WC = '\p{L}\p{N}_'
# Python's \s and str.isspace() (Unicode whitespace plus the \x1c-\x1f separators), for use inside [...]
WSP = '\p{Space}\x1c-\x1f'
SS = "[#{WSP}]*"   # Python \s*
SS1 = "[#{WSP}]+"  # Python \s+
SPACE_RE = /[#{WSP}]/     # Python str.isspace()
ALNUM_RE = /[\p{L}\p{N}]/ # Python str.isalnum()

IDENT_RE = /(?<![#{WC}$])[A-Za-z_][#{WC}]*/
# A definition starts at a line start (Ruby's ^ is a line anchor, as Python's re.M). Return-type words may be split
# across lines (`static VALUE` then `name(...)` on the next line, as bigdecimal and date write them).
DEF_RE = /^[ \t]*((?:(?:static|inline|extern)[ \t\n]+)*)((?:[A-Za-z_][#{WC}]*(?:[ \t\n]+|[ \t\n]*\*[ \t\n\*]*))+?)([A-Za-z_][#{WC}]*)[ \t\n]*\(([^()]*)\)#{SS}(\{|;)/
INC_RE = /#[ \t]*include[ \t]*[<"](ruby(?:\/[#{WC}.\/-]*)?\.h)[>"]/
REG_RE = /(?<![#{WC}$.>])(rb_define_method|rb_define_singleton_method|rb_define_module_function)#{SS}\(/
CLASS_ASSIGN_RE = /(?<![#{WC}$.>])([#{WC}]+)#{SS}=#{SS}rb_define_(?:class|module)(?:_under)?#{SS}\(/
NON_FUNC_WORDS = Set.new(%w[if while for switch return sizeof else do case goto])

# CRuby-looking identifiers that are not in api_map.json are refused.
UNKNOWN_RE = /\A(?:rb_[#{WC}]+|st_[#{WC}]+|ruby_[#{WC}]+|RB_[#{WC}]+|RUBY_[#{WC}]+|R[A-Z]{2,}_[#{WC}]+|RTEST|RBASIC[#{WC}]*|Q(?:nil|true|false|undef)|(?:NUM2|INT2|LONG2|ULONG2|UINT2|DBL2|FIX2|FIXNUM_|ID2|SYM2|CHR2|LL2|ULL2)[#{WC}]*|SYMBOL_P|NIL_P|NIL_OR_UNDEF_P|Check_[#{WC}]+|StringValue[#{WC}]*|T_[A-Z]+|ANYARGS|PRIsVALUE|CLASS_OF|SPECIAL_CONST_P|FL_[#{WC}]+|OBJ_[#{WC}]+)\z/

GEM_NAME_RE = /\A[A-Za-z][A-Za-z0-9_-]*\n?\z/

# ---- Python-compatible helpers -------------------------------------------------

# Python str.strip() (Unicode whitespace)
def py_strip(s)
  s.sub(/\A[#{WSP}]+/, '').sub(/[#{WSP}]+\z/, '')
end

# Python str.split() with no argument (whitespace runs, no empty items)
def py_split_ws(s)
  s.split(/[#{WSP}]+/).reject(&:empty?)
end

# Python slice s[a:b] (negative and out-of-range indices clamp, as in Python)
def psl(s, a, b = nil)
  n = s.length
  a += n if a < 0
  b = n if b.nil?
  b += n if b < 0
  a = 0 if a < 0
  a = n if a > n
  b = n if b > n
  return '' if b <= a
  s[a, b - a]
end

# Python str.find(sub, start): index or -1
def pyfind(s, sub, start = 0)
  s.index(sub, start) || -1
end

# Python re.finditer: MatchData objects, with character offsets (begin/end)
def finditer(re, s)
  out = []
  s.scan(re) { out << Regexp.last_match }
  out
end

# Python repr() of a str
def py_repr(s)
  quote = (s.include?("'") && !s.include?('"')) ? '"' : "'"
  out = String.new(quote) # a copy: appending to quote itself would change the closing quote
  s.each_codepoint do |cp|
    ch = [cp].pack('U')
    piece =
      if ch == quote || ch == '\\' then '\\' + ch
      elsif cp == 9 then '\\t'
      elsif cp == 10 then '\\n'
      elsif cp == 13 then '\\r'
      elsif cp < 0x20 || cp == 0x7f then format('\\x%02x', cp)
      elsif cp < 0x7f then ch
      elsif ch.match?(/[\p{C}\p{Z}]/) then (cp <= 0xff ? format('\\x%02x', cp) : (cp <= 0xffff ? format('\\u%04x', cp) : format('\\U%08x', cp)))
      else ch
      end
    out << piece
  end
  out << quote
end

# json.dump(obj, fh, indent=1) as Python writes it: ensure_ascii escapes, ": " and ",\n" separators
def py_json_str(s)
  out = +'"'
  s.each_codepoint do |cp|
    out << case cp
           when 0x22 then '\\"'
           when 0x5c then '\\\\'
           when 0x0a then '\\n'
           when 0x0d then '\\r'
           when 0x09 then '\\t'
           when 0x08 then '\\b'
           when 0x0c then '\\f'
           when 0x20..0x7e then cp.chr
           when 0..0xffff then format('\\u%04x', cp)
           else
             v = cp - 0x10000
             format('\\u%04x\\u%04x', 0xd800 | (v >> 10), 0xdc00 | (v & 0x3ff))
           end
  end
  out << '"'
end

def py_json(v, level = 0)
  case v
  when nil then 'null'
  when true then 'true'
  when false then 'false'
  when Integer then v.to_s
  when String then py_json_str(v)
  when Array
    return '[]' if v.empty?
    "[\n" + v.map { |x| ' ' * (level + 1) + py_json(x, level + 1) }.join(",\n") + "\n" + ' ' * level + ']'
  when Hash
    return '{}' if v.empty?
    "{\n" + v.map { |k, x| ' ' * (level + 1) + py_json_str(k.to_s) + ': ' + py_json(x, level + 1) }.join(",\n") +
      "\n" + ' ' * level + '}'
  else
    raise TypeError, "cannot serialise #{v.class}"
  end
end

# Input is read as text as Python did: UTF-8 with bad bytes replaced, and universal newlines (CRLF and CR become LF).
def read_text(path)
  File.binread(path).force_encoding(Encoding::UTF_8).scrub.gsub(/\r\n?/, "\n")
end

def write_bytes(path, text)
  File.binwrite(path, text)
end

def line_of(text, pos)
  psl(text, 0, pos).count("\n") + 1
end

def blank(s)
  s.gsub(/[^\n]/, ' ')
end

def mask_c(src)
  out = []
  i = 0
  n = src.length
  while i < n
    c = src[i]
    if src[i, 2] == '//'
      j = pyfind(src, "\n", i)
      j = n if j < 0
      out << blank(psl(src, i, j))
      i = j
    elsif src[i, 2] == '/*'
      j = pyfind(src, '*/', i + 2)
      j = j < 0 ? n : j + 2
      out << blank(psl(src, i, j))
      i = j
    elsif c == '"' || c == "'"
      j = i + 1
      while j < n && src[j] != c && src[j] != "\n"
        j += src[j] == '\\' ? 2 : 1
      end
      j = n if j > n
      out << c << blank(psl(src, i + 1, j))
      if j < n && src[j] == c
        out << c
        i = j + 1
      else
        i = j
      end
    else
      out << c
      i += 1
    end
  end
  out.join
end

def match_close(masked, open_pos)
  depth = 0
  k = open_pos
  while k < masked.length
    ch = masked[k]
    if '([{'.include?(ch)
      depth += 1
    elsif ')]}'.include?(ch)
      depth -= 1
      return k if depth == 0
    end
    k += 1
  end
  -1
end

def trim(masked, s, e)
  s += 1 while s < e && SPACE_RE.match?(masked[s])
  e -= 1 while e > s && SPACE_RE.match?(masked[e - 1])
  [s, e]
end

def split_args(masked, open_pos, close_pos)
  return [] if py_strip(psl(masked, open_pos + 1, close_pos)).empty?
  spans = []
  depth = 0
  start = open_pos + 1
  (open_pos + 1...close_pos).each do |k|
    ch = masked[k]
    if '([{'.include?(ch)
      depth += 1
    elsif ')]}'.include?(ch)
      depth -= 1
    elsif ch == ',' && depth == 0
      spans << [start, k]
      start = k + 1
    end
  end
  spans << [start, close_pos]
  spans.map { |s, e| trim(masked, s, e) }
end

def next_nonspace(masked, pos)
  k = pos
  k += 1 while k < masked.length && SPACE_RE.match?(masked[k])
  k < masked.length ? k : -1
end

def prev_nonspace(masked, pos)
  k = pos
  k -= 1 while k >= 0 && SPACE_RE.match?(masked[k])
  k
end

def is_member(masked, s)
  j = prev_nonspace(masked, s - 1)
  return false if j < 0
  masked[j] == '.' || (masked[j] == '>' && j > 0 && masked[j - 1] == '-')
end

# (callee name, top-level argument index) of the call enclosing pos, or [nil, nil]
def call_context(masked, pos)
  depth = 0
  commas = 0
  k = pos - 1
  while k >= 0
    ch = masked[k]
    if ')]}'.include?(ch)
      depth += 1
    elsif '([{'.include?(ch)
      if depth == 0
        return [nil, nil] if ch != '('
        j = prev_nonspace(masked, k - 1)
        e = j + 1
        while j >= 0 && (ALNUM_RE.match?(masked[j]) || masked[j] == '_')
          j -= 1
        end
        name = psl(masked, j + 1, e)
        return [(name.empty? ? nil : name), commas]
      end
      depth -= 1
    elsif ch == ',' && depth == 0
      commas += 1
    elsif ch == ';' && depth == 0
      return [nil, nil]
    end
    k -= 1
  end
  [nil, nil]
end

# (opening character, callee name) of the innermost unclosed bracket before pos in the same statement; the
# callee is the identifier before a '(' (nil when there is none). [nil, nil] at the statement start.
def innermost_open(masked, pos)
  depth = 0
  k = pos - 1
  while k >= 0
    ch = masked[k]
    if ')]}'.include?(ch)
      depth += 1
    elsif '([{'.include?(ch)
      if depth == 0
        return [ch, nil] if ch != '('
        j = prev_nonspace(masked, k - 1)
        e = j + 1
        j -= 1 while j >= 0 && (ALNUM_RE.match?(masked[j]) || masked[j] == '_')
        name = psl(masked, j + 1, e)
        return ['(', (name.empty? ? nil : name)]
      end
      depth -= 1
    elsif ch == ';' && depth == 0
      return [nil, nil]
    end
    k -= 1
  end
  [nil, nil]
end

# a use of a global-state helper in a function that has no mruby state (see global_use)
CTX_REASON = 'helper needs mruby state, and a use is in a function with no mruby state in scope (not a method, Init or threaded helper)'.freeze

# calls that may keep a pointer they are given (registration, storage, threads, data objects): a helper passed to one
# of them is not a use that stays inside the method call
# rb_thread_* runs its function on another thread (rb_thread_call_without_gvl): the state must not be used there.
STORE_CALL_RE = /\A(?:rb_define|mrb_define|rb_gc_register|rb_global|rb_set_end|rb_iv_set|rb_ivar_set|rb_const_set|
  rb_hash_aset|rb_ary_store|rb_ary_push|rb_thread_|nfcx_thread_|rb_obj_call_init|rb_data_|st_|Data_|TypedData_)/x

# the end of the logical line (a backslash-newline continues it) that starts before k
def logical_line_end(masked, k)
  while k < masked.length
    return k if masked[k] == "\n" && (k == 0 || masked[k - 1] != '\\')
    k += 1
  end
  masked.length
end

def map_types(s, types)
  types.each do |ctype, mtype|
    if ctype == 'ID'
      s = s.gsub(/(?<![#{WC}])ID(?![#{WC}])(?=[#{WSP}]+[A-Za-z_])/) { mtype }
    else
      s = s.gsub(/(?<![#{WC}])#{Regexp.escape(ctype)}(?![#{WC}])/) { mtype }
    end
  end
  s
end

class Edits
  def initialize
    @items = []
  end

  def add(s, e, text)
    @items << [s, e, text]
  end

  def overlaps(s, e)
    @items.any? { |a, b, _| a < e && s < b }
  end

  def apply(text)
    # stable sort: edits at the same position keep their insertion order, as Python's sorted() does
    items = @items.each_with_index.sort_by { |(s, e, _), i| [s, e, i] }.map(&:first)
    items.each_cons(2) do |p, q|
      raise "internal: overlapping edits at #{q[0]}" if q[0] < p[1]
    end
    # the text between the edits is copied once, in order (the same result as Python's reversed splices)
    chars = text.chars
    out = +''
    pos = 0
    items.each do |s, e, t|
      out << chars[pos...s].join << t
      pos = e
    end
    out << chars[pos..].join
  end
end

class Converter
  def initialize(cext_dir, out_dir, name = nil, scanner_mode = 'auto', defines = [])
    @scanner_mode = scanner_mode  # auto, libclang or regex
    @scanner = 'regex'            # the scanner used: libclang or regex (choose_scanner)
    @scanner_reason = nil
    @scanner_fallback = []        # files the regex scan read although libclang was used
    @excluded_defs = Set.new      # names defined in text the libclang scan does not list (see libclang_declarations)
    @defines = defines            # -D options for the libclang front end (NAME or NAME=VALUE), as extconf would set
    @cext_dir = File.absolute_path(cext_dir)
    @out_dir = File.absolute_path(out_dir)
    base = @cext_dir.sub(%r{/+\z}, '')
    base = base.include?('/') ? base[(base.rindex('/') + 1)..] : base
    @name = (name.nil? || name.empty?) ? base : name
    @funcname = @name.tr('-', '_')
    amap = JSON.parse(File.read(MAP_PATH, encoding: 'UTF-8'))
    @entries = amap['entries']
    @types = amap['types']
    @includes = amap['includes']
    @special_pos = amap['special_arg_positions_class_only']
    @type_check_refused = amap['type_check_refused'] || {}
    @files = {}   # rel -> {'text','masked','kind'}
    @edits = {}   # rel -> Edits
    @ignored = []
    @warnings = []
    @refusals = []
    @rewrites = []
    @class_vars = Set.new
    @decl_name_pos = Set.new
    @regs = []
    @reg_by_call = {}
    @reg_names = Set.new
    @valid_reg_names = Set.new  # registered functions whose registration survived check_refs
    @decls = []   # dicts for function prototypes and definitions
    @defs = {}    # name -> [def dicts]
    @init_defs = []
    @occ = {}     # identifier -> [[rel, start, end]]
    @needs = Set.new
    @helper_names = Set.new
    @init_rel = nil
    @dead_inits = []
    @variadic = {}
    @local_macros = Set.new
  end

  # ---- reporting ---------------------------------------------------------
  def extconf_entry
    path = File.join(@cext_dir, 'extconf.rb')
    return nil unless File.file?(path)
    m = /create_makefile\(#{SS}['"]([#{WC}\/.-]+)['"]/.match(read_text(path))
    m ? m[1] : nil
  end

  def in_dead_init(rel, pos)
    @dead_inits.any? { |d| d['file'] == rel && d['hstart'] <= pos && pos <= d['body_end'] }
  end

  def enclosing_func(rel, pos)
    @defs.each_value do |lst|
      lst.each do |d|
        return d if d['file'] == rel && d.key?('brace') && d['brace'] < pos && pos < d['body_end']
      end
    end
    nil
  end

  def refuse(rel, pos, api, reason)
    if rel.nil?
      @refusals << { 'file' => '(gem)', 'line' => 0, 'api' => api, 'reason' => reason }
      return
    end
    return if in_dead_init(rel, pos)
    text = @files[rel]['text']
    @refusals << { 'file' => rel, 'line' => line_of(text, pos), 'api' => api, 'reason' => reason }
    # a marker strictly inside a declaration's header would overlap the header rewrite (process step 2); the
    # refusal is still recorded and the output is still marked not buildable
    return if @decls.any? { |d| d['file'] == rel && d['hstart'] < pos && pos < d['hend'] }
    @edits[rel].add(pos, pos, "/* BC2CPP-MRBGEM REFUSED: #{api} */ ")
  end

  def uses_uv_thread?
    @rewrites.any? { |r| r['to'] == 'nfcx_thread_call_without_gvl' }
  end

  def rewrite(rel, pos, src, dst, caveat = nil)
    text = @files[rel]['text']
    rec = { 'file' => rel, 'line' => line_of(text, pos), 'from' => src, 'to' => dst }
    rec['caveat'] = caveat if caveat
    @rewrites << rec
  end

  # ---- stage 1: load -----------------------------------------------------
  def load
    abort "error: not a directory: #{@cext_dir}" unless File.directory?(@cext_dir)
    abort "error: cannot derive a gem name from #{@cext_dir}" unless GEM_NAME_RE.match?(@name)
    Dir.children(@cext_dir).reject { |n| n.start_with?('.') }.sort.each do |base|
      path = File.join(@cext_dir, base)
      if File.directory?(path)
        @ignored << [base, 'subdirectory not converted']
        next
      end
      unless base.end_with?('.c') || base.end_with?('.h')
        @ignored << [base, 'not a C source or header (read by nothing; extconf.rb is never run)']
        next
      end
      text = read_text(path)
      kind = base.end_with?('.c') ? 'src' : 'hdr'
      @files[base] = { 'text' => text, 'masked' => mask_c(text), 'kind' => kind }
      @edits[base] = Edits.new
      # gem_init.c is the generated file; the input's own copy is refused (set up before the refusal is recorded)
      refuse(base, 0, 'gem_init.c', 'name collides with the generated gem_init.c') if base == 'gem_init.c'
    end
  end

  # ---- local macros: names the input defines itself -----------------------
  # A name is local when every #define of it in the input is unconditional, apart from the include guard of a
  # header. A #define under any other conditional (or #if 0) may be a compatibility fallback for a CRuby name
  # (e.g. #if !defined(HAVE_...) #define rb_x ...), so the name stays refused. An #undef must be unconditional and
  # no use may follow it in its file. A name whose first use in its own file precedes the #define is not local
  # either: that use is the CRuby name. A local name is kept as it is (it is not a CRuby API); the body of its
  # macro is still scanned like any other text, so a CRuby API used there is checked.
  GUARD_RE = /(?:_h_*|_included)\z/i

  def scan_local_macros
    defined = {}     # name -> [[rel, directive position, tainted]]
    undefined = {}   # name -> [[rel, directive position, tainted]]
    @files.each do |rel, f|
      stack = []     # one frame per open conditional: [guard?, condition texts]
      f['masked'].scan(/^[ \t]*#[ \t]*(\w+)([^\n]*(?:\\\n[^\n]*)*)/) do
        kw, rest, pos = $1, $2.strip, $~.begin(0)
        case kw
        when 'if', 'ifdef', 'ifndef'
          gname = rest[/\A\w+\z/] if kw == 'ifndef'
          gname ||= rest[/\A!\s*defined\s*\(?\s*(\w+)\s*\)?\z/, 1] if kw == 'if'
          guard = stack.empty? && f['kind'] == 'hdr' && !gname.nil? && GUARD_RE.match?(gname)
          stack.push([guard, [rest], false])
        when 'elif', 'else'
          if stack.any?
            stack.last[1] << rest
            stack.last[0] = false   # an include guard has no other branch
          end
        when 'endif' then stack.pop
        when 'define'
          name = rest[/\A(\w+)/, 1]
          next if name.nil?
          tainted = stack.any? { |g, _, _| !g }
          (defined[name] ||= []) << [rel, pos, tainted]
        when 'undef'
          name = rest[/\A(\w+)/, 1]
          (undefined[name] ||= []) << [rel, pos, stack.any? { |g, _, _| !g }] if name
        end
      end
    end
    @local_macros = Set.new
    defined.each do |name, defs|
      next if defs.any? { |_, _, t| t }
      use_re = /(?<![#{WC}$])#{Regexp.escape(name)}(?![#{WC}])/
      # an #undef ends the gem's meaning: it must be unconditional, and no use of the name may follow it
      undone = (undefined[name] || []).any? do |rel, pos, t|
        masked = @files[rel]['masked']
        t || !masked.index(use_re, masked.index("\n", pos) || masked.length).nil?
      end
      next if undone
      early = defs.any? do |rel, pos, _|
        first = @files[rel]['masked'].index(use_re)
        !first.nil? && first < pos
      end
      @local_macros << name unless early
    end
  end

  # ---- local variables and struct tags the input declares ----------------
  # A parameter or top-level local of a function definition is local when every occurrence of its name in the input
  # lies inside a function that declares it, from the declaration on: within that function it shadows any CRuby name
  # of the same spelling, and no other occurrence can refer to it. A class variable is never local this way. A
  # struct, union or enum tag the input defines (with a body) is in the tag namespace, so `struct NAME` with that tag
  # is local; a forward declaration is not enough, since the definition may be CRuby's.
  NOT_A_TYPE = %w[return goto else case typedef sizeof break continue do].freeze

  def scan_local_names
    @local_tags = Set.new
    @files.each_value do |f|
      f['masked'].scan(/\b(?:struct|union|enum)[ \t\n]+([A-Za-z_][#{WC}]*)[ \t\n]*\{/) { @local_tags << $1 }
    end
    cands = Hash.new { |h, k| h[k] = [] }   # name -> [[rel, lo, hi, declaration position]]
    @defs.values.flatten.each do |d|
      next unless d.key?('body_end')
      span = [d['file'], d['hstart'], d['body_end']]
      param_names(d).each { |n| cands[n] << [*span, d['hstart']] }
      body_top_declarations(d).each { |n, pos| cands[n] << [*span, pos] }
    end
    @local_var_occ = Set.new
    cands.each do |name, list|
      next if @class_vars.include?(name) || !@occ.key?(name)
      occs = @occ[name]
      covered = occs.all? do |orel, s, _|
        list.any? { |rel, lo, hi, dpos| rel == orel && lo <= s && s < hi && s >= dpos }
      end
      occs.each { |orel, s, _| @local_var_occ << [orel, s] } if covered
    end
  end

  # [name, declaration position] for the declarators of the top-level declarations in a function body
  def body_top_declarations(d)
    masked = @files[d['file']]['masked']
    out = []
    depth = 0
    seg = d['brace'] + 1
    i = seg
    while i < d['body_end']
      c = masked[i]
      if c == '{'
        depth += 1
      elsif c == '}'
        depth -= 1
        seg = i + 1 if depth.zero?
      elsif c == ';' && depth.zero?
        text = masked[seg...i]
        head = /\A\s*(?:(?:static|const|volatile|unsigned|signed|struct|union|enum)\s+)*([A-Za-z_]\w*)\s+(?=[*A-Za-z_])/.match(text)
        if head && !NOT_A_TYPE.include?(head[1])
          rest = text[head.end(0)..]
          parts, cur, pd = [], +'', 0
          rest.each_char do |ch|
            pd += 1 if ch == '('
            pd -= 1 if ch == ')'
            if ch == ',' && pd.zero?
              parts << cur
              cur = +''
            else
              cur << ch
            end
          end
          parts << cur
          parts.each do |part|
            nm = part.sub(/=.*\z/m, '')[/([A-Za-z_]\w*)\s*(?:\[[^\]]*\]\s*)*\z/, 1]
            out << [nm, seg] if nm
          end
        end
        seg = i + 1
      end
      i += 1
    end
    out
  end

  # ---- stage 2: classes, registrations, definitions -----------------------
  def scan
    @files.each_value do |f|
      finditer(CLASS_ASSIGN_RE, f['masked']).each { |m| @class_vars << m[1] }
    end
    @files.each do |rel, f|
      next unless f['kind'] == 'src'
      text, masked = f['text'], f['masked']
      finditer(REG_RE, masked).each do |m|
        cs = m.begin(1)
        op = m.end(0) - 1
        cp = match_close(masked, op)
        rec = { 'file' => rel, 'call' => cs, 'open' => op, 'close' => cp, 'api' => m[1],
                'error' => nil, 'func' => nil, 'argc' => nil, 'target' => nil,
                'func_span' => nil, 'argc_span' => nil }
        if cp < 0
          rec['error'] = 'unbalanced parentheses in registration call'
        else
          args = split_args(masked, op, cp)
          if args.size != 4
            rec['error'] = "registration call has #{args.size} arguments, expected 4"
          else
            (ts, te), (ns, ne), (fs, fe), (as_, ae) = args
            rec['target'] = py_strip(psl(text, ts, te))
            nm = /\A"([^"\\\n]*)"\z/.match(py_strip(psl(text, ns, ne)))
            fm = /\A(?:\(#{SS}VALUE#{SS}\(#{SS}\*#{SS}\)#{SS}\(#{SS}ANYARGS#{SS}\)#{SS}\)#{SS})?([A-Za-z_][#{WC}]*)\z/
                 .match(py_strip(psl(text, fs, fe)))
            am = /\A-?[0-9]+\z/.match(py_strip(psl(text, as_, ae)))
            rec['func_span'] = [fs, fe]
            rec['argc_span'] = [as_, ae]
            if am.nil?
              rec['error'] = 'argc is not an integer literal'
            elsif am[0].to_i < -1
              # -1 is the variadic form (int argc, VALUE *argv, VALUE self); -2 takes an array
              rec['error'] = "argc #{am[0]} (array form) is not in the supported subset"
            elsif fm.nil?
              rec['error'] = 'method function argument is not a plain function name ' \
                             '(only the VALUE (*)(ANYARGS) cast is handled)'
            elsif nm.nil?
              rec['error'] = 'method name is not a plain string literal'
            else
              rec['func'] = fm[1]
              rec['argc'] = am[0].to_i
              rec['name'] = nm[1]
            end
          end
        end
        @regs << rec
        @reg_by_call[[rel, cs]] = rec
      end
    end
    # one arity per registered function
    arities = {}
    @regs.each do |r|
      (arities[r['func']] ||= Set.new) << r['argc'] if r['error'].nil?
    end
    @regs.each do |r|
      r['error'] = "function #{r['func']} is registered with conflicting arities" if r['error'].nil? && arities[r['func']].size > 1
    end
    @regs.each { |r| @reg_names << r['func'] if r['error'].nil? }
    # declarations and definitions, from the scanner chosen at start (see declarations_by_file)
    declarations_by_file.each do |rel, decls|
      f = @files[rel]
      decls.each do |d|
        next if f['kind'] != 'src' && !d['proto'] # a function body in a header is not converted; its prototypes are
        next if NON_FUNC_WORDS.include?(d['name']) || NON_FUNC_WORDS.include?(py_split_ws(d['ret']).last)
        unless d['proto']
          (@defs[d['name']] ||= []) << d
          @init_defs << d if d['name'].start_with?('Init_')
        end
        @decls << d
      end
    end
    # class variables declared as VALUE (decl name positions are skipped later)
    @files.each do |rel, f|
      @class_vars.each do |c|
        finditer(/(?<![#{WC}])VALUE(?![#{WC}])#{SS1}#{Regexp.escape(c)}(?![#{WC}])(?=#{SS}[=;,\[])/, f['masked'])
          .each { |m| @decl_name_pos << [rel, m.end(0) - c.length] }
      end
    end
  end

  # ---- declaration scanners ----------------------------------------------
  # The scanner is chosen once, before the scan. auto uses libclang-edg when it loads and the regex scan otherwise;
  # libclang forces it (an unavailable library stops the conversion); regex never loads it.
  def choose_scanner
    if @scanner_mode == 'regex'
      @scanner = 'regex'
      return
    end
    ok, why = DeclScan.available?
    if ok
      @scanner = 'libclang'
    elsif @scanner_mode == 'libclang'
      abort "error: libclang scanner unavailable: #{why}"
    else
      @scanner = 'regex'
      @scanner_reason = "libclang-edg not used: #{why}"
    end
  end

  # {rel => [declaration dicts]} for every input file. With libclang, a file the front end cannot parse (a header that
  # needs its includer's types, or a configuration that needs extconf's defines) is read by the regex scan and is
  # listed in scanner_fallback. The fallback is per file: the other files keep the libclang records.
  def declarations_by_file
    result = {}
    @scanner_fallback = []
    @files.each do |rel, f|
      if @scanner == 'libclang'
        begin
          decls, skipped = libclang_declarations(rel, f)
          skipped.each { |line, why| @warnings << { 'file' => rel, 'line' => line, 'api' => 'declaration scan', 'reason' => why } }
          result[rel] = decls
          next
        rescue DeclScan::Error => e
          @scanner_fallback << { 'file' => rel, 'reason' => e.message }
        end
      end
      result[rel] = regex_declarations(rel, f)
    end
    @scanner = 'regex' if @scanner == 'libclang' && @scanner_fallback.size == @files.size
    result
  end

  # [records, skipped] from libclang-edg: the function declarations of the main file (decl_scan.rb). libclang-edg
  # lists one record per function entity, so a prototype with a definition in the same file is not listed; the
  # prototypes of the names it lists are taken from the text, as the regex scan finds them.
  def libclang_declarations(rel, f)
    dirs = [@cext_dir]
    dirs += DeclScan.ruby_include_dirs if INC_RE.match?(f['text'])
    recs, skipped = DeclScan.scan_file(File.join(@cext_dir, rel), rel, f['text'], f['masked'],
                                       f['kind'] != 'src', dirs, @defines)
    names = recs.map { |d| d['name'] }.to_set
    listed = recs.map { |d| d['po'] }.to_set
    text_decls = regex_declarations(rel, f)
    extra = text_decls.select { |d| d['proto'] && names.include?(d['name']) && !listed.include?(d['po']) }
    # a definition the text has and the front end does not list is excluded by its #if (or is not a definition)
    text_decls.each { |d| @excluded_defs << d['name'] if !d['proto'] && !names.include?(d['name']) }
    [(recs + extra).sort_by { |d| d['hstart'] }, skipped]
  end

  # The declaration records of one file from DEF_RE (the regex scan)
  def regex_declarations(rel, f)
    text, masked = f['text'], f['masked']
    out = []
    finditer(DEF_RE, masked).each do |m|
      storage, name, term = m[1], m[3], m[5]
      ret = m[2].sub(/[#{WSP}\*]+\z/, '') # trailing pointer stars are dropped, as before
      po = pyfind(masked, '(', m.begin(3))
      pc = pyfind(masked, ')', po)
      d = { 'file' => rel, 'name' => name, 'storage' => storage, 'ret' => ret,
            'hstart' => m.begin(0), 'po' => po, 'pc' => pc,
            'params' => psl(text, po + 1, pc), 'proto' => term == ';', 'hdr' => f['kind'] != 'src' }
      if term == '{'
        d['brace'] = m.end(0) - 1
        d['body_end'] = match_close(masked, d['brace'])
        d['hend'] = d['brace']
      else
        d['hend'] = pc + 1
      end
      out << d
    end
    out
  end

  def build_occurrences
    @files.each do |rel, f|
      f['masked'].scan(IDENT_RE) do
        m = Regexp.last_match
        next if is_member(f['masked'], m.begin(0))
        (@occ[m[0]] ||= []) << [rel, m.begin(0), m.end(0)]
      end
    end
  end

  def body_idents(d)
    masked = @files[d['file']]['masked']
    Set.new(psl(masked, d['brace'], d['body_end'] + 1).scan(IDENT_RE))
  end

  def compute_needs
    ids = {}
    @defs.each do |name, lst|
      lst.each { |d| (ids[name] ||= Set.new).merge(body_idents(d)) }
    end
    forced = @reg_names | Set.new(@init_defs.map { |d| d['name'] })
    needs = Set.new(forced)
    ids.each do |name, s|
      needs << name if s.any? { |i| (@entries[i] || {})['needs_mrb'] }
    end
    changed = true
    while changed
      changed = false
      ids.each do |name, s|
        next if needs.include?(name)
        if s.any? { |c| needs.include?(c) && @defs.key?(c) }
          needs << name
          changed = true
        end
      end
    end
    @needs = needs
  end

  def check_refs
    # Init functions: CRuby calls only Init_<entry>, where <entry> is the name extconf.rb passes to
    # create_makefile. Other Init_ functions are dead code in the extension: they are kept under #if 0.
    @dead_inits = []
    entry = extconf_entry
    if entry && !@init_defs.empty?
      want = "Init_#{entry.split('/', -1).last}"
      chosen = @init_defs.select { |d| d['name'] == want }
      if !chosen.empty?
        @dead_inits = @init_defs.reject { |d| d.equal?(chosen[0]) }
        @init_defs = chosen
        @dead_inits.each do |d|
          @ignored << [d['file'], "Init_ function #{d['name']} is not the entry (create_makefile names #{entry}): kept under #if 0"]
        end
      else
        refuse(nil, 0, want, "create_makefile names #{entry} but no #{want} is defined in the input")
      end
    end
    @init_defs[1..].to_a.each do |extra|
      refuse(extra['file'], extra['hstart'], extra['name'], 'multiple Init_ functions in one extension are not supported')
    end
    if !@init_defs.empty?
      @init_rel = @init_defs[0]['file']
    else
      refuse(nil, 0, "Init_#{@name}", 'no Init_<name> function found')
    end
    init_first = @init_defs.empty? ? nil : @init_defs[0]['name']
    # registered functions: must be defined; must not be called directly
    @regs.each do |r|
      next unless r['error'].nil?
      next if @defs.key?(r['func'])
      why = if @excluded_defs.include?(r['func'])
              'registered function has no active definition: its only definition is in text the front end excludes'
            else
              'registered function has no definition in the input'
            end
      refuse(r['file'], r['call'], r['func'], why)
      r['error'] = why
    end
    valid_reg = @regs.select { |r| r['error'].nil? }
    @valid_reg_names = Set.new(valid_reg.map { |r| r['func'] })
    # variadic methods (argc -1): (argc, argv, self) parameter names, used by rb_scan_args
    @variadic = {}
    valid_reg.each do |r|
      next unless r['argc'] == -1 && @defs.key?(r['func'])
      p = variadic_params(@defs[r['func']][0])
      @variadic[r['func']] = p if p
    end
    # Python iterated a set here; sorted, so the refusals come out in the same order on every run
    @reg_names.to_a.sort.each do |name|
      (@occ[name] || []).each do |rel, s, _e|
        next if valid_reg.any? { |r| rel == r['file'] && r['open'] <= s && s <= r['close'] }
        next if @decls.any? { |d| d['name'] == name && rel == d['file'] && d['hstart'] <= s && s < d['hend'] }
        refuse(rel, s, name, 'registered method function is also called directly (not supported)')
      end
    end
    # helper functions that need the mruby state are threaded: the mrb argument is added to the definition, to
    # every prototype (in the .c and .h files, which are scanned) and to every call site. A use is safe when it
    # is a direct call inside a function body; a use anywhere else is refused. A static helper cannot be called
    # from another file, so its uses are all in its own file; a non-static one is threaded with a caveat (its
    # signature changes, so callers outside the input would need the argument too). Every caller of a helper is
    # itself in needs, so it either gets mrb (a threaded helper, a registered method or Init) or has a refusal of
    # its own; the check after the loop makes that explicit.
    cands = Set.new
    @needs.to_a.sort.each do |name|
      next if @reg_names.include?(name) || name == init_first || !@defs.key?(name)
      cands << name if @defs[name].size == 1
    end

    helper_uses = lambda do |name|
      out = []
      (@occ[name] || []).each do |rel, s, e|
        next if @decls.any? { |d| d['name'] == name && rel == d['file'] && d['hstart'] <= s && s < d['hend'] }
        next if in_dead_init(rel, s)
        masked = @files[rel]['masked']
        nx = next_nonspace(masked, e)
        direct = nx >= 0 && masked[nx] == '('
        out << [rel, s, direct, enclosing_func(rel, s)]
      end
      out
    end

    shadowed = lambda do |name, fn|
      # a parameter or local of the enclosing function with the helper's name hides the helper there
      next true if param_names(fn).include?(name)
      n = Regexp.escape(name)
      body = psl(@files[fn['file']]['masked'], fn['brace'], fn['body_end'] + 1)
      !(body =~ /(?<![#{WC}])(?!return(?![#{WC}])|else(?![#{WC}])|case(?![#{WC}])|goto(?![#{WC}]))[A-Za-z_][#{WC}]*[ \t\n\*]+#{n}#{SS}[=;,\[)]|\(#{SS}\*#{SS}#{n}#{SS}\)/).nil?
    end

    # why a use of a helper through its address (not a direct call) cannot take mrb, or nil (see value_problem below)
    value_problem = lambda do |rel, s, name|
      masked = @files[rel]['masked']
      open, callee = innermost_open(masked, s)
      before = prev_nonspace(masked, s - 1)
      after = next_nonspace(masked, s + name.length)
      if open != '(' || callee.nil?
        'its address is assigned or stored, so the pointer may escape the method context'
      elsif !(before >= 0 && '(,'.include?(masked[before])) || after < 0 || !')'.include?(masked[after]) && masked[after] != ','
        'the pointer is part of an expression, not a plain argument'
      elsif STORE_CALL_RE.match?(callee) || @defs.key?(callee) || !@entries.key?(callee)
        "the pointer is passed to #{callee}, which may keep it"
      end
    end

    use_problem = lambda do |name, use|
      rel, s, direct, fn = use
      if !direct
        # the address is kept or passed on, so the helper's signature cannot gain mrb; the reason says how
        why = value_problem.call(rel, s, name) || 'the pointer is passed as a value, and the helper would gain an argument'
        next "helper needs the mruby state threaded in, but is used outside a direct call (not supported): #{why}"
      end
      if fn.nil?
        next ('helper needs the mruby state threaded in, but the call is not in a function definition the ' \
              'converter recognises (a macro-decorated definition, or file scope) (not supported)')
      end
      if shadowed.call(name, fn)
        next 'helper needs the mruby state threaded in, but its name is shadowed in the calling function (not supported)'
      end
      nil
    end

    uses = {}
    cands.each { |name| uses[name] = helper_uses.call(name) }
    cands.to_a.sort.each do |name|
      cands.delete(name) if uses[name].any? { |u| use_problem.call(name, u) }
    end
    @helper_names = cands
    cands.to_a.sort.each do |name|
      d0 = @defs[name][0]
      next if d0['storage'].split.include?('static')
      rewrite(d0['file'], d0['hstart'], name, "mrb-threaded #{name}",
              'non-static helper: its signature gains the mrb argument; callers outside the input would need it too')
    end
    # Global state path (the design in the comment at @global_name). A needs-helper the threading path refused is not
    # threaded: it uses the file-scope state @global_name, which the registered methods and Init set on entry and
    # restore on exit (process, wrap_returns). Its uses must be direct calls, or a function pointer passed as an
    # argument to a call that does not keep it, inside a function with the mruby state: a registered method, Init, a
    # threaded helper or another helper of this set. The set is the greatest fixpoint: a helper leaves it when one of
    # its uses fails, and its callers are then checked again.
    @global_name = "#{@funcname}_bc2_mrb"
    gcands = Set.new
    @needs.to_a.sort.each do |name|
      next if @reg_names.include?(name) || name == init_first || !@defs.key?(name) || cands.include?(name)
      gcands << name if @defs[name].size == 1
    end
    with_state = cands | @valid_reg_names | (init_first ? Set[init_first] : Set.new)
    global_use = lambda do |name, use, members|
      rel, s, direct, fn = use
      macro = fn.nil? && direct ? define_at(rel, s) : nil
      if fn.nil?
        if direct && macro && macro_expansions_ok(macro, with_state | members)
          nil
        elsif direct
          'helper needs the mruby state threaded in, but the call is not in a function definition the converter ' \
          'recognises (a macro-decorated definition, or file scope) (not supported)'
        else
          'helper needs the mruby state threaded in, but is used outside a direct call (not supported): ' \
          'its address is in a file-scope initializer, so it may run with no method context'
        end
      elsif shadowed.call(name, fn)
        'helper needs the mruby state threaded in, but its name is shadowed in the calling function (not supported)'
      elsif !(with_state.include?(fn['name']) || members.include?(fn['name']))
        CTX_REASON
      elsif !direct
        why = value_problem.call(rel, s, name)
        why && "helper needs the mruby state threaded in, but is used outside a direct call (not supported): #{why}"
      end
    end
    gset = gcands.dup
    changed = true
    while changed
      changed = false
      gset.to_a.sort.each do |name|
        next unless helper_uses.call(name).any? { |u| global_use.call(name, u, gset) }
        gset.delete(name)
        changed = true
      end
    end
    @global_helpers = gset
    gset.to_a.sort.each do |name|
      d0 = @defs[name][0]
      rewrite(d0['file'], d0['hstart'], name, "global-state #{name}",
              "uses #{@global_name} (set by the registered method or Init it runs under), not an mrb argument")
    end
    refused_defs = Set.new
    @needs.to_a.sort.each do |name|
      next if @reg_names.include?(name) || name == init_first || !@defs.key?(name) || cands.include?(name) || gset.include?(name)
      ctx_why = nil
      if gcands.include?(name)
        # a use in a function with no state (a callback path) is reported once, on the helper's definition
        helper_uses.call(name).each do |u|
          why = global_use.call(name, u, gset)
          ctx_why ||= why if why == CTX_REASON
          refuse(u[0], u[1], name, why) if why && why != CTX_REASON
        end
      else
        helper_uses.call(name).each do |u|
          why = use_problem.call(name, u)
          refuse(u[0], u[1], name, why) if why
        end
      end
      @defs[name].each do |d0|
        refuse(d0['file'], d0['hstart'], name, ctx_why ? "helper needs mruby state; threading refused: #{ctx_why}" :
                                               'helper needs mruby state; threading refused')
      end
      refused_defs << name
    end
    # fail-safe: a call of a threaded helper from a function that gets no mrb and has no refusal of its own
    # would not compile, so it is refused. A global-state helper has the state in scope through the global.
    mrb_bearing = with_state | gset
    cands.to_a.sort.each do |name|
      uses[name].each do |rel, s, _direct, fn|
        next unless fn && !mrb_bearing.include?(fn['name']) && !refused_defs.include?(fn['name'])
        refuse(rel, s, name, 'caller has no mruby state and no refusal of its own (not supported)')
      end
    end
    compute_global_macros(with_state | gset)
    @global_wrap = !gset.empty? || @global_macro_spans.any? { |_r, l| !l.empty? }
    if @global_wrap
      # a macro that expands a return skips the restore of a registered method or Init that expands it (wrap_returns
      # only sees return statements written in the body). Such a use is refused; the macro's own body is not changed.
      wrapped = @valid_reg_names | (init_first ? Set[init_first] : Set.new)
      @files.each do |rel, f|
        define_spans(rel).each do |mname, a, b|
          next unless psl(f['masked'], a, b) =~ /(?<![#{WC}])return(?![#{WC}])/
          (@occ[mname] || []).each do |orel, os, _oe|
            next if orel == rel && a <= os && os < b
            fn = enclosing_func(orel, os)
            next unless fn && wrapped.include?(fn['name'])
            refuse(orel, os, mname, 'macro expands a return, which would skip the restore of the mruby global state in ' \
                                    'this registered method or Init (not supported)')
          end
        end
      end
    end
  end

  # Macros whose body calls an api that needs the mruby state. At file scope such a body is refused unless every
  # expansion is in a function with the state (a with_state or global-state function, mrb_tok) and the body has no
  # return (a return would skip the restore). Their mrb argument is then the global. A use in a preprocessor line
  # or in a file-scope initializer keeps the macro refused. Conservative: a macro that calls a helper is not handled.
  def compute_global_macros(ctx)
    @global_macro_spans = {}
    @files.each do |rel, f|
      masked = f['masked']
      masked.to_enum(:scan, /^[ \t]*#[ \t]*define[ \t]+([A-Za-z_][#{WC}]*)/).map { Regexp.last_match }.each do |m|
        name = m[1]
        s = m.begin(0)
        e = logical_line_end(masked, m.end(0))
        body = psl(masked, m.end(0), e)
        next unless body.scan(IDENT_RE).any? { |i| (@entries[i] || {})['needs_mrb'] }
        next if body =~ /(?<![#{WC}])return(?![#{WC}])/
        ok = (@occ[name] || []).all? do |orel, os, _oe|
          inside = orel == rel && s <= os && os < e
          if inside
            true
          else
            fn = enclosing_func(orel, os)
            !fn.nil? && ctx.include?(fn['name'])
          end
        end
        next unless ok
        (@global_macro_spans[rel] ||= []) << [s, e]
        @rewrites << { 'file' => rel, 'line' => line_of(f['text'], s), 'from' => name, 'to' => "#{name} (mrb = #{@global_name})" }
      end
    end
  end

  # [name, start, end, rel] of the #define that holds pos, or nil
  def define_at(rel, pos)
    d = define_spans(rel).find { |_n, a, b| a < pos && pos < b }
    d && [d[0], d[1], d[2], rel]
  end

  def define_spans(rel)
    @define_spans ||= {}
    @define_spans[rel] ||= begin
      masked = @files[rel]['masked']
      masked.to_enum(:scan, /^[ \t]*#[ \t]*define[ \t]+([A-Za-z_][#{WC}]*)/).map { Regexp.last_match }.map do |m|
        [m[1], m.begin(0), logical_line_end(masked, m.end(0))]
      end
    end
  end

  # A macro whose body calls a global-state helper: safe when the body has no return and every expansion is in a
  # function with the state (ctx). Checked again as the set of global-state helpers changes (its fixpoint).
  def macro_expansions_ok(macro, ctx)
    name, a, b, rel = macro
    body = psl(@files[rel]['masked'], a, b)
    return false if body =~ /(?<![#{WC}])return(?![#{WC}])/
    (@occ[name] || []).all? do |orel, os, _oe|
      next true if rel == orel && a <= os && os < b
      fn = enclosing_func(orel, os)
      !fn.nil? && ctx.include?(fn['name'])
    end
  end

  # The state a use inside function or macro position pos gets: the mrb parameter, or the file-scope global for a
  # global-state helper or a global macro body.
  def mrb_tok(rel, pos)
    fd = enclosing_func(rel, pos)
    return @global_name if fd && @global_helpers && @global_helpers.include?(fd['name'])
    return @global_name if in_global_macro?(rel, pos)
    'mrb'
  end

  def in_global_macro?(rel, pos)
    (@global_macro_spans[rel] || []).any? { |a, b| a < pos && pos < b }
  end

  # A registered method or Init with a global-state user saves the previous value on entry and restores it on each
  # return, so a nested state (a method that runs Ruby code in another state) sees its own state again afterwards.
  # The return expression is evaluated before the restore. A VALUE function that falls off its end is undefined in C
  # already, so it gets no restore; Init (void) gets one before its closing brace.
  def wrap_returns(rel, d, void)
    ed = @edits[rel]
    masked, text = @files[rel]['masked'], @files[rel]['text']
    g = @global_name
    finditer(/(?<![#{WC}])return(?![#{WC}])/, masked).each do |m|
      rs = m.begin(0)
      re = m.end(0)
      next if rs <= d['brace'] || rs >= d['body_end']
      depth = 0
      k = re
      semi = nil
      while k < masked.length
        ch = masked[k]
        if '([{'.include?(ch)
          depth += 1
        elsif ')]}'.include?(ch)
          depth -= 1
        elsif ch == ';' && depth == 0
          semi = k
          break
        end
        k += 1
      end
      next unless semi
      expr = py_strip(psl(text, re, semi))
      if expr.empty?
        ed.add(rs, rs, "{ #{g} = nfcx_bc2_old; ")
        ed.add(semi + 1, semi + 1, ' }')
      else
        ed.add(rs, re, '{ mrb_value nfcx_bc2_ret = (')
        ed.add(semi, semi + 1, "); #{g} = nfcx_bc2_old; return nfcx_bc2_ret; }")
      end
    end
    ed.add(d['body_end'], d['body_end'], " #{g} = nfcx_bc2_old; ") if void
  end

  # ---- stage 3: per-file rewrite -----------------------------------------
  def variadic_params(d)
    # (argc, argv, self) parameter names of a variadic (argc -1) method definition, or nil.
    # mruby calls every method as f(mrb, self) and hands the arguments over through mrb_get_args, so
    # the converted function reads them back with the "*" format into locals of the original names.
    params = d['params'].split(',', -1).map { |p| py_strip(p) }
    return nil unless params.size == 3
    m_argc = /\Aint#{SS1}([A-Za-z_][#{WC}]*)\z/.match(params[0])
    m_argv = /\AVALUE#{SS}\*#{SS}([A-Za-z_][#{WC}]*)\z/.match(params[1])
    m_self = /\AVALUE#{SS1}([A-Za-z_][#{WC}]*)\z/.match(params[2])
    return nil unless m_argc && m_argv && m_self
    [m_argc[1], m_argv[1], m_self[1]]
  end

  def param_names(d)
    names = Set.new
    d['params'].split(',', -1).each do |p|
      m = /([A-Za-z_][#{WC}]*)#{SS}(?:\[[^\]]*\]#{SS})*\z/.match(py_strip(p))
      names << m[1] if m
    end
    names
  end

  # returns [hdr, prologue, err]
  def registered_header(d)
    regs = @regs.select { |r| r['error'].nil? && r['func'] == d['name'] }
    n = regs[0]['argc']
    return [nil, nil, "registered method must return VALUE (found #{py_repr(d['ret'])})"] if d['ret'] != 'VALUE'
    if n == -1
      p = variadic_params(d)
      if p.nil?
        return [nil, nil, 'variadic registered method must take (int argc, VALUE *argv, VALUE self)' \
                          " (found #{py_repr(py_strip(d['params']))})"]
      end
      argc_n, argv_n, self_n = p
      hdr = "#{d['storage']}mrb_value #{d['name']}(mrb_state *mrb, mrb_value #{self_n})"
      prologue = "\n  mrb_int nfcx_argc;\n  mrb_value *#{argv_n};\n  mrb_get_args(mrb, \"*\", &#{argv_n}, &nfcx_argc);" \
                 "\n  int #{argc_n} = (int)nfcx_argc;"
      return [hdr, prologue, nil]
    end
    params = d['params'].split(',', -1).map { |p| py_strip(p) }
    if params.size != n + 1
      return [nil, nil, "registered method has #{params.size} parameters, arity #{n} needs #{n + 1}"]
    end
    names = []
    params.each do |p|
      mm = /\AVALUE#{SS1}([A-Za-z_][#{WC}]*)\z/.match(p)
      return [nil, nil, "parameter #{py_repr(p)} is not a plain VALUE"] unless mm
      names << mm[1]
    end
    hdr = "#{d['storage']}mrb_value #{d['name']}(mrb_state *mrb, mrb_value #{names[0]})"
    prologue = ''
    if n > 0
      prologue = "\n  mrb_value #{names[1..].join(', ')};\n  mrb_get_args(mrb, \"#{'o' * n}\", #{names[1..].map { |x| '&' + x }.join(', ')});"
    end
    [hdr, prologue, nil]
  end

  # A CRuby #include that api_map.json maps (its "includes" key): the mruby headers it becomes, one per line, quoted or
  # angle-bracketed. "comment" follows a quoted include; "config_macro" (when the input's text uses it) is defined by
  # the converter, as CRuby's extconf would define it; "caveat" is recorded with the rewrite.
  def map_include(rel, m, ent, masked, ed)
    heads = ent['headers']
    repl = heads.map do |h|
      line = ent['quoted'] ? "#include \"#{h}\"" : "#include <#{h}>"
      line += "  /* #{ent['comment']} */" if ent['comment'] && ent['quoted']
      line
    end.join("\n")
    ed.add(m.begin(0), m.end(0), repl)
    cm = ent['config_macro']
    if cm && masked.include?(cm)
      # CRuby's extconf sets this macro; the code it guards is in the input, so the converter defines it.
      ed.add(0, 0, "#define #{cm} 1  /* set by the converter: #{ent['config_comment']} */\n")
      rewrite(rel, 0, cm, 'defined by converter', 'extconf config macro set on')
    end
    rewrite(rel, m.begin(0), m[0], repl.gsub("\n", ' | '), ent['caveat'])
  end

  def process(rel)
    f = @files[rel]
    text, masked, ed = f['text'], f['masked'], @edits[rel]
    # 1. includes (directives only; masked check skips commented-out ones)
    finditer(INC_RE, text).each do |m|
      next if masked[m.begin(0)] != '#'
      inc = m[1]
      if @includes.key?(inc)
        map_include(rel, m, @includes[inc], masked, ed)
      elsif DROP_INCLUDES.key?(inc)
        reason = DROP_INCLUDES[inc]
        ed.add(m.begin(0), m.end(0), "/* BC2CPP-MRBGEM dropped: #include <#{inc}> (#{reason}) */")
        @warnings << { 'file' => rel, 'line' => line_of(text, m.begin(0)), 'api' => "#include <#{inc}>", 'reason' => reason }
        warn "warning: #{rel}:#{line_of(text, m.begin(0))} dropped #include <#{inc}> (#{reason})"
      else
        refuse(rel, m.begin(0), "#include <#{inc}>", 'CRuby header not in the supported subset')
      end
    end
    # 2. function headers
    init_name = @init_defs.empty? ? nil : @init_defs[0]['name']
    @decls.each do |d|
      next if d['file'] != rel
      name = d['name']
      hdr, pro, err = nil, '', nil
      # Only a function with a surviving registration gets the method signature. A refused registration
      # (e.g. no definition in the input) leaves its prototype as is; the refusal is already recorded.
      if @valid_reg_names.include?(name)
        hdr, pro, err = registered_header(d)
        pro = '' if d['proto']
      elsif d['name'] == (@init_defs.empty? ? nil : @init_defs[0]['name']) && !d['proto']
        hdr = "void mrb_#{@funcname}_gem_init(mrb_state *mrb)"
      elsif @helper_names.include?(name)
        ptxt = py_strip(d['params'])
        tail = ['', 'void'].include?(ptxt) ? '' : ', ' + map_types(ptxt, @types)
        hdr = "#{d['storage']}#{map_types(d['ret'], @types)} #{name}(mrb_state *mrb#{tail})"
      end
      if err
        refuse(rel, d['hstart'], name, err)
        next
      end
      next if hdr.nil?
      if d['proto']
        ed.add(d['hstart'], d['hend'], hdr)
      else
        # a registered method or Init of a gem that uses the global state saves and restores it (wrap_returns)
        if @global_wrap && (@valid_reg_names.include?(name) || name == init_name)
          g = @global_name
          pro = "\n  mrb_state *nfcx_bc2_old = #{g};\n  #{g} = mrb;" + pro
          wrap_returns(rel, d, name == init_name && !@valid_reg_names.include?(name))
        end
        ed.add(d['hstart'], d['hend'], hdr + ' ')
        ed.add(d['brace'] + 1, d['brace'] + 1, pro) unless pro.empty?
        rewrite(rel, d['hstart'], "#{d['name']}(...)", hdr)
      end
    end
    # 3. class variable declarations become struct RClass *
    # A VALUE parameter that has a class variable's name is an ordinary parameter (it shadows the class
    # variable in its function) and is left alone.
    @class_vars.to_a.sort.each do |c|
      finditer(/(?<![#{WC}])VALUE(?![#{WC}])#{SS1}#{Regexp.escape(c)}(?![#{WC}])(?=#{SS}[=;,\[])/, masked).each do |m|
        next if is_param(rel, m.begin(0), c)
        ed.add(m.begin(0), m.begin(0) + 'VALUE'.length, 'struct RClass *')
        rewrite(rel, m.begin(0), "VALUE #{c}", "struct RClass * #{c}")
      end
      finditer(/(?<![#{WC}])VALUE(?![#{WC}])[^;(){}]*,#{SS}#{Regexp.escape(c)}(?![#{WC}])/, masked).each do |mm|
        next if is_param(rel, mm.begin(0), c)
        refuse(rel, mm.begin(0), c, 'multi-declarator class variable declaration not supported')
        break
      end
    end
    # 4. helper call sites get the mrb argument
    header_spans = @decls.select { |d| d['file'] == rel }.map { |d| [d['hstart'], d['hend']] }
    @helper_names.to_a.sort.each do |name|
      (@occ[name] || []).each do |orel, s, e|
        next if orel != rel || header_spans.any? { |a, b| a <= s && s < b }
        po = next_nonspace(masked, e)
        next if po < 0 || masked[po] != '('
        pa = next_nonspace(masked, po + 1)
        t = mrb_tok(rel, s)
        ed.add(po + 1, po + 1, masked[pa] == ')' ? t : "#{t}, ")
      end
    end
    # 5. identifier pass. Local names: functions the input defines (a prototype alone does not count: it may declare a
    # CRuby API), class variables and the macros the input defines (scan_local_macros).
    local_syms = Set.new(@defs.keys) | @class_vars | @local_macros
    body_spans = @defs.values.flatten.select { |d| d['file'] == rel }.map { |d| [d['brace'], d['body_end']] }
    finditer(IDENT_RE, masked).each do |m|
      s, e = m.begin(0), m.end(0)
      name = m[0]
      next if is_member(masked, s) || ed.overlaps(s, e)
      next if @local_var_occ.include?([rel, s])
      entry = @entries[name]
      if !entry.nil?
        if entry['needs_mrb'] && body_spans.none? { |a, b| a < s && s < b } && !in_global_macro?(rel, s)
          refuse(rel, s, name, 'needs the mruby state, which is not in scope at file scope')
          next
        end
        map_entry(rel, s, e, name, entry)
      elsif @types.key?(name)
        next if name == 'ID' && !(psl(masked, e, e + 40) =~ /\A#{SS1}[A-Za-z_]/)
        ed.add(s, e, @types[name])
        rewrite(rel, s, name, @types[name])
      elsif UNKNOWN_RE.match?(name) && !local_syms.include?(name) &&
            !(@local_tags.include?(name) && psl(masked, [s - 40, 0].max, s).match?(/\b(?:struct|union|enum)[ \t\n]+\z/))
        refuse(rel, s, name, 'no entry in api_map.json')
      elsif @class_vars.include?(name)
        next if @decl_name_pos.include?([rel, s]) || is_param(rel, s, name)
        nx = next_nonspace(masked, e)
        next if nx >= 0 && masked[nx] == '=' && psl(masked, nx + 1, nx + 2) != '='
        callee, idx = call_context(masked, s)
        next if callee && (@special_pos[callee] || []).include?(idx)
        ed.add(s, e, "mrb_obj_value(#{name})")
        rewrite(rel, s, name, "mrb_obj_value(#{name})")
      end
    end
    # 6. mrb name clash in files that get the mrb parameter
    if @decls.any? { |d| d['file'] == rel && @needs.include?(d['name']) }
      mm = /(?<![#{WC}])mrb(?![#{WC}])/.match(masked)
      refuse(rel, mm.begin(0), 'mrb', 'source already uses the identifier mrb (clashes with the state parameter)') if mm
    end
  end

  def is_param(rel, pos, name)
    # True if name at pos is a parameter of the function (its header, or its body) that encloses pos.
    # A parameter shadows a file-scope class variable of the same name, so it must not be rewritten.
    @decls.each do |d|
      next if d['file'] != rel
      return param_names(d).include?(name) if d['hstart'] <= pos && pos < d['hend']
      return true if d.key?('body_end') && d['brace'] < pos && pos < d['body_end'] && param_names(d).include?(name)
    end
    false
  end

  def map_entry(rel, s, e, name, entry)
    masked = @files[rel]['masked']
    ed = @edits[rel]
    kind = entry['kind']
    nxt = next_nonspace(masked, e)
    called = nxt >= 0 && masked[nxt] == '('
    case kind
    when 'refuse'
      refuse(rel, s, name, entry['reason'])
    when 'special'
      special(rel, s, e, name, entry, nxt, called)
    when 'drop'
      # Declaration with no effect in mruby: the call is removed and a warning is printed and recorded.
      unless called
        refuse(rel, s, name, 'used without a call; cannot drop it')
        return
      end
      close = pyfind(masked, ')', nxt)
      stop = close + 1
      semi = next_nonspace(masked, stop)
      stop = semi + 1 if semi >= 0 && masked[semi] == ';'
      ed.add(s, stop, "/* BC2CPP-MRBGEM dropped: #{name} (#{entry['reason']}) */")
      line = line_of(@files[rel]['text'], s)
      @warnings << { 'file' => rel, 'line' => line, 'api' => name, 'reason' => entry['reason'] }
      warn "warning: #{rel}:#{line} dropped #{name} (#{entry['reason']})"
    when 'call'
      unless called
        refuse(rel, s, name, 'used without a call; no expression form in api_map.json')
        return
      end
      ed.add(s, e, entry['mruby'])
      if entry['inject_mrb']
        pa = next_nonspace(masked, nxt + 1)
        t = mrb_tok(rel, s)
        ed.add(nxt + 1, nxt + 1, masked[pa] == ')' ? t : "#{t}, ")
      end
      rewrite(rel, s, name, entry['mruby'], entry['caveat'])
    when 'macro'
      if entry['mruby'] != name
        ed.add(s, e, entry['mruby'])
        rewrite(rel, s, name, entry['mruby'])
      end
    when 'strip'
      # A macro whose only effect is a compiler hint (RB_LIKELY): the name becomes entry['mruby'] and the
      # argument stays in place, so the call form is kept and the hint is dropped.
      unless called
        refuse(rel, s, name, 'used without a call; cannot map it')
        return
      end
      ed.add(s, e, entry['mruby'])
      rewrite(rel, s, name, entry['mruby'], entry['caveat'])
    when 'expr'
      if called
        refuse(rel, s, name, 'expression mapping used in call form')
        return
      end
      ed.add(s, e, entry['mruby'])
      rewrite(rel, s, name, entry['mruby'])
    else
      refuse(rel, s, name, "unknown kind #{py_repr(kind)} in api_map.json")
    end
  end

  def special(rel, s, e, name, entry, nxt, called)
    masked = @files[rel]['masked']
    text = @files[rel]['text']
    ed = @edits[rel]
    if name == 'RB_GC_GUARD'
      fn = enclosing_func(rel, s)
      if !called || fn.nil? || !@needs.include?(fn['name'])
        refuse(rel, s, name, 'GC guard outside a function that has an mrb_state in scope')
        return
      end
      close = pyfind(masked, ')', nxt)
      arg = py_strip(psl(text, nxt + 1, close))
      if close < 0 || !/\A[A-Za-z_][#{WC}]*\z/.match?(arg)
        refuse(rel, s, name, 'GC guard argument is not a plain variable')
        return
      end
      ed.add(s, close + 1, "mrb_gc_protect(#{mrb_tok(rel, s)}, #{arg})")
      rewrite(rel, s, name, "mrb_gc_protect(mrb, #{arg})",
              'keeps the value rooted until the arena is restored (fine within the call; use mrb_gc_register to outlive it)')
      return
    end
    case name
    when 'rb_define_method', 'rb_define_singleton_method', 'rb_define_module_function'
      rec = @reg_by_call[[rel, s]]
      if rec.nil? || !called || nxt != rec['open']
        refuse(rel, s, name, 'used without a registration call')
        return
      end
      if rec['error']
        refuse(rel, s, name, rec['error'])
        return
      end
      tgt = rec['target']
      if !@class_vars.include?(tgt) && tgt != 'rb_cObject'
        refuse(rel, s, name, "target #{py_repr(tgt)} is not a tracked class or module variable")
        return
      end
      new = { 'rb_define_method' => 'mrb_define_method', 'rb_define_singleton_method' => 'mrb_define_class_method',
              'rb_define_module_function' => 'mrb_define_module_function' }[name]
      ed.add(s, e, new)
      ed.add(nxt + 1, nxt + 1, "#{mrb_tok(rel, s)}, ")
      fs, fe = rec['func_span']
      ed.add(fs, fe, rec['func'])
      as_, ae = rec['argc_span']
      aspec =
        if rec['argc'] == -1
          'MRB_ARGS_ANY()' # the function reads its arguments itself (see variadic_params)
        elsif rec['argc'] == 0
          'MRB_ARGS_NONE()'
        else
          "MRB_ARGS_REQ(#{rec['argc']})"
        end
      ed.add(as_, ae, aspec)
      rewrite(rel, s, name, "#{new}(mrb, #{tgt}, \"#{rec['name']}\", #{rec['func']}, #{aspec})")
    when 'rb_scan_args'
      scan_args(rel, s, e, nxt, called)
    when 'RB_TYPE_P'
      type_p(rel, s, e, nxt, called)
    when 'Check_Type', 'rb_check_type'
      check_type(rel, s, e, name, nxt, called)
    when 'rb_gc_start'
      gc_start(rel, s, e, nxt, called)
    when 'rb_gc_writebarrier'
      gc_writebarrier(rel, s, e, nxt, called)
    when 'rb_define_const'
      define_const(rel, s, e, nxt, called)
    when 'rb_const_get'
      const_get(rel, s, e, nxt, called)
    when 'rb_raise'
      unless called
        refuse(rel, s, name, 'used without a call')
        return
      end
      cp = match_close(masked, nxt)
      args = cp > 0 ? split_args(masked, nxt, cp) : []
      if args.size < 2
        refuse(rel, s, name, 'rb_raise needs an exception class and a format string')
        return
      end
      fmt = psl(text, args[1][0], args[1][1])
      if fmt.include?('PRIsVALUE')
        refuse(rel, s, name, 'PRIsVALUE format (VALUE to string) not supported')
        return
      end
      ed.add(s, e, 'mrb_raisef')
      ed.add(nxt + 1, nxt + 1, "#{mrb_tok(rel, s)}, ")
      rewrite(rel, s, name, 'mrb_raisef')
    else
      refuse(rel, s, name, 'unknown special handler')
    end
  end

  # rb_const_get(klass, id) -> mrb_const_get(mrb, klass, id). Both take the receiver as a VALUE and the name as
  # an ID (mrb_sym); rb_cObject is passed as its VALUE. Differences, recorded as a caveat: a module receiver
  # does not fall back to Object in mruby (CRuby does), and there is no autoload.
  def const_get(rel, s, e, nxt, called)
    masked, text, ed = @files[rel]['masked'], @files[rel]['text'], @edits[rel]
    unless called
      refuse(rel, s, 'rb_const_get', 'used without a call')
      return
    end
    close = match_close(masked, nxt)
    args = close > 0 ? split_args(masked, nxt, close) : []
    if args.size != 2
      refuse(rel, s, 'rb_const_get', 'rb_const_get takes a class and an ID')
      return
    end
    ed.add(s, e, 'mrb_const_get')
    ed.add(nxt + 1, nxt + 1, "#{mrb_tok(rel, s)}, ")
    ed.add(args[0][0], args[0][1], "mrb_obj_value(#{mrb_tok(rel, s)}->object_class)") if psl(text, args[0][0], args[0][1]) == 'rb_cObject'
    rewrite(rel, s, 'rb_const_get', 'mrb_const_get(mrb, klass, id)',
            'a module receiver does not fall back to Object as CRuby does; no autoload')
  end

  # rb_define_const(klass, "NAME", value) -> mrb_define_const(mrb, klass, "NAME", value). The receiver must be
  # a tracked class or module variable (a struct RClass *) or rb_cObject, as mrb_define_const takes a class
  # pointer. mruby stores the constant without CRuby's 'already initialized' warning on redefinition.
  def define_const(rel, s, e, nxt, called)
    masked, text, ed = @files[rel]['masked'], @files[rel]['text'], @edits[rel]
    unless called
      refuse(rel, s, 'rb_define_const', 'used without a call')
      return
    end
    close = match_close(masked, nxt)
    args = close > 0 ? split_args(masked, nxt, close) : []
    if args.size != 3
      refuse(rel, s, 'rb_define_const', 'rb_define_const takes a class, a name and a value')
      return
    end
    tgt = psl(text, args[0][0], args[0][1])
    unless tgt == 'rb_cObject' || (@class_vars.include?(tgt) && !is_param(rel, args[0][0], tgt))
      refuse(rel, s, 'rb_define_const', "target #{py_repr(tgt)} is not a tracked class or module variable")
      return
    end
    ed.add(s, e, 'mrb_define_const')
    ed.add(nxt + 1, nxt + 1, "#{mrb_tok(rel, s)}, ")
    rewrite(rel, s, 'rb_define_const', "mrb_define_const(mrb, #{tgt}, ...)",
            'an existing constant is replaced without CRuby\'s "already initialized" warning')
  end

  # rb_scan_args(argc, argv, FMT, &v...) in a variadic method, as a statement, with FMT of the form
  # "<lead><opt>" (no rest, keyword or block parts) -> mrb_get_args(mrb, "o|o", &v...). mrb_get_args reads
  # the same stack the method was called with, and its arity check is the one rb_scan_args makes. Optional
  # outputs are set to nil first, because mrb_get_args leaves a missing optional argument unwritten.
  def scan_args(rel, s, e, nxt, called)
    masked, text, ed = @files[rel]['masked'], @files[rel]['text'], @edits[rel]
    fn = enclosing_func(rel, s)
    if !called || fn.nil? || !@variadic.key?(fn['name'])
      refuse(rel, s, 'rb_scan_args', 'only supported directly in a variadic method (argc -1)')
      return
    end
    close = match_close(masked, nxt)
    args = close > 0 ? split_args(masked, nxt, close) : []
    if args.size < 3
      refuse(rel, s, 'rb_scan_args', 'rb_scan_args needs argc, argv and a format string')
      return
    end
    argc_n, argv_n, self_n = @variadic[fn['name']]
    if psl(text, args[0][0], args[0][1]) != argc_n || psl(text, args[1][0], args[1][1]) != argv_n
      refuse(rel, s, 'rb_scan_args', 'rb_scan_args is not called on the argc and argv of its method')
      return
    end
    fm = /\A"([0-9])([0-9]?)"\z/.match(psl(text, args[2][0], args[2][1]))
    unless fm
      refuse(rel, s, 'rb_scan_args',
             "format #{psl(text, args[2][0], args[2][1])} not supported " \
             '(only "<lead><optional>" counts: no rest, keyword or block parts)')
      return
    end
    lead = fm[1].to_i
    opt = (fm[2].empty? ? 0 : fm[2].to_i)
    outs = args[3..] || []
    if outs.size != lead + opt
      refuse(rel, s, 'rb_scan_args', "format needs #{lead + opt} output pointer(s), call gives #{outs.size}")
      return
    end
    names = []
    outs.each do |a, b|
      om = /\A&#{SS}([A-Za-z_][#{WC}]*)\z/.match(psl(text, a, b))
      if !om || @class_vars.include?(om[1]) || [argc_n, argv_n, self_n].include?(om[1])
        refuse(rel, s, 'rb_scan_args', "output #{py_repr(psl(text, a, b))} is not a plain local variable")
        return
      end
      names << om[1]
    end
    prev = prev_nonspace(masked, s - 1)
    after = next_nonspace(masked, close + 1)
    if (prev >= 0 && !";{}".include?(masked[prev])) || after < 0 || masked[after] != ';'
      refuse(rel, s, 'rb_scan_args', 'the return value of rb_scan_args is used (mruby returns a different count)')
      return
    end
    fmt = 'o' * lead + (opt > 0 ? '|' + 'o' * opt : '')
    pre = names[lead..].map { |n| "#{n} = mrb_nil_value(), " }.join
    callargs = (['mrb', "\"#{fmt}\""] + names.map { |n| '&' + n }).join(', ')
    ed.add(s, close + 1, "(#{pre}mrb_get_args(#{callargs}))")
    rewrite(rel, s, 'rb_scan_args', "mrb_get_args(mrb, \"#{fmt}\", ...)",
            'optional outputs are set to nil first (as rb_scan_args does); mruby arity errors are ArgumentError as in CRuby')
  end

  # True if the call whose name starts at s and whose ')' is at close is a whole statement: the value is
  # discarded. It must follow a statement boundary, a closed condition or do/else, and be followed by ';'.
  def statement_call(rel, s, close)
    masked = @files[rel]['masked']
    prev = prev_nonspace(masked, s - 1)
    after = next_nonspace(masked, close + 1)
    return false if after < 0 || masked[after] != ';'
    return true if prev < 0 || ";{})".include?(masked[prev])
    !(psl(masked, 0, s) =~ /(?<![#{WC}])(?:else|do)#{SS}\z/).nil?
  end

  # rb_gc_start() as a statement -> mrb_full_gc(mrb). CRuby returns nil; mruby returns void, so a use of the
  # value is refused. mrb_full_gc does nothing while gc.disabled is set or during an iteration (src/gc.c:1442).
  def gc_start(rel, s, _e, nxt, called)
    masked, text = @files[rel]['masked'], @files[rel]['text']
    unless called
      refuse(rel, s, 'rb_gc_start', 'used without a call')
      return
    end
    close = match_close(masked, nxt)
    if close < 0 || !py_strip(psl(text, nxt + 1, close)).empty?
      refuse(rel, s, 'rb_gc_start', 'rb_gc_start takes no arguments')
      return
    end
    unless statement_call(rel, s, close)
      refuse(rel, s, 'rb_gc_start', 'the return value of rb_gc_start (nil) is used; mruby has no equivalent')
      return
    end
    @edits[rel].add(s, close + 1, "mrb_full_gc(#{mrb_tok(rel, s)})")
    rewrite(rel, s, 'rb_gc_start', 'mrb_full_gc(mrb)',
            'mrb_full_gc does nothing while gc.disabled is set or an object iteration is running; no collection is forced then')
  end

  # RB_TYPE_P(obj, T_X) -> (mrb_type(obj) == MRB_TT_X), where T_X is a T_ name whose api_map entry is an exact
  # MRB_TT_ type with no caveat (T_DATA, T_FIXNUM, T_NIL and the like are refused). obj must be a plain local: the
  # whole call is replaced, so a nested mapped name would not be rewritten.
  def type_p(rel, s, _e, nxt, called)
    masked, text, ed = @files[rel]['masked'], @files[rel]['text'], @edits[rel]
    unless called
      refuse(rel, s, 'RB_TYPE_P', 'used without a call')
      return
    end
    close = match_close(masked, nxt)
    args = close > 0 ? split_args(masked, nxt, close) : []
    if args.size != 2
      refuse(rel, s, 'RB_TYPE_P', 'RB_TYPE_P takes an object and a T_ type')
      return
    end
    obj = psl(text, args[0][0], args[0][1])
    tname = psl(text, args[1][0], args[1][1])
    if !/\A[A-Za-z_][#{WC}]*\z/.match?(obj) || @entries.key?(obj) || @types.key?(obj) ||
       @class_vars.include?(obj) || obj == 'mrb'
      refuse(rel, s, 'RB_TYPE_P', "object #{py_repr(obj)} is not a plain local variable (nested names would not be mapped)")
      return
    end
    ent = @entries[tname]
    if ent.nil? || ent.empty? || ent['kind'] != 'expr' || !(ent['mruby'] || '').start_with?('MRB_TT_') || ent.key?('caveat')
      refuse(rel, s, 'RB_TYPE_P', "#{tname} has no exact mruby type to compare with")
      return
    end
    new = "(mrb_type(#{obj}) == #{ent['mruby']})"
    ed.add(s, close + 1, new)
    rewrite(rel, s, 'RB_TYPE_P', new)
  end

  # Check_Type(v, T_X) and rb_check_type(v, T_X) -> mrb_check_type(mrb, v, MRB_TT_X). Only the name and the type
  # argument are edited, so the value argument is left to the identifier pass (it may be any expression). The type
  # argument must be a literal T_ identifier: CRuby's int values differ from mruby's enum, so a variable is refused.
  # The name must have type_check "exact" or "caveat" in api_map.json; the others are refused with type_check_refused.
  def check_type(rel, s, e, name, nxt, called)
    masked, text, ed = @files[rel]['masked'], @files[rel]['text'], @edits[rel]
    unless called
      refuse(rel, s, name, 'used without a call')
      return
    end
    close = match_close(masked, nxt)
    args = close > 0 ? split_args(masked, nxt, close) : []
    if args.size != 2
      refuse(rel, s, name, "#{name} takes a value and a T_ type")
      return
    end
    ts, te = args[1]
    tname = psl(text, ts, te)
    unless /\A(?:RUBY_)?T_[A-Z]+\z/.match?(tname)
      refuse(rel, s, name, 'type argument is not a literal T_ constant')
      return
    end
    ent = @entries[tname]
    if !@type_check_refused[tname].nil? || ent.nil? || !%w[exact caveat].include?(ent['type_check']) ||
       !(ent['mruby'] || '').start_with?('MRB_TT_')
      reason = @type_check_refused[tname] || "#{tname} has no exact mruby type test in the supported subset"
      refuse(rel, s, name, reason)
      # keep the T_ name as written: the identifier pass must not map it inside a refused call
      ed.add(ts, te, tname)
      return
    end
    obj = psl(text, args[0][0], args[0][1])
    to = "mrb_check_type(mrb, #{obj}, #{ent['mruby']})"
    ed.add(s, e, 'mrb_check_type')
    ed.add(nxt + 1, nxt + 1, "#{mrb_tok(rel, s)}, ")
    ed.add(ts, te, ent['mruby'])
    rewrite(rel, s, name, to, ent['caveat'])
  end

  # rb_gc_writebarrier(old, young) as a statement -> an immediate-guarded mrb_field_write_barrier_value. The
  # arguments are plain locals: they are used more than once, and an edit inside them would overlap. CRuby's
  # `old` is never a special constant (RB_OBJ_WRITE only calls this for heap owners), so the guard is a no-op there.
  def gc_writebarrier(rel, s, _e, nxt, called)
    masked, text, ed = @files[rel]['masked'], @files[rel]['text'], @edits[rel]
    unless called
      refuse(rel, s, 'rb_gc_writebarrier', 'used without a call')
      return
    end
    close = match_close(masked, nxt)
    args = close > 0 ? split_args(masked, nxt, close) : []
    if args.size != 2
      refuse(rel, s, 'rb_gc_writebarrier', 'rb_gc_writebarrier takes an owner and a referenced value')
      return
    end
    names = []
    args.each do |a, b|
      t = psl(text, a, b)
      if !/\A[A-Za-z_][#{WC}]*\z/.match?(t) || @entries.key?(t) || @types.key?(t) ||
         @class_vars.include?(t) || t == 'mrb'
        refuse(rel, s, 'rb_gc_writebarrier', "argument #{py_repr(t)} is not a plain local variable (it is used twice)")
        return
      end
      names << t
    end
    unless statement_call(rel, s, close)
      refuse(rel, s, 'rb_gc_writebarrier', 'the return value of rb_gc_writebarrier is used (it is void)')
      return
    end
    old, young = names
    new = "do { if (!mrb_immediate_p(#{old})) mrb_field_write_barrier_value(#{mrb_tok(rel, s)}, mrb_basic_ptr(#{old}), #{young}); } while (0)"
    ed.add(s, close + 1, new)
    rewrite(rel, s, 'rb_gc_writebarrier', new,
            'mruby keeps the write barrier only for a heap owner; it does not make C-held storage a GC root ' \
            '(there is no mark callback, see rb_gc_mark)')
  end

  # ---- stage 4: write ----------------------------------------------------
  def write_outputs
    src_dir = File.join(@out_dir, 'src')
    inc_dir = File.join(@out_dir, 'include')
    FileUtils.mkdir_p(src_dir)
    FileUtils.mkdir_p(inc_dir)
    outputs = {}
    @files.each { |rel, f| outputs[rel] = @edits[rel].apply(f['text']) }
    if @global_wrap
      # the global state (check_refs): defined once, in the file of Init; declared before any other text in the others.
      # Declared as struct mrb_state so the prefix needs no include (the typedef is the same type).
      @files.each do |rel, _f|
        pre = "extern struct mrb_state *#{@global_name};\n"
        pre += "struct mrb_state *#{@global_name} = NULL;\n" if rel == @init_rel
        outputs[rel] = pre + outputs[rel]
      end
    end
    @files.each do |rel, f|
      dest = File.join(f['kind'] == 'src' ? src_dir : inc_dir, rel)
      write_bytes(dest, outputs[rel])
    end
    write_bytes(File.join(inc_dir, 'nfcx_uv_thread.h'), NFCX_UV_THREAD_H) if uses_uv_thread?
    fn = @funcname
    init_file = @init_rel
    gem_init = []
    gem_init << '#error "BC2CPP-MRBGEM: NOT BUILDABLE, see REFUSALS.txt"' unless @refusals.empty?
    gem_init += [
      "/* Generated by convert_mrbgem.rb from ext/#{@name}. */",
      '#include <mruby.h>',
      '',
      init_file ? "/* mrb_#{fn}_gem_init is defined in src/#{init_file} (the converted Init_ function). */" :
        "void\nmrb_#{fn}_gem_init(mrb_state *mrb)  /* no Init_ function: see REFUSALS.txt */\n{\n  (void)mrb;\n}",
      '',
      'void',
      "mrb_#{fn}_gem_final(mrb_state *mrb)",
      '{',
      '  (void)mrb;',
      '}',
      '',
    ]
    write_bytes(File.join(src_dir, 'gem_init.c'), gem_init.join("\n"))
    status = @refusals.empty? ? 'no refusals (NOT compiled or tested)' : 'NOT BUILDABLE'
    rake = ["# Generated by convert_mrbgem.rb from CRuby ext/#{@name}. Fill in the TODO fields."]
    unless @refusals.empty?
      rake << "raise \"BC2CPP-MRBGEM: #{@name} is NOT BUILDABLE (#{@refusals.size} refusal(s)); see REFUSALS.txt\""
    end
    rake += [
      '',
      "MRuby::Gem::Specification.new('#{@name}') do |spec|",
      "  spec.license = 'TODO'",
      "  spec.author  = 'TODO'",
      "  spec.summary = 'converted from CRuby ext/#{@name}'",
    ]
    rake << "  spec.add_dependency 'mruby-uv'  # thread model: nfcx_uv_thread.h" if uses_uv_thread?
    rake += ['end', '']
    write_bytes(File.join(@out_dir, 'mrbgem.rake'), rake.join("\n"))
    lines = ["BC2CPP-MRBGEM refusals for ext/#{@name}",
             "STATUS: #{status} (#{@refusals.size} refusal(s))", '']
    @refusals.each { |r| lines << "#{r['file']}:#{r['line']}  #{r['api']}  #{r['reason']}" }
    write_bytes(File.join(@out_dir, 'REFUSALS.txt'), lines.join("\n") + "\n")
    unless @warnings.empty?
      body = @warnings.map { |w| "#{w['file']}:#{w['line']}  #{w['api']}  dropped: #{w['reason']}\n" }.join
      write_bytes(File.join(@out_dir, 'WARNINGS.txt'), body)
    end
    marker = File.join(@out_dir, 'NOT_BUILDABLE')
    if !@refusals.empty?
      write_bytes(marker, "#{@refusals.size} refusal(s); see REFUSALS.txt\n")
    elsif File.exist?(marker)
      File.delete(marker)
    end
    log = { 'gem' => @name, 'funcname' => fn, 'init_file' => init_file, 'scanner' => @scanner,
            'rewrites' => @rewrites, 'refusals' => @refusals,
            'ignored' => @ignored.map { |a, b| { 'file' => a, 'why' => b } },
            'helpers_threaded' => @helper_names.to_a.sort,
            'registered' => @regs.map { |r| { 'name' => r['name'], 'c_func' => r['func'], 'argc' => r['argc'],
                                              'target' => r['target'], 'error' => r['error'] } } }
    log['scanner_reason'] = @scanner_reason if @scanner_reason
    log['scanner_fallback'] = @scanner_fallback unless @scanner_fallback.empty?
    write_bytes(File.join(@out_dir, 'conversion_log.json'), py_json(log, 0))
    [@rewrites.size, @refusals.size]
  end

  def run
    choose_scanner
    load
    scan_local_macros
    scan
    build_occurrences
    scan_local_names
    compute_needs
    check_refs
    @files.keys.sort.each { |rel| process(rel) }
    @dead_inits.each do |d|
      @edits[d['file']].add(d['hstart'], d['hstart'],
                            "#if 0  /* BC2CPP-MRBGEM: not the extension entry; CRuby never calls it */\n")
      @edits[d['file']].add(d['body_end'] + 1, d['body_end'] + 1, "\n#endif\n")
    end
    n_rw, n_ref = write_outputs
    puts "converted #{@name}: #{n_rw} rewrite(s), #{n_ref} refusal(s), " \
         "#{@regs.count { |r| r['error'].nil? }} registered method(s) -> #{@out_dir}"
    @refusals.empty? ? 0 : 2
  end
end

def main(argv)
  args = argv.dup
  name = nil
  scanner = 'auto'
  defines = []
  while args.first&.start_with?('--')
    opt = args.shift
    if opt == '--name' && !args.empty?
      name = args.shift
    elsif opt == '--scanner' && %w[auto libclang regex].include?(args.first)
      scanner = args.shift
    elsif opt == '--define' && !args.empty?
      defines << args.shift
    else
      args = nil
      break
    end
  end
  if args.nil? || args.size != 2
    warn 'usage: convert_mrbgem.rb [--name GEM] [--scanner auto|libclang|regex] [--define NAME[=VALUE]]... ' \
         '<cext_dir> <out_dir>'
    return 1
  end
  Converter.new(args[0], args[1], name, scanner, defines).run
end

exit(main(ARGV)) if $PROGRAM_NAME == __FILE__
