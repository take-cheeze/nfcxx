#!/usr/bin/env ruby
# frozen_string_literal: false
#
# convert_mrbgem.rb [--name GEM] <cext_dir> <out_dir>
#
# Text-only converter: a CRuby C extension directory (ext/<name>/ with *.c, *.h)
# -> an mruby mrbgem directory (mrbgem.rake, src/*.c, src/gem_init.c, include/*.h).
#
# The input is only read as text. It is never compiled, loaded or executed.
# Mappings come from api_map.json next to this script. Any CRuby-looking API
# identifier without a map entry is REFUSED: a marker comment
# `/* BC2CPP-MRBGEM REFUSED: <api> */` is left in the output, the item is listed
# in REFUSALS.txt, and the output is marked not buildable (NOT_BUILDABLE file,
# #error in gem_init.c, raise in mrbgem.rake).
#
# Exit status: 0 converted with no refusals; 2 refusals present (output written,
# marked not buildable); 1 usage or input error.
#
# This is the Ruby port of the former Python converter. Python's Unicode \w, \s and
# str.isspace() are reproduced with explicit character classes (WC, WSP), and Python's
# `$` (which also matches before a final newline) is written as \z.

require 'json'
