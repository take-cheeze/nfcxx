NFCX_UV_THREAD_H = <<'EOS'
/* nfcx_uv_thread.h: models CRuby's rb_thread_call_without_gvl on mruby-uv (generated by convert_mrbgem.rb).
 * func runs on libuv's thread pool; the calling Ruby-side C code runs the loop until the work is done, so
 * the call stays synchronous as in CRuby. func must not touch mrb_state (no GVL section rules apply here).
 * ubf (the unblock function) is ignored: a blocked worker cannot be interrupted. NOT COMPILED. */
#ifndef NFCX_UV_THREAD_H
#define NFCX_UV_THREAD_H
#include <uv.h>
#include <mruby.h>
#include "mrb_uv.h"   /* mruby-uv: mrb_uv_current_loop */

typedef struct {
  void *(*fn)(void *);
  void *data;
  void *result;
  int done;
} nfcx_uv_work_t;

static void nfcx_uv_work_cb(uv_work_t *w) {
  nfcx_uv_work_t *n = (nfcx_uv_work_t *)w->data;
  n->result = n->fn(n->data);
}

static void nfcx_uv_after_cb(uv_work_t *w, int status) {
  nfcx_uv_work_t *n = (nfcx_uv_work_t *)w->data;
  (void)status;
  n->done = 1;
}

static inline void *
nfcx_thread_call_without_gvl(mrb_state *mrb, void *(*fn)(void *), void *data, void *ubf, void *data2)
{
  uv_loop_t *loop = mrb_uv_current_loop(mrb);
  uv_work_t w;
  nfcx_uv_work_t n = { fn, data, NULL, 0 };
  (void)ubf;
  (void)data2;
  w.data = &n;
  if (uv_queue_work(loop, &w, nfcx_uv_work_cb, nfcx_uv_after_cb) != 0)
    return NULL;
  while (!n.done)
    uv_run(loop, UV_RUN_ONCE);
  return n.result;
}
#endif
EOS

