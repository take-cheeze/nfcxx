#!/bin/bash
# Compiles each converted gem's src/*.c against the mruby headers, with the gem's corpus defines (corpus_flags.json), and links the
# objects as a shared object with --no-undefined against libmruby: a converted gem that compiles and links has no undefined symbols.
# usage: check_mruby_compile.sh CONVERTED_DIR GEM [GEM...]   (CONVERTED_DIR holds one converted gem per directory: CONVERTED_DIR/GEM)
# MRUBY_LIB (optional) lists the mruby archives to link, space-separated (default: MRUBY's build/host/lib/libmruby.a).
# MRUBY (default /home/user/mruby) is the mruby tree with build/host/lib/libmruby.a; MRUBY_UV (default /home/user/mruby-uv) is the
# mruby-uv tree that bcrypt's thread header needs.
HERE=$(cd "$(dirname "$0")" && pwd)
MR=${MRUBY:-/home/user/mruby}
UV=${MRUBY_UV:-/home/user/mruby-uv}
ROOT=${1:?usage: check_mruby_compile.sh CONVERTED_DIR GEM...}; shift
rc=0
for N in "$@"; do
  G="$ROOT/$N"
  # a gem with no converted directory is a failure, not an empty pass
  if [ ! -d "$G" ]; then echo "== $N: no converted gem at $G"; rc=1; continue; fi
  W=$(mktemp -d)
  DEFS=$(python3 -I "$HERE/corpus_defs.py" "$HERE/corpus_flags.json" "$N")
  INC="-I $G/include -I $MR/include -I $MR/build/host/include -I $UV/fork/src -I $UV/fork/include"
  # the fork builds every object with MRB_USE_BIGINT (mrbgems/mruby-bigint/mrbgem.rake): the bigint helpers are declared under it
  DEFS="$DEFS -DMRB_USE_BIGINT"
  # the same extra mruby gem headers the corpus runner gives (mruby-encoding, mruby-time, mruby-marshal)
  for d in $(echo "${NFCX_MRUBY_INCLUDE:-/home/user/mruby/include:/home/user/mruby/build/host/include:/home/user/mruby/mrbgems/mruby-encoding/include:/home/user/mruby/mrbgems/mruby-time/include:/home/user/nfcxx/3rd/mruby-marshal/include}" | tr : " "); do
    INC="$INC -I $d"
  done
  errs=0
  for c in "$G"/src/*.c "$G"/src/*.cc; do
    [ -f "$c" ] || continue
    b=$(basename "$c"); o="$W/${b%.*}.o"
    case "$c" in
      *.cc) cc="g++ -std=gnu++17"; have_cxx=1 ;;
      *) cc="gcc -std=gnu99" ;;
    esac
    if ! $cc -c -w -fPIC $DEFS $INC "$c" -o "$o" 2> "$W/$b.err"; then
      n=$(grep -c " error" "$W/$b.err"); errs=$((errs + n))
      grep " error" "$W/$b.err" | sed "s|^|$b: |" | cut -c1-200
    fi
  done
  objs=$(ls "$W"/*.o 2>/dev/null)
  if [ -n "$objs" ] && [ $errs -eq 0 ]; then
    # libmruby.a is not built position-independent, so the check links an executable (with a trivial main) against it: any
    # unresolved symbol of the gem is a link error
    # mrb_init_mrbgems and mrb_init_mrblib are generated by the mruby build (the gem list, the compiled mrblib): no-ops here
    printf '%s\n' 'typedef struct mrb_state mrb_state;' 'void mrb_init_mrbgems(mrb_state *mrb) { (void)mrb; }' \
      'void mrb_init_mrblib(mrb_state *mrb) { (void)mrb; }' 'int main(void) { return 0; }' > "$W/main.c"
    linker=gcc; [ -n "${have_cxx:-}" ] && linker=g++
    gcc -c -w "$W/main.c" -o "$W/main.o"
    $linker -o "$W/check" "$W/main.o" $objs -Wl,--start-group ${MRUBY_LIB:-$MR/build/host/lib/libmruby.a} -Wl,--end-group -lm 2> "$W/link.err" \
      || { echo "LINK $N: $(grep -o 'undefined reference to [^ ]*' "$W/link.err" | sort -u | head -8 | tr '\n' ' ')"; head -3 "$W/link.err" | cut -c1-200; errs=$((errs + 1)); }
  fi
  echo "== $N: compile-and-link errors=$errs"
  [ $errs -eq 0 ] || rc=1
  rm -rf "$W"
done
exit $rc
