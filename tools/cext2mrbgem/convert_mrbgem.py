#!/usr/bin/env python3
"""convert_mrbgem.py <cext_dir> <out_dir>

Text-only converter: a CRuby C extension directory (ext/<name>/ with *.c, *.h)
-> an mruby mrbgem directory (mrbgem.rake, src/*.c, src/gem_init.c, include/*.h).

The input is only read as text. It is never compiled, loaded or executed.
Mappings come from api_map.json next to this script. Any CRuby-looking API
identifier without a map entry is REFUSED: a marker comment
`/* BC2CPP-MRBGEM REFUSED: <api> */` is left in the output, the item is listed
in REFUSALS.txt, and the output is marked not buildable (NOT_BUILDABLE file,
#error in gem_init.c, raise in mrbgem.rake).

Exit status: 0 converted with no refusals; 2 refusals present (output written,
marked not buildable); 1 usage or input error.
"""

import glob
import json
import os
import re
import sys

NFCX_UV_THREAD_H = r'''/* nfcx_uv_thread.h: models CRuby's rb_thread_call_without_gvl on mruby-uv (generated by convert_mrbgem.py).
 * func runs on libuv's thread pool; the calling Ruby-side C code runs the loop until the work is done, so
 * the call stays synchronous as in CRuby. func must not touch mrb_state (no GVL section rules apply here).
 * ubf (the unblock function) is ignored: a blocked worker cannot be interrupted. NOT COMPILED. */
#ifndef NFCX_UV_THREAD_H
#define NFCX_UV_THREAD_H
#include <uv.h>
#include <mruby.h>
#include "mrb_uv.h"   /* mruby-uv: mrb_uv_current_loop */

typedef struct {
  void *(*fn)(void *);
  void *data;
  void *result;
  int done;
} nfcx_uv_work_t;

static void nfcx_uv_work_cb(uv_work_t *w) {
  nfcx_uv_work_t *n = (nfcx_uv_work_t *)w->data;
  n->result = n->fn(n->data);
}

static void nfcx_uv_after_cb(uv_work_t *w, int status) {
  nfcx_uv_work_t *n = (nfcx_uv_work_t *)w->data;
  (void)status;
  n->done = 1;
}

static inline void *
nfcx_thread_call_without_gvl(mrb_state *mrb, void *(*fn)(void *), void *data, void *ubf, void *data2)
{
  uv_loop_t *loop = mrb_uv_current_loop(mrb);
  uv_work_t w;
  nfcx_uv_work_t n = { fn, data, NULL, 0 };
  (void)ubf;
  (void)data2;
  w.data = &n;
  if (uv_queue_work(loop, &w, nfcx_uv_work_cb, nfcx_uv_after_cb) != 0)
    return NULL;
  while (!n.done)
    uv_run(loop, UV_RUN_ONCE);
  return n.result;
}
#endif
'''

# CRuby headers whose only use is a compatibility redefinition that the target libc does not need.
DROP_INCLUDES = {
    'ruby/util.h': 'only redefines strdup as ruby_strdup for libcs without it; mruby targets provide strdup',
}

HERE = os.path.dirname(os.path.abspath(__file__))
MAP_PATH = os.path.join(HERE, 'api_map.json')

IDENT_RE = re.compile(r'(?<![\w$])[A-Za-z_]\w*')
# A definition starts at a line start. Return-type words may be split across lines (`static VALUE` then
# `name(...)` on the next line, as bigdecimal and date write them); every word is followed by at least one
# separator, so the pattern has no ambiguous splits.
DEF_RE = re.compile(
    r'^[ \t]*((?:(?:static|inline|extern)[ \t\n]+)*)'
    r'((?:[A-Za-z_]\w*(?:[ \t\n]+|[ \t\n]*\*[ \t\n\*]*))+?)'
    r'([A-Za-z_]\w*)[ \t\n]*\(([^()]*)\)\s*(\{|;)', re.M)
INC_RE = re.compile(r'#[ \t]*include[ \t]*[<"](ruby(?:/[\w./-]*)?\.h)[>"]')
REG_RE = re.compile(r'(?<![\w$.>])(rb_define_method|rb_define_singleton_method)\s*\(')
CLASS_ASSIGN_RE = re.compile(r'(?<![\w$.>])(\w+)\s*=\s*rb_define_(?:class|module)(?:_under)?\s*\(')
NON_FUNC_WORDS = {'if', 'while', 'for', 'switch', 'return', 'sizeof', 'else', 'do', 'case', 'goto'}

# CRuby-looking identifiers that are not in api_map.json are refused.
UNKNOWN_RE = re.compile(
    r'^(rb_\w+|RB_\w+|RUBY_\w+|R[A-Z]{2,}_\w+|RTEST|RBASIC\w*|Q(nil|true|false|undef)|'
    r'(NUM2|INT2|LONG2|ULONG2|UINT2|DBL2|FIX2|FIXNUM_|ID2|SYM2|CHR2|LL2|ULL2)\w*|'
    r'SYMBOL_P|NIL_P|NIL_OR_UNDEF_P|Check_\w+|StringValue\w*|T_[A-Z]+|ANYARGS|'
    r'PRIsVALUE|CLASS_OF|SPECIAL_CONST_P|FL_\w+|OBJ_\w+)$')

GEM_NAME_RE = re.compile(r'^[A-Za-z][A-Za-z0-9_-]*$')


def param_names(d):
    """Names of the parameters of a function prototype or definition dict (from decl scan)."""
    names = set()
    for p in d['params'].split(','):
        m = re.search(r'([A-Za-z_]\w*)\s*(?:\[[^\]]*\]\s*)*$', p.strip())
        if m:
            names.add(m.group(1))
    return names


def line_of(text, pos):
    return text.count('\n', 0, pos) + 1


def blank(s):
    return ''.join('\n' if ch == '\n' else ' ' for ch in s)


def mask_c(src):
    """Same length as src; comment and literal bodies become spaces, newlines kept."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            out.append(blank(src[i:j]))
            i = j
        elif src.startswith('/*', i):
            j = src.find('*/', i + 2)
            j = n if j < 0 else j + 2
            out.append(blank(src[i:j]))
            i = j
        elif c in '"\'':
            j = i + 1
            while j < n and src[j] not in (c, '\n'):
                j += 2 if src[j] == '\\' else 1
            j = min(j, n)
            out.append(c + blank(src[i + 1:j]))
            if j < n and src[j] == c:
                out.append(c)
                i = j + 1
            else:
                i = j
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def match_close(masked, open_pos):
    depth = 0
    for k in range(open_pos, len(masked)):
        ch = masked[k]
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
            if depth == 0:
                return k
    return -1


def split_args(masked, open_pos, close_pos):
    """Top-level comma split of the argument list; returns trimmed (start, end) spans."""
    if masked[open_pos + 1:close_pos].strip() == '':
        return []
    spans, depth, start = [], 0, open_pos + 1
    for k in range(open_pos + 1, close_pos):
        ch = masked[k]
        if ch in '([{':
            depth += 1
        elif ch in ')]}':
            depth -= 1
        elif ch == ',' and depth == 0:
            spans.append((start, k))
            start = k + 1
    spans.append((start, close_pos))
    return [trim(masked, s, e) for s, e in spans]


def trim(masked, s, e):
    while s < e and masked[s].isspace():
        s += 1
    while e > s and masked[e - 1].isspace():
        e -= 1
    return s, e


def next_nonspace(masked, pos):
    k = pos
    while k < len(masked) and masked[k].isspace():
        k += 1
    return k if k < len(masked) else -1


def prev_nonspace(masked, pos):
    k = pos
    while k >= 0 and masked[k].isspace():
        k -= 1
    return k


def is_member(masked, s):
    j = prev_nonspace(masked, s - 1)
    if j < 0:
        return False
    return masked[j] == '.' or (masked[j] == '>' and j > 0 and masked[j - 1] == '-')


def call_context(masked, pos):
    """(callee name, top-level argument index) of the call enclosing pos, or (None, None)."""
    depth, commas, k = 0, 0, pos - 1
    while k >= 0:
        ch = masked[k]
        if ch in ')]}':
            depth += 1
        elif ch in '([{':
            if depth == 0:
                if ch != '(':
                    return None, None
                j = prev_nonspace(masked, k - 1)
                e = j + 1
                while j >= 0 and (masked[j].isalnum() or masked[j] == '_'):
                    j -= 1
                return (masked[j + 1:e] or None), commas
            depth -= 1
        elif ch == ',' and depth == 0:
            commas += 1
        elif ch == ';' and depth == 0:
            return None, None
        k -= 1
    return None, None


def map_types(s, types):
    for ctype, mtype in types.items():
        if ctype == 'ID':
            s = re.sub(r'\bID\b(?=\s+[A-Za-z_])', mtype, s)
        else:
            s = re.sub(r'\b%s\b' % re.escape(ctype), mtype, s)
    return s


class Edits:
    def __init__(self):
        self.items = []

    def add(self, s, e, text):
        self.items.append((s, e, text))

    def overlaps(self, s, e):
        return any(a < e and s < b for a, b, _ in self.items)

    def apply(self, text):
        items = sorted(self.items, key=lambda x: (x[0], x[1]))
        for p, q in zip(items, items[1:]):
            if q[0] < p[1]:
                raise RuntimeError('internal: overlapping edits at %d' % q[0])
        out = text
        for s, e, t in reversed(items):
            out = out[:s] + t + out[e:]
        return out


class Converter:
    def __init__(self, cext_dir, out_dir, name=None):
        self.cext_dir = os.path.abspath(cext_dir)
        self.out_dir = os.path.abspath(out_dir)
        self.name = name or os.path.basename(self.cext_dir.rstrip('/'))
        self.funcname = self.name.replace('-', '_')
        with open(MAP_PATH, encoding='utf-8') as fh:
            amap = json.load(fh)
        self.entries = amap['entries']
        self.types = amap['types']
        self.special_pos = amap['special_arg_positions_class_only']
        self.files = {}      # rel -> {'text','masked','kind'}
        self.edits = {}      # rel -> Edits
        self.ignored = []
        self.warnings = []
        self.refusals = []
        self.rewrites = []
        self.class_vars = set()
        self.decl_name_pos = set()
        self.regs = []
        self.reg_by_call = {}
        self.reg_names = set()
        self.valid_reg_names = set()  # registered functions whose registration survived check_refs
        self.decls = []      # dicts for function prototypes and definitions
        self.defs = {}       # name -> [def dicts]
        self.init_defs = []
        self.occ = {}        # identifier -> [(rel, start, end)]
        self.needs = set()
        self.helper_names = set()
        self.init_rel = None

    # ---- reporting -------------------------------------------------------
    def extconf_entry(self):
        path = os.path.join(self.cext_dir, 'extconf.rb')
        if not os.path.isfile(path):
            return None
        with open(path, encoding='utf-8', errors='replace') as fh:
            m = re.search(r'create_makefile\(\s*[\'"]([\w/.-]+)[\'"]', fh.read())
        return m.group(1) if m else None

    def in_dead_init(self, rel, pos):
        return any(d['file'] == rel and d['hstart'] <= pos <= d['body_end'] for d in self.dead_inits)

    def enclosing_func(self, rel, pos):
        for lst in self.defs.values():
            for d in lst:
                if d['file'] == rel and 'brace' in d and d['brace'] < pos < d['body_end']:
                    return d
        return None

    def refuse(self, rel, pos, api, reason):
        if rel is None:
            self.refusals.append({'file': '(gem)', 'line': 0, 'api': api, 'reason': reason})
            return
        if self.in_dead_init(rel, pos):
            return
        text = self.files[rel]['text']
        self.refusals.append({'file': rel, 'line': line_of(text, pos), 'api': api, 'reason': reason})
        self.edits[rel].add(pos, pos, '/* BC2CPP-MRBGEM REFUSED: %s */ ' % api)

    def uses_uv_thread(self):
        return any(r['to'] == 'nfcx_thread_call_without_gvl' for r in self.rewrites)

    def rewrite(self, rel, pos, src, dst, caveat=None):
        text = self.files[rel]['text']
        rec = {'file': rel, 'line': line_of(text, pos), 'from': src, 'to': dst}
        if caveat:
            rec['caveat'] = caveat
        self.rewrites.append(rec)

    # ---- stage 1: load ---------------------------------------------------
    def load(self):
        if not os.path.isdir(self.cext_dir):
            sys.exit('error: not a directory: %s' % self.cext_dir)
        if not GEM_NAME_RE.match(self.name):
            sys.exit('error: cannot derive a gem name from %s' % self.cext_dir)
        for path in sorted(glob.glob(os.path.join(self.cext_dir, '*'))):
            base = os.path.basename(path)
            if os.path.isdir(path):
                self.ignored.append((base, 'subdirectory not converted'))
                continue
            if not (base.endswith('.c') or base.endswith('.h')):
                self.ignored.append((base, 'not a C source or header (read by nothing; extconf.rb is never run)'))
                continue
            with open(path, encoding='utf-8', errors='replace') as fh:
                text = fh.read()
            kind = 'src' if base.endswith('.c') else 'hdr'
            if base == 'gem_init.c':
                self.refuse(base, 0, 'gem_init.c', 'name collides with the generated gem_init.c')
            self.files[base] = {'text': text, 'masked': mask_c(text), 'kind': kind}
            self.edits[base] = Edits()

    # ---- stage 2: classes, registrations, definitions ---------------------
    def scan(self):
        for rel, f in self.files.items():
            for m in CLASS_ASSIGN_RE.finditer(f['masked']):
                self.class_vars.add(m.group(1))
        for rel, f in self.files.items():
            if f['kind'] != 'src':
                continue
            text, masked = f['text'], f['masked']
            for m in REG_RE.finditer(masked):
                cs, op = m.start(1), m.end() - 1
                cp = match_close(masked, op)
                rec = {'file': rel, 'call': cs, 'open': op, 'close': cp, 'api': m.group(1),
                       'error': None, 'func': None, 'argc': None, 'target': None,
                       'func_span': None, 'argc_span': None}
                if cp < 0:
                    rec['error'] = 'unbalanced parentheses in registration call'
                else:
                    args = split_args(masked, op, cp)
                    if len(args) != 4:
                        rec['error'] = 'registration call has %d arguments, expected 4' % len(args)
                    else:
                        (ts, te), (ns, ne), (fs, fe), (as_, ae) = args
                        rec['target'] = text[ts:te].strip()
                        nm = re.fullmatch(r'"([^"\\\n]*)"', text[ns:ne].strip())
                        fm = re.fullmatch(r'(?:\(\s*VALUE\s*\(\s*\*\s*\)\s*\(\s*ANYARGS\s*\)\s*\)\s*)?([A-Za-z_]\w*)',
                                          text[fs:fe].strip())
                        am = re.fullmatch(r'-?\d+', text[as_:ae].strip())
                        rec['func_span'] = (fs, fe)
                        rec['argc_span'] = (as_, ae)
                        if am is None:
                            rec['error'] = 'argc is not an integer literal'
                        elif int(am.group()) < -1:
                            # -1 is the variadic form (int argc, VALUE *argv, VALUE self); -2 takes an array
                            rec['error'] = ('argc %s (array form) is not in the supported subset'
                                            % am.group())
                        elif fm is None:
                            rec['error'] = ('method function argument is not a plain function name '
                                            '(only the VALUE (*)(ANYARGS) cast is handled)')
                        elif nm is None:
                            rec['error'] = 'method name is not a plain string literal'
                        else:
                            rec['func'] = fm.group(1)
                            rec['argc'] = int(am.group())
                            rec['name'] = nm.group(1)
                self.regs.append(rec)
                self.reg_by_call[(rel, cs)] = rec
        # one arity per registered function
        arities = {}
        for r in self.regs:
            if r['error'] is None:
                arities.setdefault(r['func'], set()).add(r['argc'])
        for r in self.regs:
            if r['error'] is None and len(arities[r['func']]) > 1:
                r['error'] = 'function %s is registered with conflicting arities' % r['func']
        for r in self.regs:
            if r['error'] is None:
                self.reg_names.add(r['func'])
        # declarations and definitions
        for rel, f in self.files.items():
            if f['kind'] != 'src':
                continue
            text, masked = f['text'], f['masked']
            for m in DEF_RE.finditer(masked):
                storage, name, term = m.group(1), m.group(3), m.group(5)
                ret = re.sub(r'[\s\*]+$', '', m.group(2))  # trailing pointer stars are dropped, as before
                if name in NON_FUNC_WORDS or ret.split()[-1] in NON_FUNC_WORDS:
                    continue
                po = masked.find('(', m.start(3))
                pc = masked.find(')', po)
                d = {'file': rel, 'name': name, 'storage': storage, 'ret': ret,
                     'hstart': m.start(), 'po': po, 'pc': pc,
                     'params': text[po + 1:pc], 'proto': term == ';'}
                if term == '{':
                    d['brace'] = m.end() - 1
                    d['body_end'] = match_close(masked, d['brace'])
                    d['hend'] = d['brace']
                    self.defs.setdefault(name, []).append(d)
                    if name.startswith('Init_'):
                        self.init_defs.append(d)
                else:
                    d['hend'] = pc + 1
                self.decls.append(d)
        # class variables declared as VALUE (decl name positions are skipped later)
        for rel, f in self.files.items():
            for C in self.class_vars:
                for m in re.finditer(r'\bVALUE\b\s+%s\b(?=\s*[=;,\[])' % re.escape(C), f['masked']):
                    self.decl_name_pos.add((rel, m.end() - len(C)))

    def build_occurrences(self):
        for rel, f in self.files.items():
            for m in IDENT_RE.finditer(f['masked']):
                if is_member(f['masked'], m.start()):
                    continue
                self.occ.setdefault(m.group(), []).append((rel, m.start(), m.end()))

    def body_idents(self, d):
        masked = self.files[d['file']]['masked']
        return set(IDENT_RE.findall(masked[d['brace']:d['body_end'] + 1]))

    def compute_needs(self):
        ids = {}
        for name, lst in self.defs.items():
            for d in lst:
                ids.setdefault(name, set()).update(self.body_idents(d))
        forced = set(self.reg_names) | {d['name'] for d in self.init_defs}
        needs = set(forced)
        for name, s in ids.items():
            if any(self.entries.get(i, {}).get('needs_mrb') for i in s):
                needs.add(name)
        changed = True
        while changed:
            changed = False
            for name, s in ids.items():
                if name not in needs and any(c in needs for c in s if c in self.defs):
                    needs.add(name)
                    changed = True
        self.needs = needs

    def check_refs(self):
        # Init functions: CRuby calls only Init_<entry>, where <entry> is the name extconf.rb passes to
        # create_makefile. Other Init_ functions are dead code in the extension: they are kept under #if 0.
        self.dead_inits = []
        entry = self.extconf_entry()
        if entry and self.init_defs:
            want = 'Init_%s' % entry.split('/')[-1]
            chosen = [d for d in self.init_defs if d['name'] == want]
            if chosen:
                self.dead_inits = [d for d in self.init_defs if d is not chosen[0]]
                self.init_defs = chosen
                for d in self.dead_inits:
                    self.ignored.append((d['file'], 'Init_ function %s is not the entry (create_makefile names %s): kept under #if 0'
                                         % (d['name'], entry)))
            else:
                self.refuse(None, 0, want, 'create_makefile names %s but no %s is defined in the input' % (entry, want))
        for extra in self.init_defs[1:]:
            self.refuse(extra['file'], extra['hstart'], extra['name'],
                        'multiple Init_ functions in one extension are not supported')
        if self.init_defs:
            self.init_rel = self.init_defs[0]['file']
        else:
            self.refuse(None, 0, 'Init_%s' % self.name, 'no Init_<name> function found')
        init_first = self.init_defs[0]['name'] if self.init_defs else None
        # registered functions: must be defined; must not be called directly
        for r in self.regs:
            if r['error'] is None and r['func'] not in self.defs:
                self.refuse(r['file'], r['call'], r['func'],
                            'registered function has no definition in the input')
                r['error'] = 'registered function has no definition in the input'
        for r in self.regs:
            if r['error'] is None:
                continue
        valid_reg = [r for r in self.regs if r['error'] is None]
        self.valid_reg_names = {r['func'] for r in valid_reg}
        # variadic methods (argc -1): (argc, argv, self) parameter names, used by rb_scan_args
        self.variadic = {}
        for r in valid_reg:
            if r['argc'] == -1 and r['func'] in self.defs:
                p = self.variadic_params(self.defs[r['func']][0])
                if p:
                    self.variadic[r['func']] = p
        for name in self.reg_names:
            spans = [(r['open'], r['close']) for r in valid_reg if r['func'] == name and r['file']]
            for rel, s, e in self.occ.get(name, []):
                if any(rel == r['file'] and r['open'] <= s <= r['close'] for r in valid_reg):
                    continue
                if any(rel == d['file'] and d['hstart'] <= s < d['hend'] for d in self.decls
                       if d['name'] == name):
                    continue
                self.refuse(rel, s, name, 'registered method function is also called directly (not supported)')
        # helper functions that need the mruby state
        for name in sorted(self.needs):
            if name in self.reg_names or name == init_first or name not in self.defs:
                continue
            defs = self.defs[name]
            def_file = defs[0]['file']
            ok = len(defs) == 1
            for rel, s, e in self.occ.get(name, []):
                if any(rel == d['file'] and d['hstart'] <= s < d['hend'] for d in self.decls
                       if d['name'] == name):
                    continue
                if rel != def_file or next_nonspace(self.files[rel]['masked'], e) < 0 or \
                        self.files[rel]['masked'][next_nonspace(self.files[rel]['masked'], e)] != '(':
                    ok = False
                    self.refuse(rel, s, name,
                                'helper needs the mruby state threaded in, but is used outside a direct call '
                                'in its own file (not supported)')
            if ok:
                self.helper_names.add(name)
            else:
                d0 = defs[0]
                self.refuse(d0['file'], d0['hstart'], name, 'helper needs mruby state; threading refused')

    # ---- stage 3: per-file rewrite --------------------------------------
    def variadic_params(self, d):
        """(argc, argv, self) parameter names of a variadic (argc -1) method definition, or None.
        mruby calls every method as f(mrb, self) and hands the arguments over through mrb_get_args, so
        the converted function reads them back with the "*" format into locals of the original names."""
        params = [p.strip() for p in d['params'].split(',')]
        if len(params) != 3:
            return None
        m_argc = re.fullmatch(r'int\s+([A-Za-z_]\w*)', params[0])
        m_argv = re.fullmatch(r'VALUE\s*\*\s*([A-Za-z_]\w*)', params[1])
        m_self = re.fullmatch(r'VALUE\s+([A-Za-z_]\w*)', params[2])
        if not (m_argc and m_argv and m_self):
            return None
        return m_argc.group(1), m_argv.group(1), m_self.group(1)

    def registered_header(self, d):
        regs = [r for r in self.regs if r['error'] is None and r['func'] == d['name']]
        n = regs[0]['argc']
        if d['ret'] != 'VALUE':
            return None, None, 'registered method must return VALUE (found %r)' % d['ret']
        if n == -1:
            p = self.variadic_params(d)
            if p is None:
                return None, None, ('variadic registered method must take (int argc, VALUE *argv, VALUE self)'
                                    ' (found %r)' % d['params'].strip())
            argc_n, argv_n, self_n = p
            hdr = '%smrb_value %s(mrb_state *mrb, mrb_value %s)' % (d['storage'], d['name'], self_n)
            prologue = ('\n  mrb_int nfcx_argc;\n  mrb_value *%s;\n  mrb_get_args(mrb, "*", &%s, &nfcx_argc);'
                        '\n  int %s = (int)nfcx_argc;') % (argv_n, argv_n, argc_n)
            return hdr, prologue, None
        params = [p.strip() for p in d['params'].split(',')]
        if len(params) != n + 1:
            return None, None, ('registered method has %d parameters, arity %d needs %d'
                                % (len(params), n, n + 1))
        names = []
        for p in params:
            mm = re.fullmatch(r'VALUE\s+([A-Za-z_]\w*)', p)
            if not mm:
                return None, None, 'parameter %r is not a plain VALUE' % p
            names.append(mm.group(1))
        hdr = '%smrb_value %s(mrb_state *mrb, mrb_value %s)' % (d['storage'], d['name'], names[0])
        prologue = ''
        if n > 0:
            prologue = '\n  mrb_value %s;\n  mrb_get_args(mrb, "%s", %s);' % (
                ', '.join(names[1:]), 'o' * n, ', '.join('&' + x for x in names[1:]))
        return hdr, prologue, None

    def process(self, rel):
        f = self.files[rel]
        text, masked, E = f['text'], f['masked'], self.edits[rel]
        # 1. includes (directives only; masked check skips commented-out ones)
        for m in INC_RE.finditer(text):
            if masked[m.start()] != '#':
                continue
            inc = m.group(1)
            if inc == 'ruby.h':
                repl = '#include <mruby.h>\n#include <mruby/string.h>\n#include <mruby/numeric.h>'
                E.add(m.start(), m.end(), repl)
                self.rewrite(rel, m.start(), m.group(), repl.replace('\n', ' | '))
            elif inc in DROP_INCLUDES:
                reason = DROP_INCLUDES[inc]
                E.add(m.start(), m.end(), '/* BC2CPP-MRBGEM dropped: #include <%s> (%s) */' % (inc, reason))
                self.warnings.append({'file': rel, 'line': line_of(text, m.start()), 'api': '#include <%s>' % inc,
                                      'reason': reason})
                print('warning: %s:%d dropped #include <%s> (%s)' % (rel, line_of(text, m.start()), inc, reason),
                      file=sys.stderr)
            elif inc == 'ruby/thread.h':
                repl = '#include "nfcx_uv_thread.h"  /* thread model on mruby-uv */'
                E.add(m.start(), m.end(), repl)
                if 'HAVE_RUBY_THREAD_H' in masked:
                    # CRuby's extconf sets this; the thread code is guarded by it, so the converter defines it.
                    E.add(0, 0, '#define HAVE_RUBY_THREAD_H 1  /* set by the converter: thread model is on */\n')
                    self.rewrite(rel, 0, 'HAVE_RUBY_THREAD_H', 'defined by converter', 'extconf config macro set on')
                self.rewrite(rel, m.start(), m.group(), repl, 'thread API modelled on mruby-uv')
            else:
                self.refuse(rel, m.start(), '#include <%s>' % inc, 'CRuby header not in the supported subset')
        # 2. function headers
        prologue_at = {}
        for d in self.decls:
            if d['file'] != rel:
                continue
            name = d['name']
            hdr, pro, err = None, '', None
            # Only a function with a surviving registration gets the method signature. A refused registration
            # (e.g. no definition in the input) leaves its prototype as is; the refusal is already recorded.
            if name in self.valid_reg_names:
                hdr, pro, err = self.registered_header(d)
                if d['proto']:
                    pro = ''
            elif d['name'] == (self.init_defs[0]['name'] if self.init_defs else None) and not d['proto']:
                hdr = 'void mrb_%s_gem_init(mrb_state *mrb)' % self.funcname
            elif name in self.helper_names:
                ptxt = d['params'].strip()
                tail = '' if ptxt in ('', 'void') else ', ' + map_types(ptxt, self.types)
                hdr = '%s%s %s(mrb_state *mrb%s)' % (d['storage'], map_types(d['ret'], self.types), name, tail)
            if err:
                self.refuse(rel, d['hstart'], name, err)
                continue
            if hdr is None:
                continue
            if d['proto']:
                E.add(d['hstart'], d['hend'], hdr)
            else:
                E.add(d['hstart'], d['hend'], hdr + ' ')
                if pro:
                    E.add(d['brace'] + 1, d['brace'] + 1, pro)
                self.rewrite(rel, d['hstart'], d['name'] + '(...)', hdr)
        # 3. class variable declarations become struct RClass *
        # A VALUE parameter that has a class variable's name is an ordinary parameter (it shadows the class
        # variable in its function) and is left alone.
        for C in sorted(self.class_vars):
            for m in re.finditer(r'\bVALUE\b\s+%s\b(?=\s*[=;,\[])' % re.escape(C), masked):
                if self.is_param(rel, m.start(), C):
                    continue
                E.add(m.start(), m.start() + len('VALUE'), 'struct RClass *')
                self.rewrite(rel, m.start(), 'VALUE ' + C, 'struct RClass *' + ' ' + C)
            for mm in re.finditer(r'\bVALUE\b[^;(){}]*,\s*%s\b' % re.escape(C), masked):
                if self.is_param(rel, mm.start(), C):
                    continue
                self.refuse(rel, mm.start(), C, 'multi-declarator class variable declaration not supported')
                break
        # 4. helper call sites get the mrb argument
        header_spans = [(d['hstart'], d['hend']) for d in self.decls if d['file'] == rel]
        for name in self.helper_names:
            for orel, s, e in self.occ.get(name, []):
                if orel != rel or any(a <= s < b for a, b in header_spans):
                    continue
                po = next_nonspace(masked, e)
                if po < 0 or masked[po] != '(':
                    continue
                pa = next_nonspace(masked, po + 1)
                E.add(po + 1, po + 1, 'mrb' if masked[pa] == ')' else 'mrb, ')
        # 5. identifier pass
        local_syms = set(self.defs) | {d['name'] for d in self.decls} | self.class_vars
        body_spans = [(d['brace'], d['body_end']) for lst in self.defs.values() for d in lst
                      if d['file'] == rel]
        for m in IDENT_RE.finditer(masked):
            s, e = m.span()
            name = m.group()
            if is_member(masked, s) or E.overlaps(s, e):
                continue
            entry = self.entries.get(name)
            if entry is not None:
                if entry.get('needs_mrb') and not any(a < s < b for a, b in body_spans):
                    self.refuse(rel, s, name, 'needs the mruby state, which is not in scope at file scope')
                    continue
                self.map_entry(rel, s, e, name, entry)
            elif name in self.types:
                if name == 'ID' and not re.match(r'\s+[A-Za-z_]', masked[e:e + 40] or ''):
                    continue
                E.add(s, e, self.types[name])
                self.rewrite(rel, s, name, self.types[name])
            elif UNKNOWN_RE.match(name) and name not in local_syms:
                self.refuse(rel, s, name, 'no entry in api_map.json')
            elif name in self.class_vars:
                if (rel, s) in self.decl_name_pos or self.is_param(rel, s, name):
                    continue
                nx = next_nonspace(masked, e)
                if nx >= 0 and masked[nx] == '=' and masked[nx + 1:nx + 2] != '=':
                    continue
                callee, idx = call_context(masked, s)
                if callee and idx in self.special_pos.get(callee, []):
                    continue
                E.add(s, e, 'mrb_obj_value(%s)' % name)
                self.rewrite(rel, s, name, 'mrb_obj_value(%s)' % name)
        # 6. mrb name clash in files that get the mrb parameter
        if any(d['file'] == rel and (d['name'] in self.needs) for d in self.decls):
            mm = re.search(r'\bmrb\b', masked)
            if mm:
                self.refuse(rel, mm.start(), 'mrb', 'source already uses the identifier mrb (clashes with the state parameter)')

    def is_param(self, rel, pos, name):
        """True if name at pos is a parameter of the function (its header, or its body) that encloses pos.
        A parameter shadows a file-scope class variable of the same name, so it must not be rewritten."""
        for d in self.decls:
            if d['file'] != rel:
                continue
            if d['hstart'] <= pos < d['hend']:
                return name in param_names(d)
            if 'body_end' in d and d['brace'] < pos < d['body_end'] and name in param_names(d):
                return True
        return False

    def map_entry(self, rel, s, e, name, entry):
        masked = self.files[rel]['masked']
        E = self.edits[rel]
        kind = entry['kind']
        nxt = next_nonspace(masked, e)
        called = nxt >= 0 and masked[nxt] == '('
        if kind == 'refuse':
            self.refuse(rel, s, name, entry['reason'])
        elif kind == 'special':
            self.special(rel, s, e, name, entry, nxt, called)
        elif kind == 'drop':
            # Declaration with no effect in mruby: the call is removed and a warning is printed and recorded.
            if not called:
                self.refuse(rel, s, name, 'used without a call; cannot drop it')
                return
            close = masked.find(')', nxt)
            end = close + 1
            semi = next_nonspace(masked, end)
            if semi >= 0 and masked[semi] == ';':
                end = semi + 1
            E.add(s, end, '/* BC2CPP-MRBGEM dropped: %s (%s) */' % (name, entry['reason']))
            self.warnings.append({'file': rel, 'line': line_of(self.files[rel]['text'], s), 'api': name,
                                  'reason': entry['reason']})
            print('warning: %s:%d dropped %s (%s)' % (rel, line_of(self.files[rel]['text'], s), name, entry['reason']),
                  file=sys.stderr)
        elif kind == 'call':
            if not called:
                self.refuse(rel, s, name, 'used without a call; no expression form in api_map.json')
                return
            E.add(s, e, entry['mruby'])
            if entry.get('inject_mrb'):
                pa = next_nonspace(masked, nxt + 1)
                E.add(nxt + 1, nxt + 1, 'mrb' if masked[pa] == ')' else 'mrb, ')
            self.rewrite(rel, s, name, entry['mruby'], entry.get('caveat'))
        elif kind == 'macro':
            if entry['mruby'] != name:
                E.add(s, e, entry['mruby'])
                self.rewrite(rel, s, name, entry['mruby'])
        elif kind == 'expr':
            if called:
                self.refuse(rel, s, name, 'expression mapping used in call form')
                return
            E.add(s, e, entry['mruby'])
            self.rewrite(rel, s, name, entry['mruby'])
        else:
            self.refuse(rel, s, name, 'unknown kind %r in api_map.json' % kind)

    def special(self, rel, s, e, name, entry, nxt, called):
        masked = self.files[rel]['masked']
        text = self.files[rel]['text']
        E = self.edits[rel]
        if name == 'RB_GC_GUARD':
            fn = self.enclosing_func(rel, s)
            if not called or fn is None or fn['name'] not in self.needs:
                self.refuse(rel, s, name, 'GC guard outside a function that has an mrb_state in scope')
                return
            close = masked.find(')', nxt)
            arg = text[nxt + 1:close].strip()
            if close < 0 or not re.fullmatch(r'[A-Za-z_]\w*', arg):
                self.refuse(rel, s, name, 'GC guard argument is not a plain variable')
                return
            E.add(s, close + 1, 'mrb_gc_protect(mrb, %s)' % arg)
            self.rewrite(rel, s, name, 'mrb_gc_protect(mrb, %s)' % arg,
                         'keeps the value rooted until the arena is restored (fine within the call; use mrb_gc_register to outlive it)')
            return
        if name in ('rb_define_method', 'rb_define_singleton_method'):
            rec = self.reg_by_call.get((rel, s))
            if rec is None or not called or nxt != rec['open']:
                self.refuse(rel, s, name, 'used without a registration call')
                return
            if rec['error']:
                self.refuse(rel, s, name, rec['error'])
                return
            tgt = rec['target']
            if tgt not in self.class_vars and tgt != 'rb_cObject':
                self.refuse(rel, s, name, 'target %r is not a tracked class or module variable' % tgt)
                return
            new = 'mrb_define_method' if name == 'rb_define_method' else 'mrb_define_class_method'
            E.add(s, e, new)
            E.add(nxt + 1, nxt + 1, 'mrb, ')
            fs, fe = rec['func_span']
            E.add(fs, fe, rec['func'])
            as_, ae = rec['argc_span']
            if rec['argc'] == -1:
                aspec = 'MRB_ARGS_ANY()'  # the function reads its arguments itself (see variadic_params)
            else:
                aspec = 'MRB_ARGS_NONE()' if rec['argc'] == 0 else 'MRB_ARGS_REQ(%d)' % rec['argc']
            E.add(as_, ae, aspec)
            self.rewrite(rel, s, name, '%s(mrb, %s, "%s", %s, %s)' % (
                new, tgt, rec['name'], rec['func'], aspec))
        elif name == 'rb_scan_args':
            self.scan_args(rel, s, e, nxt, called)
        elif name == 'rb_raise':
            if not called:
                self.refuse(rel, s, name, 'used without a call')
                return
            cp = match_close(masked, nxt)
            args = split_args(masked, nxt, cp) if cp > 0 else []
            if len(args) < 2:
                self.refuse(rel, s, name, 'rb_raise needs an exception class and a format string')
                return
            fmt = text[args[1][0]:args[1][1]]
            if 'PRIsVALUE' in fmt:
                self.refuse(rel, s, name, 'PRIsVALUE format (VALUE to string) not supported')
                return
            E.add(s, e, 'mrb_raisef')
            E.add(nxt + 1, nxt + 1, 'mrb, ')
            self.rewrite(rel, s, name, 'mrb_raisef')
        else:
            self.refuse(rel, s, name, 'unknown special handler')

    def scan_args(self, rel, s, e, nxt, called):
        """rb_scan_args(argc, argv, FMT, &v...) in a variadic method, as a statement, with FMT of the form
        "<lead><opt>" (no rest, keyword or block parts) -> mrb_get_args(mrb, "o|o", &v...). mrb_get_args reads
        the same stack the method was called with, and its arity check is the one rb_scan_args makes. Optional
        outputs are set to nil first, because mrb_get_args leaves a missing optional argument unwritten."""
        masked, text, E = self.files[rel]['masked'], self.files[rel]['text'], self.edits[rel]
        fn = self.enclosing_func(rel, s)
        if not called or fn is None or fn['name'] not in self.variadic:
            self.refuse(rel, s, 'rb_scan_args', 'only supported directly in a variadic method (argc -1)')
            return
        close = match_close(masked, nxt)
        args = split_args(masked, nxt, close) if close > 0 else []
        if len(args) < 3:
            self.refuse(rel, s, 'rb_scan_args', 'rb_scan_args needs argc, argv and a format string')
            return
        argc_n, argv_n, self_n = self.variadic[fn['name']]
        if text[args[0][0]:args[0][1]] != argc_n or text[args[1][0]:args[1][1]] != argv_n:
            self.refuse(rel, s, 'rb_scan_args', 'rb_scan_args is not called on the argc and argv of its method')
            return
        fm = re.fullmatch(r'"([0-9])([0-9]?)"', text[args[2][0]:args[2][1]])
        if not fm:
            self.refuse(rel, s, 'rb_scan_args',
                        'format %s not supported (only "<lead><optional>" counts: no rest, keyword or block parts)'
                        % text[args[2][0]:args[2][1]])
            return
        lead, opt = int(fm.group(1)), int(fm.group(2) or 0)
        outs = args[3:]
        if len(outs) != lead + opt:
            self.refuse(rel, s, 'rb_scan_args', 'format needs %d output pointer(s), call gives %d' % (lead + opt, len(outs)))
            return
        names = []
        for a, b in outs:
            om = re.fullmatch(r'&\s*([A-Za-z_]\w*)', text[a:b])
            if not om or om.group(1) in self.class_vars or om.group(1) in (argc_n, argv_n, self_n):
                self.refuse(rel, s, 'rb_scan_args', 'output %r is not a plain local variable' % text[a:b])
                return
            names.append(om.group(1))
        prev = prev_nonspace(masked, s - 1)
        after = next_nonspace(masked, close + 1)
        if (prev >= 0 and masked[prev] not in ';{}') or after < 0 or masked[after] != ';':
            self.refuse(rel, s, 'rb_scan_args', 'the return value of rb_scan_args is used (mruby returns a different count)')
            return
        fmt = 'o' * lead + ('|' + 'o' * opt if opt else '')
        pre = ''.join('%s = mrb_nil_value(), ' % n for n in names[lead:])
        callargs = ', '.join(['mrb', '"%s"' % fmt] + ['&' + n for n in names])
        E.add(s, close + 1, '(%smrb_get_args(%s))' % (pre, callargs))
        self.rewrite(rel, s, 'rb_scan_args', 'mrb_get_args(mrb, "%s", ...)' % fmt,
                     'optional outputs are set to nil first (as rb_scan_args does); mruby arity errors are ArgumentError as in CRuby')

    # ---- stage 4: write --------------------------------------------------
    def write_outputs(self):
        src_dir = os.path.join(self.out_dir, 'src')
        inc_dir = os.path.join(self.out_dir, 'include')
        os.makedirs(src_dir, exist_ok=True)
        os.makedirs(inc_dir, exist_ok=True)
        outputs = {}
        for rel, f in self.files.items():
            outputs[rel] = self.edits[rel].apply(f['text'])
        for rel, f in self.files.items():
            dest = os.path.join(src_dir if f['kind'] == 'src' else inc_dir, rel)
            with open(dest, 'w', encoding='utf-8') as fh:
                fh.write(outputs[rel])
        if self.uses_uv_thread():
            with open(os.path.join(inc_dir, 'nfcx_uv_thread.h'), 'w', encoding='utf-8') as fh:
                fh.write(NFCX_UV_THREAD_H)
        fn = self.funcname
        init_file = self.init_rel
        gem_init = []
        if self.refusals:
            gem_init.append('#error "BC2CPP-MRBGEM: NOT BUILDABLE, see REFUSALS.txt"')
        gem_init += [
            '/* Generated by convert_mrbgem.py from ext/%s. */' % self.name,
            '#include <mruby.h>',
            '',
            ('/* mrb_%s_gem_init is defined in src/%s (the converted Init_ function). */' % (fn, init_file)) if init_file else
            'void\nmrb_%s_gem_init(mrb_state *mrb)  /* no Init_ function: see REFUSALS.txt */\n{\n  (void)mrb;\n}' % fn,
            '',
            'void',
            'mrb_%s_gem_final(mrb_state *mrb)' % fn,
            '{',
            '  (void)mrb;',
            '}',
            '',
        ]
        with open(os.path.join(src_dir, 'gem_init.c'), 'w', encoding='utf-8') as fh:
            fh.write('\n'.join(gem_init))
        status = 'NOT BUILDABLE' if self.refusals else 'no refusals (NOT compiled or tested)'
        rake = [
            '# Generated by convert_mrbgem.py from CRuby ext/%s. Fill in the TODO fields.' % self.name,
        ]
        if self.refusals:
            rake.append('raise "BC2CPP-MRBGEM: %s is NOT BUILDABLE (%d refusal(s)); see REFUSALS.txt"'
                        % (self.name, len(self.refusals)))
        rake += [
            '',
            "MRuby::Gem::Specification.new('%s') do |spec|" % self.name,
            "  spec.license = 'TODO'",
            "  spec.author  = 'TODO'",
            "  spec.summary = 'converted from CRuby ext/%s'" % self.name,
        ] + (["  spec.add_dependency 'mruby-uv'  # thread model: nfcx_uv_thread.h"] if self.uses_uv_thread() else []) + [
            'end',
            '',
        ]
        with open(os.path.join(self.out_dir, 'mrbgem.rake'), 'w', encoding='utf-8') as fh:
            fh.write('\n'.join(rake))
        lines = ['BC2CPP-MRBGEM refusals for ext/%s' % self.name,
                 'STATUS: %s (%d refusal(s))' % (status, len(self.refusals)), '']
        for r in self.refusals:
            lines.append('%s:%d  %s  %s' % (r['file'], r['line'], r['api'], r['reason']))
        with open(os.path.join(self.out_dir, 'REFUSALS.txt'), 'w', encoding='utf-8') as fh:
            fh.write('\n'.join(lines) + '\n')
        if self.warnings:
            with open(os.path.join(self.out_dir, 'WARNINGS.txt'), 'w', encoding='utf-8') as fh:
                for w in self.warnings:
                    fh.write('%s:%d  %s  dropped: %s\n' % (w['file'], w['line'], w['api'], w['reason']))
        marker = os.path.join(self.out_dir, 'NOT_BUILDABLE')
        if self.refusals:
            with open(marker, 'w', encoding='utf-8') as fh:
                fh.write('%d refusal(s); see REFUSALS.txt\n' % len(self.refusals))
        elif os.path.exists(marker):
            os.remove(marker)
        log = {'gem': self.name, 'funcname': fn, 'init_file': init_file,
               'rewrites': self.rewrites, 'refusals': self.refusals,
               'ignored': [{'file': a, 'why': b} for a, b in self.ignored],
               'helpers_threaded': sorted(self.helper_names),
               'registered': [{'name': r.get('name'), 'c_func': r['func'], 'argc': r['argc'],
                               'target': r['target'], 'error': r['error']} for r in self.regs]}
        with open(os.path.join(self.out_dir, 'conversion_log.json'), 'w', encoding='utf-8') as fh:
            json.dump(log, fh, indent=1)
        return len(self.rewrites), len(self.refusals)

    def run(self):
        self.load()
        self.scan()
        self.build_occurrences()
        self.compute_needs()
        self.check_refs()
        for rel in sorted(self.files):
            self.process(rel)
        for d in self.dead_inits:
            self.edits[d['file']].add(d['hstart'], d['hstart'],
                                      '#if 0  /* BC2CPP-MRBGEM: not the extension entry; CRuby never calls it */\n')
            self.edits[d['file']].add(d['body_end'] + 1, d['body_end'] + 1, '\n#endif\n')
        n_rw, n_ref = self.write_outputs()
        print('converted %s: %d rewrite(s), %d refusal(s), %d registered method(s) -> %s'
              % (self.name, n_rw, n_ref, len([r for r in self.regs if r['error'] is None]), self.out_dir))
        return 2 if self.refusals else 0


def main(argv):
    args = argv[1:]
    name = None
    if len(args) == 4 and args[0] == '--name':
        name, args = args[1], args[2:]
    if len(args) != 2:
        print('usage: convert_mrbgem.py [--name GEM] <cext_dir> <out_dir>', file=sys.stderr)
        return 1
    return Converter(args[0], args[1], name).run()


if __name__ == '__main__':
    sys.exit(main(sys.argv))
