#!/usr/bin/env python3
# Generates tools/quickjs/qjs_tables.inc from the QuickJS source in 3rd/quickjs (quickjs-opcode.h, quickjs-atom.h and the
# BC_VERSION of quickjs.c): the opcode numbers, sizes, stack effects and operand formats, the predefined atoms, and the
# bytecode version the reader checks. The numbers are the enum values of quickjs.c (OPCodeEnum counts the DEF lines of
# quickjs-opcode.h with SHORT_OPCODES on; the temporary def() opcodes are not in the enum and are not bytecode).
#
#   python3 tools/quickjs/gen_tables.py 3rd/quickjs > tools/quickjs/qjs_tables.inc
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "3rd/quickjs"

ops = []
for line in open(src + "/quickjs-opcode.h"):
    m = re.match(r"^\s*DEF\(\s*(\w+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\w+)\s*\)", line)
    if m:
        ops.append((m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4)), m.group(5)))

atoms = []
for line in open(src + "/quickjs-atom.h"):
    m = re.match(r'^DEF\(\s*(\w+)\s*,\s*("(?:[^"\\]|\\.)*")\s*\)', line)
    if m:
        atoms.append(m.group(2))

bcv = None
for line in open(src + "/quickjs.c"):
    m = re.match(r"^#define BC_VERSION (\d+)\s*$", line)
    if m:
        bcv = int(m.group(1))
if bcv is None:
    sys.exit("gen_tables.py: BC_VERSION not found")

print("// Generated by tools/quickjs/gen_tables.py from 3rd/quickjs (quickjs-opcode.h, quickjs-atom.h, quickjs.c). Do not edit.")
print("constexpr int kQjsBcVersion = %d;" % bcv)
print("struct QjsOp {")
print("  const char *name;")
print("  int size, npop, npush;")
print("  const char *fmt;")
print("};")
print("constexpr int kQjsNumOps = %d;" % len(ops))
print("constexpr QjsOp kQjsOps[kQjsNumOps] = {")
for name, size, npop, npush, fmt in ops:
    print('    {"%s", %d, %d, %d, "%s"},' % (name, size, npop, npush, fmt))
print("};")
# atom 0 is JS_ATOM_NULL, atom i+1 is the i-th DEF; JS_ATOM_END is the number after the last
print("constexpr int kQjsAtomEnd = %d;" % (len(atoms) + 1))
print("// the predefined atoms by number: kQjsAtoms[0] is JS_ATOM_NULL")
print("constexpr const char *kQjsAtoms[kQjsAtomEnd] = {")
print('    "",')
for s in atoms:
    print("    %s," % s)
print("};")
