#!/usr/bin/env python3
"""Regenerates the two tables of the .mpy reader from a MicroPython source tree (v1.29.0 is the pin).

  tools/mpy/gen_tables.py <micropython-tree> [<unix-port-build-dir>]

The static qstrs are the QDEF0 entries of genhdr/qstrdefs.generated.h, in order: the index is the qstr value that
.mpy files use. The opcodes are the MP_BC_* values of py/bc0.h, evaluated in order.
"""
import re
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
tree = Path(sys.argv[1])
genhdr = Path(sys.argv[2]) if len(sys.argv) > 2 else tree / "ports/unix/build-standard/genhdr"

# qstrs
names = []
for line in (genhdr / "qstrdefs.generated.h").read_text().splitlines():
    m = re.match(r'QDEF0\((\w+), (\d+), (\d+), "(.*)"\)\s*$', line)
    if m:
        names.append(m.group(4))
with open(here / "mpy_qstrs_static.inc", "w") as f:
    f.write("// Generated by tools/mpy/gen_tables.py from MicroPython genhdr/qstrdefs.generated.h (the static qstrs).\n")
    f.write("static const char *const kStaticQstrs[] = {\n")
    for s in names:
        f.write('    "%s",\n' % s.replace("\\", "\\\\").replace('"', '\\"'))
    f.write("};\n")

# opcodes
src = (tree / "py/bc0.h").read_text()
vals = {}
for m in re.finditer(r'^#define (MP_BC_[A-Z0-9_]+)\s+\((.*?)\)\s*(//.*)?$', src, re.M):
    expr = m.group(2)
    for k, v in sorted(vals.items(), key=lambda kv: -len(kv[0])):
        expr = re.sub(r"\b%s\b" % k, str(v), expr)
    try:
        vals[m.group(1)] = eval(expr)
    except Exception:
        pass
with open(here / "mpy_opcodes.inc", "w") as f:
    f.write("// Generated by tools/mpy/gen_tables.py from MicroPython py/bc0.h (the MP_BC_* opcode values).\n")
    f.write("struct OpName { unsigned value; const char *name; };\n")
    f.write("static const OpName kOpNames[] = {\n")
    for n, v in vals.items():
        if n.startswith(("MP_BC_BASE", "MP_BC_MASK", "MP_BC_FORMAT")) or "MULTI" in n or n.endswith("_NUM") or "EXCESS" in n:
            continue
        f.write('    {0x%02x, "%s"},\n' % (v, n[len("MP_BC_"):]))
    f.write("};\n")
print(len(names), "static qstrs;", len(vals), "opcode values")
