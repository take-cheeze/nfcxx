#!/usr/bin/env bash
# Regenerates tools/cuda-rewrite/tables.inc from the embedded text and tables of scripts/cuda-rewrite.rb: the
# definitions between the device-side marker and the cooperative-groups heredoc are run with mruby, and each value is
# dumped as a C++ literal. The text is byte-exact by construction (no transcription).
set -eu
root=$(cd "$(dirname "$0")/../.." && pwd)
mrb=${MRB:-$root/build/mruby-tool/bin/mruby}
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
awk '/^# ---- device side \(--device\)/{on=1} on{print} /^COOP$/{if(on){exit}}' "$root/scripts/cuda-rewrite.rb" > "$tmp/defs.rb"
cat >> "$tmp/defs.rb" <<'RUBY'

def cesc(s)
  out = "\""
  s.each_byte do |b|
    if b == 92
      out << "\\\\"
    elsif b == 34
      out << "\\\""
    elsif b == 10
      out << "\\n"
    elsif b >= 32 && b < 127
      out << b.chr
    else
      out << ("\\%03o" % b)
    end
  end
  out << "\""
end
puts "// Generated by tools/cuda-rewrite/gen-tables.sh from scripts/cuda-rewrite.rb. Do not edit."
puts "const char *const DEVICE_PRELUDE = #{cesc(DEVICE_PRELUDE)};"
puts "const char *const COOP_DEF = #{cesc(COOP_DEF)};"
puts "const char *const DEVICE_AXES_TBL[] = {#{DEVICE_AXES.map { |x| cesc(x) }.join(', ')}};"
puts "const char *const DEVICE_QUALIFIERS_TBL[] = {#{DEVICE_QUALIFIERS.map { |x| cesc(x) }.join(', ')}};"
puts "const TblEntry DEVICE_BUILTINS_TBL[] = {"
DEVICE_BUILTINS.each { |k, v| puts "  {#{cesc(k)}, #{cesc(v)}}," }
puts "};"
puts "const TblEntry VECTOR_DEFS_TBL[] = {"
VECTOR_DEFS.each { |k, v| puts "  {#{cesc(k)}, #{cesc(v)}}," }
puts "};"
puts "const TblEntry BUILTIN_DEFS_TBL[] = {"
BUILTIN_DEFS.each { |k, v| puts "  {#{cesc(k)}, #{cesc(v)}}," }
puts "};"
RUBY
"$mrb" "$tmp/defs.rb" > "$root/tools/cuda-rewrite/tables.inc"
echo "wrote tools/cuda-rewrite/tables.inc"
