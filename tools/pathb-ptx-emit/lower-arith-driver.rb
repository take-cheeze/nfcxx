# Driver for the arithmetic, call and asm differentials (diff-arith.sh). Appended after the reference functions copied from
# scripts/pathb-ptx-emit.rb (class Fn among them); it runs each case (arith DEST PRESETS INSTR) through Fn#rval and
# prints the emitted lines joined by " ~ ", the same text the C++ --eval-arith prints. Keep the head list in step with
# FnCtx::arith in lower_arith.cpp.

class BadCase < StandardError; end

# The harness's view of a Fn: the register map it is given, and the lines it emitted.
class Fn
  def set_regs(r)
    @regs = r
  end

  def lines_out
    @lines
  end

  # The module's data symbols and the frame slots of a memory case (the Ruby's @shared .. @strings and @slots).
  def set_mem(shared, globals, consts, externs, strings, slots)
    @shared = shared
    @globals = globals
    @consts = consts
    @externs = externs
    @strings = strings
    @slots = slots
    @sp = "%sp"
  end
end

# The memory heads of rval and the statement heads of stmt this port covers (diff-arith.sh's memory cases).
MEM_HEADS = %w[load load.v bitcast offset index]
STMT_HEADS = %w[store store.v]

# The symbols of a memory case: (shared NAME), (global NAME), (const NAME), (extern NAME), (string NAME), (slot NAME OFF).
def mem_symbols(list)
  h = { shared: {}, globals: {}, consts: {}, externs: {}, strings: {}, slots: {} }
  list.each do |e|
    raise BadCase, "symbol" unless e.is_a?(Array) && e.length >= 2 && e[0].is_a?(String) && e[1].is_a?(String)
    case e[0]
    when "shared" then h[:shared][e[1]] = true
    when "global" then h[:globals][e[1]] = true
    when "const" then h[:consts][e[1]] = true
    when "extern" then h[:externs][e[1]] = true
    when "string" then h[:strings][e[1]] = true
    when "slot"
      raise BadCase, "symbol" unless e.length == 3 && e[2].is_a?(String)
      h[:slots][e[1]] = as_int(e[2])
    else raise BadCase, "symbol"
    end
  end
  h
end

def mem_regs(presets)
  raise BadCase, "presets" unless presets.is_a?(Array)
  regs = {}
  presets.each do |p|
    raise BadCase, "preset" unless p.is_a?(Array) && p.length == 3 && p[0].is_a?(String) && p[1].is_a?(String)
    regs[p[0]] = [p[1], parse_type(p[2])]
  end
  regs
end

def ev_mem(c)
  raise BadCase, "case" unless c.is_a?(Array) && c.length == 5 && c[0] == "mem"
  fn = Fn.new(["fn", "t"], 0)
  fn.set_regs(mem_regs(c[2]))
  h = mem_symbols(c[3])
  fn.set_mem(h[:shared], h[:globals], h[:consts], h[:externs], h[:strings], h[:slots])
  dty = parse_type(c[1])
  x = c[4]
  raise BadCase, "instr" unless x.is_a?(Array) && !x.empty? && x[0].is_a?(String)
  return "NOTMEM" unless MEM_HEADS.include?(x[0])
  fn.rval(x, "%d", dty)
  fn.lines_out.map { |l| l.to_s }.join(" ~ ")
end

def ev_stmt(c)
  raise BadCase, "case" unless c.is_a?(Array) && c.length == 4 && c[0] == "stmt"
  fn = Fn.new(["fn", "t"], 0)
  fn.set_regs(mem_regs(c[1]))
  h = mem_symbols(c[2])
  fn.set_mem(h[:shared], h[:globals], h[:consts], h[:externs], h[:strings], h[:slots])
  x = c[3]
  raise BadCase, "stmt" unless x.is_a?(Array) && !x.empty? && x[0].is_a?(String)
  return "NOTSTMT" unless STMT_HEADS.include?(x[0])
  fn.stmt(x)
  fn.lines_out.map { |l| l.to_s }.join(" ~ ")
end

# The instruction heads of the rval branches this port covers (wadd..cf2i and the comparisons). The call and asm
# cases (ev_call, ev_asm) are the device intrinsics, warp, atomic and ptx-asm forms of lower_call.cpp.
ARITH_HEADS = %w[
  wadd wsub wmul wneg cdiv crem cshl cshr and or xor not fadd fsub fmul fdiv fneg iconv fconv i2f u2f cf2i
  lt le gt ge eq ne lt.s le.s gt.s ge.s eq.s ne.s lt.u le.u gt.u ge.u eq.u ne.u lt.f le.f gt.f ge.f eq.f ne.f
]

# The Fn of a case (its preset registers), with the presets at index presets_at of a case of len items.
def ev_setup(c, presets_at, len)
  raise BadCase, "case" unless c.is_a?(Array) && c.length == len
  presets = c[presets_at]
  raise BadCase, "presets" unless presets.is_a?(Array)
  fn = Fn.new(["fn", "t"], 0)
  regs = {}
  presets.each do |p|
    raise BadCase, "preset" unless p.is_a?(Array) && p.length == 3 && p[0].is_a?(String) && p[1].is_a?(String)
    regs[p[0]] = [p[1], parse_type(p[2])]
  end
  fn.set_regs(regs)
  fn
end

def ev_arith(c)
  fn = ev_setup(c, 2, 4)
  raise BadCase, "case" unless c[0] == "arith"
  dty = parse_type(c[1])
  x = c[3]
  raise BadCase, "instr" unless x.is_a?(Array) && !x.empty? && x[0].is_a?(String)
  return "NOTARITH" unless ARITH_HEADS.include?(x[0])
  fn.rval(x, "%d", dty)
  fn.lines_out.map { |l| l.to_s }.join(" ~ ")
end

# (call DTY PRESETS INSTR): the rval "call" branch, for the handled callees (the cases generated by gen-call-cases.sh).
def ev_call(c)
  fn = ev_setup(c, 2, 4)
  raise BadCase, "case" unless c[0] == "call"
  dty = parse_type(c[1])
  x = c[3]
  raise BadCase, "instr" unless x.is_a?(Array) && !x.empty? && x[0] == "call"
  fn.rval(x, "%d", dty)
  fn.lines_out.map { |l| l.to_s }.join(" ~ ")
end

# (asm PRESETS INSTR): the ptx-asm statement (stmt).
def ev_asm(c)
  fn = ev_setup(c, 1, 3)
  raise BadCase, "case" unless c[0] == "asm"
  x = c[2]
  raise BadCase, "instr" unless x.is_a?(Array) && !x.empty? && x[0] == "ptx-asm"
  fn.stmt(x)
  fn.lines_out.map { |l| l.to_s }.join(" ~ ")
end

def ev_case(c)
  raise BadCase, "case" unless c.is_a?(Array) && !c.empty? && c[0].is_a?(String)
  case c[0]
  when "arith" then ev_arith(c)
  when "call" then ev_call(c)
  when "asm" then ev_asm(c)
  when "mem" then ev_mem(c)
  when "stmt" then ev_stmt(c)
  else raise BadCase, "case"
  end
end

def run_arith(src)
  forms = nil
  begin
    forms = parse_forms_chunked(src)
  rescue BadIR
    $stdout.write("BADIR-PARSE\n")
    return 1
  end
  forms.each do |f|
    line = nil
    begin
      line = ev_case(f)
    rescue Refused
      line = "REFUSED"
    rescue BadIR
      line = "BADIR"
    rescue BadCase
      line = "BADCASE"
    end
    $stdout.write(line + "\n")
  end
  0
end

case_src = File.open(ARGV[0], "rb") { |f| f.read }
exit(run_arith(case_src))
