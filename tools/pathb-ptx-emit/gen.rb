
# ---- generator (run after the extracted table definitions, by gen-tables.sh) ----
# stdout: tables.inc (C++). stderr: the canonical dump of the Ruby values, one line per entry, which check-tables.sh
# compares with the C++ dump (tools/pathb-ptx-emit/dump.cpp). Shapes are fixed per table; a value that does not have its
# table's shape stops the generator.

SHAPES = {
  "VOID" => :strlist,
  "SCALARS" => :scalars,
  "DYNSHARED_SYM" => :string,
  "STRING_PREFIX" => :string,
  "DEVICE_INTRINSICS" => :kv_str,
  "WARP_SHUFFLES" => :kv_str,
  "WARP_VOTES" => :kv_str,
  "FLOAT_TO_INT_BUILTINS" => :kv_str,
  "SCALAR_U32" => :kv_op,
  "HALF_BUILTINS" => :kv_op,
  "FLOAT_BUILTINS" => :kv_float,
  "ATOMICS" => :kv_atomic,
}

def fail_gen(msg)
  $stderr.puts "gen-tables: #{msg}"
  exit(1)
end

# A C string literal for text made of printable ASCII without quotes and backslashes (the tables are that).
def cstr(s)
  fail_gen("not a plain string: #{s}") unless s.is_a?(String)
  s.each_byte do |b|
    fail_gen("not plain ASCII: #{s}") if b < 32 || b > 126 || b == 34 || b == 92
  end
  "\"" + s + "\""
end

def bool_value?(b)
  b == true || b == false
end

def bool_text(b)
  b ? "true" : "false"
end

def check_kv_str(name, h)
  fail_gen("#{name} is not a hash") unless h.is_a?(Hash)
  h.each do |k, v|
    fail_gen("#{name}: key #{k.inspect}") unless k.is_a?(String)
    fail_gen("#{name}: value of #{k} is not a string") unless v.is_a?(String)
  end
end

def check_kv_op(name, h)
  fail_gen("#{name} is not a hash") unless h.is_a?(Hash)
  h.each do |k, v|
    fail_gen("#{name}: key") unless k.is_a?(String)
    fail_gen("#{name}: value of #{k} is not [op, n]") unless v.is_a?(Array) && v.length == 2 && v[0].is_a?(String) && v[1].is_a?(Integer)
  end
end

def check_kv_float(name, h)
  fail_gen("#{name} is not a hash") unless h.is_a?(Hash)
  h.each do |k, v|
    fail_gen("#{name}: key") unless k.is_a?(String)
    fail_gen("#{name}: value of #{k} is not [op, n]") unless v.is_a?(Array) && v.length == 2 && (v[0].is_a?(String) || v[0].is_a?(Symbol)) && v[1].is_a?(Integer)
  end
end

def check_kv_atomic(name, h)
  fail_gen("#{name} is not a hash") unless h.is_a?(Hash)
  h.each do |k, v|
    fail_gen("#{name}: key") unless k.is_a?(String)
    fail_gen("#{name}: value of #{k} is not [op, type]") unless v.is_a?(Array) && v.length == 2 && v[0].is_a?(String) && v[1].is_a?(String)
  end
end

def check_scalars(name, h)
  fail_gen("#{name} is not a hash") unless h.is_a?(Hash)
  h.each do |k, v|
    fail_gen("#{name}: key") unless k.is_a?(String)
    ok = v.is_a?(Array) && v[0].is_a?(String) && v[1].is_a?(Integer) &&
         ((v.length == 4 && bool_value?(v[2]) && bool_value?(v[3])) ||
          (v.length == 2))
    fail_gen("#{name}: value of #{k} has no scalar shape") unless ok
  end
end

def check_strlist(name, a)
  fail_gen("#{name} is not an array") unless a.is_a?(Array)
  a.each { |x| fail_gen("#{name}: item is not a string") unless x.is_a?(String) }
end

def check_string(name, s)
  fail_gen("#{name} is not a string") unless s.is_a?(String)
end

value_of = {}
SHAPES.each_key { |n| value_of[n] = Object.const_get(n.to_sym) rescue nil }
SHAPES.each do |n, shape|
  v = value_of[n]
  fail_gen("#{n} is not defined") if v.nil?
  case shape
  when :kv_str then check_kv_str(n, v)
  when :kv_op then check_kv_op(n, v)
  when :kv_float then check_kv_float(n, v)
  when :kv_atomic then check_kv_atomic(n, v)
  when :scalars then check_scalars(n, v)
  when :strlist then check_strlist(n, v)
  when :string then check_string(n, v)
  end
end

# ---- C++ (stdout) ----
puts "// Generated by tools/pathb-ptx-emit/gen-tables.sh from scripts/pathb-ptx-emit.rb. Do not edit."
puts "// Each table is the Ruby table's entries in source order. A symbol value (FLOAT_BUILTINS' :exp and :log) is is_symbol."
puts "#pragma once"
puts "#include <cstddef>"
puts ""
puts "struct KvStr { const char *key; const char *value; };"
puts "struct KvOp { const char *key; const char *op; int n; };"
puts "struct KvFloatOp { const char *key; const char *op; bool is_symbol; int n; };"
puts "struct KvAtomic { const char *key; const char *op; const char *type; };"
puts "struct ScalarType { const char *name; const char *kind; int size; int arity; bool is_signed; bool is_bool; };"
puts ""

SHAPES.each do |n, shape|
  v = value_of[n]
  case shape
  when :strlist
    puts "static const char *const #{n}[] = {#{v.map { |x| cstr(x) }.join(', ')}};"
    puts "static const size_t #{n}_N = #{v.length};"
  when :string
    puts "static const char *const #{n} = #{cstr(v)};"
  when :kv_str
    puts "static const KvStr #{n}[] = {"
    v.each { |k, x| puts "  {#{cstr(k)}, #{cstr(x)}}," }
    puts "};"
    puts "static const size_t #{n}_N = #{v.length};"
  when :kv_op
    puts "static const KvOp #{n}[] = {"
    v.each { |k, x| puts "  {#{cstr(k)}, #{cstr(x[0])}, #{x[1]}}," }
    puts "};"
    puts "static const size_t #{n}_N = #{v.length};"
  when :kv_float
    puts "static const KvFloatOp #{n}[] = {"
    v.each do |k, x|
      op = x[0].is_a?(Symbol) ? x[0].to_s : x[0]
      puts "  {#{cstr(k)}, #{cstr(op)}, #{bool_text(x[0].is_a?(Symbol))}, #{x[1]}},"
    end
    puts "};"
    puts "static const size_t #{n}_N = #{v.length};"
  when :kv_atomic
    puts "static const KvAtomic #{n}[] = {"
    v.each { |k, x| puts "  {#{cstr(k)}, #{cstr(x[0])}, #{cstr(x[1])}}," }
    puts "};"
    puts "static const size_t #{n}_N = #{v.length};"
  when :scalars
    puts "static const ScalarType #{n}[] = {"
    v.each do |k, x|
      signed = x.length == 4 ? x[2] : false
      isb = x.length == 4 ? x[3] : false
      puts "  {#{cstr(k)}, #{cstr(x[0])}, #{x[1]}, #{x.length}, #{bool_text(signed)}, #{bool_text(isb)}},"
    end
    puts "};"
    puts "static const size_t #{n}_N = #{v.length};"
  end
end

# ---- canonical dump (stderr): the same lines dump.cpp prints ----
SHAPES.each do |n, shape|
  v = value_of[n]
  case shape
  when :strlist then $stderr.puts "#{n}|" + v.join("|")
  when :string then $stderr.puts "#{n}|#{v}"
  when :kv_str then v.each { |k, x| $stderr.puts "#{n}|#{k}|#{x}" }
  when :kv_op then v.each { |k, x| $stderr.puts "#{n}|#{k}|#{x[0]}|#{x[1]}" }
  when :kv_float then v.each { |k, x| $stderr.puts "#{n}|#{k}|#{x[0].is_a?(Symbol) ? ':' + x[0].to_s : x[0]}|#{x[1]}" }
  when :kv_atomic then v.each { |k, x| $stderr.puts "#{n}|#{k}|#{x[0]}|#{x[1]}" }
  when :scalars
    v.each do |k, x|
      tail = x.length == 4 ? "|#{bool_text(x[2])}|#{bool_text(x[3])}" : ""
      $stderr.puts "#{n}|#{k}|#{x[0]}|#{x[1]}#{tail}"
    end
  end
end
