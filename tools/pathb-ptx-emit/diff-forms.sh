#!/usr/bin/env bash
# Differential check of the C++ reader (build/pathb-ptx-emit --dump-forms) against the Ruby reader in
# scripts/pathb-ptx-emit.rb. The Ruby side is generated from that file's own reader functions (Refused .. form_text and
# strip_comments .. parse_forms_chunked, copied verbatim), so the reference cannot drift from the script.
# Compares stdout and exit status of both on each IR file. Usage: diff-forms.sh [FILE.ir]...
# Default corpus: tools/pathb-ptx-emit/testdata/*.ir and build/sweep3/*.ir under 8 MB.
set -u
root=$(cd "$(dirname "$0")/../.." && pwd)
mrb=${MRB:-$root/build/mruby-tool/bin/mruby}
cxx=${PTX_READER:-$root/build/pathb-ptx-emit}
ref=$root/scripts/pathb-ptx-emit.rb
work=$(mktemp -d)
[ -x "$cxx" ] || { echo "diff-forms: $cxx not built (make -C tools/pathb-ptx-emit)"; exit 1; }

# The Ruby reader functions, verbatim from the reference script, then the dump driver.
a=$(grep -n '^class Refused' "$ref" | cut -d: -f1)
b=$(grep -n '^# The signed 64-bit value' "$ref" | cut -d: -f1)
c=$(grep -n '^def strip_comments' "$ref" | cut -d: -f1)
d=$(grep -n '^def emit_module' "$ref" | cut -d: -f1)
{
  echo "# generated by tools/pathb-ptx-emit/diff-forms.sh from scripts/pathb-ptx-emit.rb"
  sed -n "${a},$((b-1))p" "$ref"
  sed -n "${c},$((d-1))p" "$ref"
  cat <<'RUBY'
src = File.open(ARGV[0], "rb") { |f| f.read }
begin
  parse_forms_chunked(src).each { |f| $stdout.write(form_text(f) + "\n") }
rescue BadIR => e
  $stdout.write("error: #{e.message}\n")
  exit(1)
end
RUBY
} > "$work/dump-ruby.rb"

if [ $# -gt 0 ]; then
  files=("$@")
else
  files=("$root"/tools/pathb-ptx-emit/testdata/*.ir)
  for f in "$root"/build/sweep3/*.ir; do
    [ -f "$f" ] || continue
    [ "$(wc -c < "$f")" -le 8000000 ] && files+=("$f")
  done
fi

same=0; diff=0
for f in "${files[@]}"; do
  "$mrb" "$work/dump-ruby.rb" "$f" > "$work/r.out" 2> "$work/r.err"; rr=$?
  "$cxx" --dump-forms "$f" > "$work/c.out" 2> "$work/c.err"; cr=$?
  if [ $rr -eq $cr ] && cmp -s "$work/r.out" "$work/c.out"; then
    same=$((same + 1))
  else
    diff=$((diff + 1))
    echo "DIFF $f: ruby exit=$rr cxx exit=$cr"
    cmp "$work/r.out" "$work/c.out" 2>&1 | head -1
  fi
done
echo "diff-forms: $same identical, $diff different, of $((same + diff)) files (work dir $work)"
[ $diff -eq 0 ]
