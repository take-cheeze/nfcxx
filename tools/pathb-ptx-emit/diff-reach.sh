#!/usr/bin/env bash
# Differential check of the C++ selective module parse (build/pathb-ptx-emit --dump-forms --kernel=...) against the
# Ruby parse_module_forms in scripts/pathb-ptx-emit.rb (the reachability pass). The Ruby side is generated from that
# file's own reader functions (from `class Refused` to `def emit_module`, copied verbatim), so the reference cannot drift
# from the script. Compares stdout (the forms, then the `# fn-indices:` line) and exit status of both on each IR file.
# Usage: diff-reach.sh [FILE.ir KERNELS_FILE]...   (KERNELS_FILE: one kernel name per line; default: build/sweep3)
# The reference is scripts/pathb-ptx-emit.rb of REF_REV (default origin/emitter-reachable-only-2), which has the pass.
set -u
root=$(cd "$(dirname "$0")/../.." && pwd)
mrb=${MRB:-$root/build/mruby-tool/bin/mruby}
sweep=${SWEEP:-/home/takecheeze/dev/nfcxx/build/sweep3}
cxx=${PTX_READER:-$root/build/pathb-ptx-emit}
rev=${REF_REV:-origin/emitter-reachable-only-2}
work=$(mktemp -d)
[ -x "$cxx" ] || { echo "diff-reach: $cxx not built (make -C tools/pathb-ptx-emit)"; exit 1; }
git -C "$root" show "$rev:scripts/pathb-ptx-emit.rb" > "$work/ref.rb" || { echo "diff-reach: no $rev"; exit 1; }

# The Ruby reader functions, verbatim from the reference script, then the dump driver.
a=$(grep -n '^class Refused' "$work/ref.rb" | cut -d: -f1)
d=$(grep -n '^def emit_module' "$work/ref.rb" | cut -d: -f1)
{
  echo "# generated by tools/pathb-ptx-emit/diff-reach.sh from scripts/pathb-ptx-emit.rb ($rev)"
  sed -n "${a},$((d-1))p" "$work/ref.rb"
  cat <<'RUBY'
src = File.open(ARGV[0], "rb") { |f| f.read }
kernels = ARGV[1..-1]
begin
  r = kernels.empty? ? nil : parse_module_forms(src, kernels)
  if r
    forms, idx = r
    forms.each { |f| $stdout.write(form_text(f) + "\n") }
    $stdout.write("# fn-indices:" + idx.map { |i| " #{i}" }.join + "\n")
  else
    parse_forms_chunked(src).each { |f| $stdout.write(form_text(f) + "\n") }
    $stdout.write("# fn-indices: all\n") unless kernels.empty?
  end
rescue BadIR => e
  $stdout.write("error: #{e.message}\n")
  exit(1)
end
RUBY
} > "$work/dump-ruby.rb"

# Pairs of IR file and kernel file; the kernel file may be empty (no kernels: the whole text is parsed).
pairs=()
if [ $# -gt 0 ]; then
  while [ $# -gt 0 ]; do pairs+=("$1|$2"); shift 2; done
else
  for f in "$sweep"/*.ir; do
    [ -f "$f" ] || continue
    k="${f%.ir}.kernels"
    [ -f "$k" ] || k=/dev/null
    pairs+=("$f|$k")
  done
fi

same=0; diff=0; slow=0
for p in "${pairs[@]}"; do
  f=${p%%|*}; k=${p#*|}
  kargs=()
  if [ "$k" != /dev/null ]; then while IFS= read -r line; do [ -n "$line" ] && kargs+=("--kernel=$line"); done < "$k"; fi
  rargs=()
  if [ "$k" != /dev/null ]; then while IFS= read -r line; do [ -n "$line" ] && rargs+=("$line"); done < "$k"; fi
  # A file the Ruby does not finish in RUBY_TIMEOUT seconds (124) is not compared; a file both time out on is listed.
  timeout "${RUBY_TIMEOUT:-900}" "$mrb" "$work/dump-ruby.rb" "$f" "${rargs[@]}" > "$work/r.out" 2> "$work/r.err"; rr=$?
  if [ $rr -eq 124 ]; then
    slow=$((slow + 1)); echo "SLOW (ruby > ${RUBY_TIMEOUT:-900}s) $f"; continue
  fi
  timeout "${RUBY_TIMEOUT:-900}" "$cxx" --dump-forms "${kargs[@]}" "$f" > "$work/c.out" 2> "$work/c.err"; cr=$?
  if [ $rr -eq $cr ] && cmp -s "$work/r.out" "$work/c.out"; then
    same=$((same + 1))
  else
    diff=$((diff + 1))
    echo "DIFF $f: ruby exit=$rr cxx exit=$cr"
    cmp "$work/r.out" "$work/c.out" 2>&1 | head -1
  fi
done
echo "diff-reach: $same identical, $diff different, $slow skipped (Ruby over the time limit), of ${#pairs[@]} files (work dir $work)"
[ $diff -eq 0 ]
