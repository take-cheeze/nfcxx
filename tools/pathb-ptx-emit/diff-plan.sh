#!/usr/bin/env bash
# Differential check of the C++ module plan (build/pathb-ptx-emit --plan) against the module level of
# scripts/pathb-ptx-emit.rb (emit_module). The Ruby side is generated from that file's own reader and module functions
# (copied verbatim) with one change: Fn#compile is a stub that writes "// body NAME", since the function bodies are not
# ported. Both sides therefore stop at the same point, and the comparison covers the module text (header, declarations,
# call order), the exit status, and the error text. Compares stdout and exit status exactly, and stderr with the
# program name normalized (the usage line). Usage: diff-plan.sh [FILE.ir]...
# A FILE.args next to an IR gives its options (--sm=, --kernel=). Default corpus: testdata/module/*.ir and
# testdata/*.ir (the reader's cases; most have no function, so they test the errors in the Ruby's order).
# REF_TIMEOUT (seconds, default 900) bounds each Ruby run: a run that times out is reported as skipped, not as a diff.
# BUDGET (seconds, default unlimited) bounds the whole run: the files after the budget is spent are reported as skipped.
set -u
root=$(cd "$(dirname "$0")/../.." && pwd)
cxx=${PTX_PLAN:-$root/build/pathb-ptx-emit}
ref=$root/scripts/pathb-ptx-emit.rb
here=$(cd "$(dirname "$0")" && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
[ -x "$cxx" ] || { echo "diff-plan: $cxx not built (make -C tools/pathb-ptx-emit)"; exit 1; }

# The Ruby harness: the reference's reader and module functions verbatim, a stub Fn, then the driver.
a=$(grep -n '^class Refused' "$ref" | cut -d: -f1)
b=$(grep -n '^class Fn' "$ref" | cut -d: -f1)
c=$(grep -n '^def strip_comments' "$ref" | cut -d: -f1)
d=$(grep -n '^def read_input' "$ref" | cut -d: -f1)
{
  echo "# generated by tools/pathb-ptx-emit/diff-plan.sh from scripts/pathb-ptx-emit.rb"
  sed -n "${a},$((b-1))p" "$ref"
  sed -n "${c},$((d-1))p" "$ref"
  cat <<'RUBY'
# The function bodies are not ported: Fn#compile writes a marker line, and the stub reports no dynamic shared memory
# and no printf (what the lowering would find).
class Fn
  attr_reader :name, :form, :uses_dynshared, :uses_printf, :text
  attr_accessor :kernel, :module_fns, :shared, :globals, :consts, :externs, :strings

  def initialize(form, index)
    @form = form
    @index = index
    @kernel = true
    @name = form[1].to_s
    @uses_dynshared = false
    @uses_printf = false
  end

  def compile
    @text = "// body #{@name}"
  end
end

def plan_main(argv)
  args = argv.dup
  sm = "sm_75"
  kernels = []
  usage = "usage: pathb-ptx-emit.rb [--sm=75] [--kernel=NAME]... [FILE.ir | -] > out.ptx\n"
  while args.length > 0 && args[0].start_with?("--")
    opt = args.shift
    if opt.start_with?("--sm=")
      sm = "sm_" + opt[5..-1]
    elsif opt.start_with?("--kernel=")
      kernels << opt[9..-1]
    else
      $stderr.write(usage)
      return 1
    end
  end
  if args.length > 1
    $stderr.write(usage)
    return 1
  end
  src = (args.empty? || args[0] == "-") ? $stdin.read : File.open(args[0], "rb") { |f| f.read }
  begin
    ptx = emit_module(src, sm, kernels)
  rescue Refused => e
    $stderr.write("refused: #{e.message}\n")
    return 3
  rescue BadIR => e
    $stderr.write("error: #{e.message}\n")
    return 1
  end
  $stdout.write(ptx)
  0
end

rc = plan_main(ARGV)
exit(rc) if rc != 0
RUBY
} > "$work/plan-ref.rb"

ir_files=("$@")
if [ ${#ir_files[@]} -eq 0 ]; then
  ir_files=("$here"/testdata/module/*.ir "$here"/testdata/*.ir)
fi

pass=0; fail=0; skip=0
start=$(date +%s)
for ir in "${ir_files[@]}"; do
  name=${ir#"$here"/}
  if [ -n "${BUDGET:-}" ] && [ $(( $(date +%s) - start )) -ge "$BUDGET" ]; then
    skip=$((skip + 1)); echo "SKIP $name (budget of ${BUDGET}s spent)"; continue
  fi
  args_file="${ir%.ir}.args"
  opts=""
  [ -f "$args_file" ] && opts=$(cat "$args_file")
  t0=$(date +%s)
  # shellcheck disable=SC2086
  timeout "${REF_TIMEOUT:-900}" "$root/scripts/mrb" "$work/plan-ref.rb" $opts "$ir" > "$work/ref.out" 2> "$work/ref.err"; rc_ref=$?
  t1=$(date +%s)
  if [ "$rc_ref" = 124 ]; then
    skip=$((skip + 1)); echo "SKIP $name (ruby did not finish in ${REF_TIMEOUT:-900}s)"; continue
  fi
  # shellcheck disable=SC2086
  "$cxx" --plan $opts "$ir" > "$work/cxx.out" 2> "$work/cxx.err"; rc_cxx=$?
  t2=$(date +%s)
  sed -i 's/pathb-ptx-emit\.rb/pathb-ptx-emit/g' "$work/ref.err"
  sed -i 's/pathb-ptx-emit\.rb/pathb-ptx-emit/g' "$work/cxx.err"
  if [ "$rc_ref" = "$rc_cxx" ] && cmp -s "$work/ref.out" "$work/cxx.out" && cmp -s "$work/ref.err" "$work/cxx.err"; then
    pass=$((pass + 1))
    echo "ok   $name (exit $rc_ref; ruby $((t1 - t0))s, c++ $((t2 - t1))s)"
  else
    fail=$((fail + 1))
    echo "DIFF $name (ruby exit $rc_ref, c++ exit $rc_cxx; ruby $((t1 - t0))s, c++ $((t2 - t1))s)"
    diff -u "$work/ref.out" "$work/cxx.out" | head -20
    diff -u "$work/ref.err" "$work/cxx.err" | head -10
  fi
done
echo "diff-plan: $pass same, $fail different, $skip skipped"
[ "$fail" = 0 ]
