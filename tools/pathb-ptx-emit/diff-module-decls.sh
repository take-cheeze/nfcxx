#!/usr/bin/env bash
# Differential check of the module-level declarations (module_decls.cpp, run as build/pathb-ptx-emit --decls) against
# the Ruby reference in scripts/pathb-ptx-emit.rb. The reference is built from that file's own lines: the reader and
# helpers (class Refused .. before the special registers), the two name constants, and the classification and declaration
# lines of emit_module, copied verbatim (the function-body parts are left out: their flags are false on both sides).
# Usage: diff-module-decls.sh [FILE.ir]...   (default: build/sweep3/*.ir under 8 MB, plus testdata/decls/*.ir)
set -u
root=$(cd "$(dirname "$0")/../.." && pwd)
here=$root/tools/pathb-ptx-emit
main=$(cd "$(dirname "$(git -C "$root" rev-parse --git-common-dir)")" && pwd)
mrb=${MRB:-$root/build/mruby-tool/bin/mruby}
[ -x "$mrb" ] || mrb=$main/build/mruby-tool/bin/mruby
cxx=${PTX_EMIT:-$root/build/pathb-ptx-emit}
ref=$root/scripts/pathb-ptx-emit.rb
[ -x "$cxx" ] || { echo "diff-module-decls: $cxx not built (make -C tools/pathb-ptx-emit)"; exit 1; }
[ -x "$mrb" ] || { echo "diff-module-decls: no mruby (set MRB)"; exit 1; }
work=$(mktemp -d)

a=$(grep -n '^class Refused' "$ref" | cut -d: -f1)
b=$(grep -n '^# The special registers of the GPU' "$ref" | cut -d: -f1)
c=$(grep -n '^def strip_comments' "$ref" | cut -d: -f1)
d=$(grep -n '^def emit_module' "$ref" | cut -d: -f1)
s1=$(awk -v d="$d" 'NR>d && /^  shared = \{\}/{print NR; exit}' "$ref")
s2=$(awk -v d="$d" 'NR>d && /no function in the IR/{print NR; exit}' "$ref")
s3=$(awk -v d="$d" 'NR>d && /^  byte_inits.each do/{print NR; exit}' "$ref")
s4=$(awk -v d="$d" 'NR>d && /^  fns.each \{ \|fn\| fn.module_fns/{print NR; exit}' "$ref")
s5=$(awk -v d="$d" 'NR>d && /^  out << "\.extern \.shared/{print NR; exit}' "$ref")
s6=$(awk -v d="$d" 'NR>d && /^  out << "\\n" unless shared.empty/{print NR; exit}' "$ref")
dyn=$(grep -n '^DYNSHARED_SYM = ' "$ref" | cut -d: -f1)
strp=$(grep -n '^STRING_PREFIX = ' "$ref" | cut -d: -f1)
{
  echo "# generated by tools/pathb-ptx-emit/diff-module-decls.sh from scripts/pathb-ptx-emit.rb"
  sed -n "${a},$((b-1))p" "$ref"
  sed -n "${dyn}p;${strp}p" "$ref"
  sed -n "${c},$((d-1))p" "$ref"
  r=$(grep -n '^def read_input' "$ref" | cut -d: -f1); sed -n "${r},$(awk -v r="$r" 'NR>r && /^end/{print NR; exit}' "$ref")p" "$ref"
  echo "def module_decls(src, dynshared_flag, printf_flag)"
  echo "  forms = parse_forms_chunked(src)"
  echo "  fns = []"
  sed -n "${s1},$((s2-1))p" "$ref" | sed 's/fns << Fn.new(f, fns.length)/fns << f/'
  sed -n "${s3},$((s4-1))p" "$ref" | sed 's/fn.module_fns = by_name.*$//'
  echo "  out = \"\""
  sed -n "${s5},${s6}p" "$ref" | sed 's/if fns.any?(&:uses_dynshared)/if dynshared_flag/; s/if fns.any?(&:uses_printf)/if printf_flag/'
  echo "  out"
  echo "end"
  cat <<'RUBY'
src = read_input(ARGV[0])
begin
  out = module_decls(src, false, false)
rescue Refused => e
  $stderr.write("refused: #{e.message}\n")
  exit(3)
rescue BadIR => e
  $stderr.write("error: #{e.message}\n")
  exit(1)
end
$stdout.write(out)
RUBY
} > "$work/decls.rb"

if [ $# -gt 0 ]; then
  files=("$@")
else
  files=()
  for f in "$root"/build/sweep3/*.ir "$main"/build/sweep3/*.ir "$here"/testdata/decls/*.ir; do
    [ -f "$f" ] || continue
    [ "$(wc -c < "$f")" -le 8000000 ] && files+=("$f")
  done
fi
n=0; bad=0
for f in "${files[@]}"; do
  n=$((n+1))
  "$mrb" "$work/decls.rb" "$f" > "$work/r.out" 2> "$work/r.err"; rr=$?
  "$cxx" --decls "$f" > "$work/c.out" 2> "$work/c.err"; cr=$?
  if [ "$rr" != "$cr" ] || ! cmp -s "$work/r.out" "$work/c.out" || ! diff -q "$work/r.err" "$work/c.err" >/dev/null 2>&1; then
    bad=$((bad+1))
    echo "DIFF $f: exit ruby=$rr cxx=$cr"
    diff "$work/r.err" "$work/c.err" | head -3
  fi
done
echo "diff-module-decls: $n files, $bad different"
rm -rf "$work"
[ "$bad" -eq 0 ]
