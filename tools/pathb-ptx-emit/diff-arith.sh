#!/usr/bin/env bash
# Differential check of the arithmetic, comparison and conversion lowering (lower_arith.cpp), and of the memory forms and
# stores (lower_mem.cpp), run by build/pathb-ptx-emit --eval-arith, against the Ruby reference in scripts/pathb-ptx-emit.rb. The Ruby side is generated
# from that file's own code (the reader and type helpers, then class Fn, copied verbatim), then lower-arith-driver.rb,
# so the reference cannot drift from the script. Cases come from gen-arith-cases.sh, and the counts are per instruction
# head, with the first difference of each.
# Usage: diff-arith.sh [CASES_FILE]   (default: the generated cases)
set -u
root=$(cd "$(dirname "$0")/../.." && pwd)
here=$root/tools/pathb-ptx-emit
mrb=${MRB:-$root/build/mruby-tool/bin/mruby}
cxx=${PTX_EMIT:-$root/build/pathb-ptx-emit}
ref=$root/scripts/pathb-ptx-emit.rb
[ -x "$cxx" ] || { echo "diff-arith: $cxx not built (make -C tools/pathb-ptx-emit)"; exit 1; }
[ -x "$mrb" ] || { echo "diff-arith: no mruby (set MRB)"; exit 1; }
work=$(mktemp -d)

# The Ruby functions: the reader and type helpers (class Refused .. before the special registers), strip_comments and
# parse_forms_chunked (the phase-1 reader the case files are read with), and class Fn (its end is the first `end` at
# column 0 after its start).
a=$(grep -n '^class Refused' "$ref" | cut -d: -f1)
b=$(grep -n '^# The special registers of the GPU' "$ref" | cut -d: -f1)
c=$(grep -n '^def strip_comments' "$ref" | cut -d: -f1)
d=$(grep -n '^def emit_module' "$ref" | cut -d: -f1)
f=$(grep -n '^class Fn$' "$ref" | cut -d: -f1)
g=$(awk -v s="$f" 'NR > s && /^end$/ { print NR; exit }' "$ref")
{
  echo "# generated by tools/pathb-ptx-emit/diff-arith.sh from scripts/pathb-ptx-emit.rb"
  grep '^STRING_PREFIX = ' "$ref"
  sed -n "${a},$((b-1))p" "$ref"
  sed -n "${c},$((d-1))p" "$ref"
  sed -n "${f},${g}p" "$ref"
  cat "$here/lower-arith-driver.rb"
} > "$work/eval.rb"

if [ $# -gt 0 ]; then
  cases=$1
else
  cases=$work/cases.txt
  { "$here/gen-arith-cases.sh"; "$here/gen-mem-cases.sh"; } > "$cases"
fi
n_cases=$(wc -l < "$cases")
# The instruction head of each case (the form after the preset list), one per line, for the per-head counts.
sed -E -e 's/^\(arith [^ ]+ \(.*\)\) \(([^ )]+).*/\1/' -e 's/^\((mem|stmt) .*/\1/' "$cases" > "$work/heads.txt"

"$cxx" --eval-arith "$cases" > "$work/c.out" 2> "$work/c.err"; cr=$?
"$mrb" "$work/eval.rb" "$cases" > "$work/r.out" 2> "$work/r.err"; rr=$?
if [ $cr -ne 0 ] || [ $rr -ne 0 ]; then
  echo "diff-arith: exit cxx=$cr ruby=$rr"; head -3 "$work/c.err" "$work/r.err"
fi
if [ "$(wc -l < "$work/r.out")" -ne "$(wc -l < "$work/c.out")" ] || [ "$(wc -l < "$work/c.out")" -ne "$n_cases" ]; then
  echo "diff-arith: line counts differ (cases $n_cases, ruby $(wc -l < "$work/r.out"), cxx $(wc -l < "$work/c.out"))"
  head -3 "$work/r.err"
  exit 1
fi

# Per-head counts: cases, and cases whose two outputs differ (with the first difference of each head).
paste -d'\t' "$work/heads.txt" "$work/r.out" "$work/c.out" | awk -F'\t' '
  { n[$1]++ }
  $2 != $3 { bad[$1]++; if (!($1 in first)) first[$1] = NR ": ruby=" $2 " cxx=" $3 }
  END {
    for (k in n) printf "%-8s %5d cases %5d differ%s\n", k, n[k], bad[k] + 0, (k in first ? "   first: " first[k] : "")
  }' | sort
total_bad=$(paste -d'\t' "$work/r.out" "$work/c.out" | awk -F'\t' '$1 != $2' | wc -l)
echo "diff-arith: $n_cases cases, $total_bad different (work dir $work)"
[ "$total_bad" -eq 0 ]
