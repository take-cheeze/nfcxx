#!/usr/bin/env python3
"""Generate a large-text kernel: a 32,768-entry lookup table (128 KB of .rodata, which the linker places in the
kernel's text section) and a loop that reads it. The text therefore grows with the table, not with the code, so
this tests whether a kernel of that size loads and runs.

  python3 gen_lut.py --out big_lut.c     (writes the kernel source and big_lut_expected.npy)

Kernel: out[n] = table[in[n] & 0x7fff] + in[n], on 32-bit words, wrapping.
"""
import argparse
import pathlib

import numpy as np

ENTRIES = 32768
MULT = np.uint32(2654435761)


def table():
    i = np.arange(ENTRIES, dtype=np.uint64)
    return ((i * 2654435761 + 12345) & 0xFFFFFFFF).astype(np.uint32)


def expected(words):
    t = table()
    return (t[words & 0x7FFF] + words.astype(np.uint32)).astype(np.uint32)


SOURCE = """/* Generated by gen_lut.py. NR_ELEMENTS is injected by the runner. */
typedef unsigned int u32;
typedef unsigned char u8;
static u32 pword(const u8 *p) { return (u32)p[0] | ((u32)p[1] << 8) | ((u32)p[2] << 16) | ((u32)p[3] << 24); }
static const u32 table[32768] = {
%s
};
void nr_probe_kernel(const u8 *params) {
    const u32 *in = (const u32 *)pword(params);
    u32 *out = (u32 *)pword(params + 80);
    int n;
    for (n = 0; n < NR_ELEMENTS / 2; ++n) {
        u32 w = in[n];
        out[n] = table[w & 0x7fffu] + w;
    }
}
"""


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="big_lut.c")
    p.add_argument("--expected", default="big_lut_expected.npy")
    args = p.parse_args()
    t = table()
    body = ",\n".join(",".join(str(int(v)) for v in t[i : i + 16]) for i in range(0, ENTRIES, 16))
    pathlib.Path(args.out).write_text(SOURCE % body)
    np.save(args.expected, expected(np.arange(8192, dtype=np.float16).view(np.uint32)))
    print("wrote", args.out, "and", args.expected)
