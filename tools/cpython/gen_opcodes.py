#!/usr/bin/env python3
# Generates tools/cpython/cpy_opcodes.inc from the running CPython 3.13 interpreter's opcode tables (opcode.py):
# the number, name, inline cache size and relative-jump flag of every opcode. The reader and the lowering use them.
#
#   python3 tools/cpython/gen_opcodes.py > tools/cpython/cpy_opcodes.inc
import opcode
import sys

if sys.version_info[:2] != (3, 13):
    sys.exit("gen_opcodes.py: needs CPython 3.13 (got %s)" % sys.version.split()[0])

rows = {}
for name, num in opcode.opmap.items():
    rows[num] = (name, opcode._inline_cache_entries.get(name, 0), num in opcode.hasjrel)

print("// Generated by tools/cpython/gen_opcodes.py from CPython %s (opcode.py). Do not edit." % sys.version.split()[0])
print("// { name, number, inline cache entries, relative jump }, indexed by the opcode number.")
print("struct CpyOpInfo {")
print("  const char *name;")
print("  int caches;")
print("  bool jrel;")
print("};")
print("constexpr int kCpyNumOpcodes = 256;")
print("constexpr CpyOpInfo kCpyOps[kCpyNumOpcodes] = {")
for num in range(256):
    if num in rows:
        name, caches, jrel = rows[num]
        print('    {"%s", %d, %s},' % (name, caches, "true" if jrel else "false"))
    else:
        print('    {nullptr, 0, false},')
print("};")
