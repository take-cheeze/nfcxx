struct nfc_node {
  enum CXCursorKind kind;
  unsigned line, col;
  char *name;
  int parent;        /* index of the parent node, -1 at file scope */
};

struct CXTranslationUnitImpl {
  char *file;        /* the main file, as given to clang_parseTranslationUnit */
  struct nfc_node *nodes;
  int count;
  int **kids;        /* per node, then the file scope at index count: the child indices, in source order */
  int *nkids;
};

/* A cursor's data: data[0] the translation unit, data[1] the node index + 1 (0 for the translation unit). */
#define NFC_TU_KIND CXCursor_TranslationUnit

static CXCursor nfc_cursor(CXTranslationUnit tu, int node)
{
  CXCursor c;
  c.kind = node < 0 ? NFC_TU_KIND : tu->nodes[node].kind;
  c.xdata = 0;
  c.data[0] = tu;
  c.data[1] = (const void *)(intptr_t)(node + 1);
  c.data[2] = NULL;
  return c;
}

static int nfc_node_of(CXCursor c)
{
  return (int)(intptr_t)c.data[1] - 1;
}

static CXString nfc_string(const char *s)
{
  CXString r;
  r.data = s == NULL ? NULL : strdup(s);
  r.private_flags = 1;   /* owned: clang_disposeString frees it */
  return r;
}

static const char *nfc_kind_name(enum CXCursorKind kind)
{
  switch (kind) {
    case CXCursor_Namespace: return "Namespace";
    case CXCursor_FunctionTemplate: return "FunctionTemplate";
    case CXCursor_ClassTemplate: return "ClassTemplate";
    case CXCursor_StructDecl: return "StructDecl";
    case CXCursor_ClassDecl: return "ClassDecl";
    case CXCursor_UnionDecl: return "UnionDecl";
    case CXCursor_EnumDecl: return "EnumDecl";
    case CXCursor_EnumConstantDecl: return "EnumConstantDecl";
    case CXCursor_TypedefDecl: return "TypedefDecl";
    case CXCursor_FunctionDecl: return "FunctionDecl";
    case CXCursor_CXXMethod: return "CXXMethod";
    case CXCursor_Constructor: return "CXXConstructor";
    case CXCursor_Destructor: return "CXXDestructor";
    case CXCursor_VarDecl: return "VarDecl";
    case CXCursor_FieldDecl: return "FieldDecl";
    case CXCursor_ParmDecl: return "ParmDecl";
    case CXCursor_TranslationUnit: return "TranslationUnit";
    default: return "UnexposedDecl";
  }
}

/* The runner's kind word (be/nfcxx_decl.c) to a libclang cursor kind; 0 when unknown. */
static enum CXCursorKind nfc_kind_of_word(const char *w)
{
  static const struct { const char *word; enum CXCursorKind kind; } table[] = {
    {"namespace", CXCursor_Namespace}, {"struct", CXCursor_StructDecl}, {"class", CXCursor_ClassDecl},
    {"union", CXCursor_UnionDecl}, {"enum", CXCursor_EnumDecl}, {"enumerator", CXCursor_EnumConstantDecl},
    {"typedef", CXCursor_TypedefDecl}, {"function", CXCursor_FunctionDecl}, {"method", CXCursor_CXXMethod},
    {"constructor", CXCursor_Constructor}, {"destructor", CXCursor_Destructor}, {"var", CXCursor_VarDecl},
    {"field", CXCursor_FieldDecl}, {"param", CXCursor_ParmDecl},
    {"function_template", CXCursor_FunctionTemplate}, {"class_template", CXCursor_ClassTemplate},
  };
  size_t i;
  for (i = 0; i < sizeof table / sizeof table[0]; i++) {
    if (strcmp(table[i].word, w) == 0) return table[i].kind;
  }
  return 0;
}

/* Sort key for the children of a node: source position. */
static struct nfc_node *nfc_sort_nodes;
static int nfc_by_position(const void *a, const void *b)
{
  const struct nfc_node *x = &nfc_sort_nodes[*(const int *)a];
  const struct nfc_node *y = &nfc_sort_nodes[*(const int *)b];
  if (x->line != y->line) return x->line < y->line ? -1 : 1;
  if (x->col != y->col) return x->col < y->col ? -1 : 1;
  return *(const int *)a < *(const int *)b ? -1 : 1;
}

/* Build the child lists from the parent links. Children are kept in source order. */
static void nfc_link(CXTranslationUnit tu)
{
  int i, n = tu->count;
  int *order = malloc(sizeof(int) * (size_t)(n > 0 ? n : 1));
  int *fill;
  int slot;

  tu->kids = calloc((size_t)n + 1, sizeof(int *));
  tu->nkids = calloc((size_t)n + 1, sizeof(int));
  for (i = 0; i < n; i++) order[i] = i;
  nfc_sort_nodes = tu->nodes;
  qsort(order, (size_t)n, sizeof(int), nfc_by_position);
  for (i = 0; i < n; i++) {
    slot = tu->nodes[order[i]].parent < 0 ? n : tu->nodes[order[i]].parent;
    tu->nkids[slot]++;
  }
  for (slot = 0; slot <= n; slot++) {
    tu->kids[slot] = tu->nkids[slot] > 0 ? malloc(sizeof(int) * (size_t)tu->nkids[slot]) : NULL;
  }
  fill = calloc((size_t)n + 1, sizeof(int));
  for (i = 0; i < n; i++) {
    slot = tu->nodes[order[i]].parent < 0 ? n : tu->nodes[order[i]].parent;
    tu->kids[slot][fill[slot]++] = order[i];
  }
  free(fill);
  free(order);
}

static int nfc_shell_quote(char *dst, size_t size, const char *s)
{
  size_t used = 0;
  if (used + 2 >= size) return 0;
  dst[used++] = '\'';
  for (; *s != '\0'; s++) {
    if (*s == '\'') {
      if (used + 5 >= size) return 0;
      memcpy(dst + used, "'\\''", 4);
      used += 4;
    } else {
      if (used + 2 >= size) return 0;
      dst[used++] = *s;
    }
  }
  if (used + 2 >= size) return 0;
  dst[used++] = '\'';
  dst[used] = '\0';
  return 1;
}

/* The options the front end takes; anything else is left to the caller's compiler. */
static int nfc_front_end_option(const char *a)
{
  return strncmp(a, "-std=", 5) == 0 || strncmp(a, "-I", 2) == 0 || strncmp(a, "-D", 2) == 0 ||
         strncmp(a, "-U", 2) == 0;
}

/* Read the records of the front end from in into a new translation unit for file. */
static CXTranslationUnit nfc_read(FILE *in, const char *file)
{
  char *line = NULL;
  size_t cap = 0;
  ssize_t len;
  CXTranslationUnit tu;

  tu = calloc(1, sizeof *tu);
  tu->file = strdup(file);
  tu->count = 0;
  tu->nodes = NULL;
  while ((len = getline(&line, &cap, in)) != -1) {
    char *f[6], *s = line, *tab;
    int fi;
    int id, parent;
    if (len > 0 && line[len - 1] == '\n') line[len - 1] = '\0';
    for (fi = 0; fi < 5; fi++) {
      tab = strchr(s, '\t');
      if (tab == NULL) break;
      *tab = '\0';
      f[fi] = s;
      s = tab + 1;
    }
    if (fi < 5) continue;
    if (nfc_kind_of_word(f[0]) == 0) continue;  /* records for other consumers (sig: be/nfcxx_decl.c) */
    f[5] = s;
    id = atoi(f[1]);
    parent = atoi(f[2]);
    if (id < 1) continue;
    if (id > tu->count) {
      tu->nodes = realloc(tu->nodes, sizeof *tu->nodes * (size_t)id);
      memset(tu->nodes + tu->count, 0, sizeof *tu->nodes * (size_t)(id - tu->count));
      tu->count = id;
    }
    tu->nodes[id - 1].kind = nfc_kind_of_word(f[0]);
    tu->nodes[id - 1].parent = parent > 0 ? parent - 1 : -1;
    tu->nodes[id - 1].line = (unsigned)atoi(f[3]);
    tu->nodes[id - 1].col = (unsigned)atoi(f[4]);
    tu->nodes[id - 1].name = strdup(f[5]);
  }
  free(line);
  return tu;
}

static void nfc_free_tu(CXTranslationUnit tu)
{
  int i;
  for (i = 0; i < tu->count; i++) free(tu->nodes[i].name);
  free(tu->file);
  free(tu->nodes);
  free(tu);
}

/* Run the runner on the file with the options it understands, and read its records. NULL when it fails. */
static CXTranslationUnit nfc_run_process(const char *runner, const char *file, const char *const *args, int nargs)
{
  char cmd[65536], quoted[8192];
  size_t used;
  FILE *p;
  CXTranslationUnit tu;
  int i, status;

  if (!nfc_shell_quote(quoted, sizeof quoted, runner)) return NULL;
  used = (size_t)snprintf(cmd, sizeof cmd, "%s", quoted);
  for (i = 0; i < nargs; i++) {
    if (!nfc_front_end_option(args[i])) continue;
    if (!nfc_shell_quote(quoted, sizeof quoted, args[i])) return NULL;
    used += (size_t)snprintf(cmd + used, sizeof cmd - used, " %s", quoted);
  }
  if (!nfc_shell_quote(quoted, sizeof quoted, file)) return NULL;
  snprintf(cmd + used, sizeof cmd - used, " %s", quoted);

  p = popen(cmd, "r");
  if (p == NULL) return NULL;
  tu = nfc_read(p, file);
  status = pclose(p);
  if (status != 0) {
    nfc_free_tu(tu);
    return NULL;
  }
  nfc_link(tu);
  return tu;
}

#ifdef LIBCLANG_EDG_IN_PROCESS
static pthread_mutex_t nfc_front_end_lock = PTHREAD_MUTEX_INITIALIZER;

/* An absolute form of path (the front end runs with --wdir /, as scripts/libclang-cursors runs it): its realpath, or
   the current directory joined with it when it does not exist. NULL when out of memory. */
static char *nfc_absolute(const char *path)
{
  char cwd[PATH_MAX], *r = realpath(path, NULL), *out;
  if (r != NULL || path[0] == '/') return r != NULL ? r : strdup(path);
  if (getcwd(cwd, sizeof cwd) == NULL) return strdup(path);
  out = malloc(strlen(cwd) + strlen(path) + 2);
  if (out != NULL) sprintf(out, "%s/%s", cwd, path);
  return out;
}

/* Run the front end in this process, as scripts/libclang-cursors runs cpfe: the fixed options before and after the
   caller's -I/-D/-U (each -I made absolute), its -std=c++NN as --c++NN, then the file. NULL when it fails. */
static CXTranslationUnit nfc_run_in_process(const char *file, const char *const *args, int nargs)
{
  size_t nbefore = sizeof nfc_edg_before / sizeof nfc_edg_before[0];
  size_t nafter = sizeof nfc_edg_after / sizeof nfc_edg_after[0];
  size_t n = 0, size = 0, k;
  char **argv, **owned, *buf = NULL, std[64];
  FILE *out, *in;
  int i, nowned = 0, status;
  CXTranslationUnit tu;

  snprintf(std, sizeof std, "%s", NFC_EDG_STD);
  for (i = 0; i < nargs; i++) {
    if (strncmp(args[i], "-std=c++", 8) == 0) snprintf(std, sizeof std, "--c++%s", args[i] + 8);
  }
  argv = calloc(nbefore + nafter + (size_t)nargs + 4, sizeof *argv);
  owned = calloc((size_t)nargs + 2, sizeof *owned);
  if (argv == NULL || owned == NULL) {
    free(argv);
    free(owned);
    return NULL;
  }
  argv[n++] = (char *)"cpfe";
  for (k = 0; k < nbefore; k++) argv[n++] = (char *)nfc_edg_before[k];
  argv[n++] = std;
  for (i = 0; i < nargs; i++) {
    if (!nfc_front_end_option(args[i]) || strncmp(args[i], "-std=", 5) == 0) continue;
    if (strncmp(args[i], "-I", 2) == 0 && args[i][2] != '\0') {
      char *abs = nfc_absolute(args[i] + 2), *opt = abs ? malloc(strlen(abs) + 3) : NULL;
      if (opt != NULL) sprintf(opt, "-I%s", abs);
      free(abs);
      if (opt == NULL) continue;
      owned[nowned++] = opt;
      argv[n++] = opt;
    } else if (strcmp(args[i], "-I") != 0) {
      argv[n++] = (char *)args[i];
    }
  }
  for (k = 0; k < nafter; k++) argv[n++] = (char *)nfc_edg_after[k];
  owned[nowned] = nfc_absolute(file);
  argv[n++] = owned[nowned] != NULL ? owned[nowned] : (char *)file;
  nowned++;
  argv[n] = NULL;

  out = open_memstream(&buf, &size);
  if (out == NULL) {
    status = -1;
  } else {
    pthread_mutex_lock(&nfc_front_end_lock);
    status = nfcxx_edg_run((int)n, argv, out);
    pthread_mutex_unlock(&nfc_front_end_lock);
    fclose(out);
  }
  for (i = 0; i < nowned; i++) free(owned[i]);
  free(owned);
  free(argv);
  if (status != 0) {
    free(buf);
    return NULL;
  }
  in = size > 0 ? fmemopen(buf, size, "r") : NULL;
  if (in != NULL) {
    tu = nfc_read(in, file);
    fclose(in);
  } else {
    tu = calloc(1, sizeof *tu);
    tu->file = strdup(file);
  }
  free(buf);
  nfc_link(tu);
  return tu;
}
#endif

/* The front end on the file, in this process or through a runner (see the top of the file). */
static CXTranslationUnit nfc_run(const char *file, const char *const *args, int nargs)
{
  const char *runner = getenv("LIBCLANG_EDG_RUNNER");
  if (runner != NULL && runner[0] != '\0') return nfc_run_process(runner, file, args, nargs);
#ifdef LIBCLANG_EDG_IN_PROCESS
  return nfc_run_in_process(file, args, nargs);
#else
  return nfc_run_process(LIBCLANG_EDG_RUNNER_DEFAULT, file, args, nargs);
#endif
}

