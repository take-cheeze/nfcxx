/*
clang_edg.c -- a subset of libclang's C API, backed by the EDG front end.

clang_parseTranslationUnit runs the EDG front end with be/nfcxx_decl.c as its back end. That lists the declarations of
the main file, one per line, as

  KIND <TAB> ID <TAB> PARENT <TAB> LINE <TAB> COLUMN <TAB> NAME

and this file turns the list into a tree of cursors. Declarations only: no expressions, no types and no
references yet (see docs/notes/libclang-edg.md for what is implemented and what is not).

Two ways to run it:
- In-process (built with LIBCLANG_EDG_IN_PROCESS, the default of scripts/build-libclang-edg.sh when the front-end
  archive exists): the front end is linked into this library (be/nfcxx_edg_entry.c, nfcxx_edg_run) and called with
  the options scripts/libclang-cursors gives cpfe, fixed at build time (edg_args.h: the host's system include
  directories and GNU version, the base directory). No process and no shell per parse. The front end's state is
  global, so the calls are serialized; a crash of the front end is a crash of the client.
- A runner process: $LIBCLANG_EDG_RUNNER if set (always this way), else, in a library built without the archive, the
  path given at build time (LIBCLANG_EDG_RUNNER_DEFAULT), normally scripts/libclang-cursors. EDG's state stays out of
  the client's process, and a front-end crash shows up as a failed parse.
*/

